                HorizontalExpand = true,
                MinWidth = 0,
                ClipText = true,
                Align = Label.AlignMode.Left,
            };

            jobContainer.AddChild(jobLabel);

            ApplySensorRowStyle(sensorButton, selected);

            // Add user coordinates to the navmap
            if (coordinates != null && NavMap.Visible && _blipTexture != null)
            {
                var localCoords = CoordinatesToLocal(coordinates.Value);
                if (localCoords == null)
                    continue;

                // ADT-Tweak start
                var statusColorValue = GetStatusColor(sensor, out var isCriticalBlip);
                var seconds = _timing.RealTime.TotalSeconds;
                var blipBase = isCriticalBlip
                    ? GetCritBlinkColor(seconds)
                    : statusColorValue ?? Color.LimeGreen;
                var blipColor = (_trackedEntity == null || sensor.SuitSensorUid == _trackedEntity)
                    ? blipBase
                    : blipBase * Color.DimGray;
                // ADT-Tweak end
                NavMap.TrackedEntities.TryAdd(sensor.SuitSensorUid,
                    new NavMapBlip
                    (localCoords.Value,
                    _blipTexture,
                    blipColor, // ADT-Tweak
                    blinks: !isCriticalBlip && sensor.SuitSensorUid == _trackedEntity));

                NavMap.Focus = _trackedEntity;

                // On button up
                sensorButton.OnButtonUp += args =>
                {
                    var prevTrackedEntity = _trackedEntity;

                    if (_trackedEntity == sensor.SuitSensorUid)
                    {
                        _trackedEntity = null;
                    }

                    else
                    {
                        _trackedEntity = sensor.SuitSensorUid;
                        NavMap.CenterToCoordinates(coordinates.Value);
                    }

                    NavMap.Focus = _trackedEntity;

                    UpdateSensorsTable(_trackedEntity, prevTrackedEntity);
                };
            }
        }
    }

    // #ADT-Tweak End

    private void SetTrackedEntityFromNavMap(NetEntity? netEntity)
    {
        var prevTrackedEntity = _trackedEntity;
        _trackedEntity = netEntity;

        if (_trackedEntity == prevTrackedEntity)
            prevTrackedEntity = null;

        NavMap.Focus = _trackedEntity;
        _tryToScrollToListFocus = true;

        UpdateSensorsTable(_trackedEntity, prevTrackedEntity);
    }

    private void UpdateSensorsTable(NetEntity? currTrackedEntity, NetEntity? prevTrackedEntity)
    {
        foreach (var sensor in SensorsTable.Children)
        {
            if (sensor is not CrewMonitoringButton castSensor)
                continue;

            if (castSensor.SuitSensorUid == prevTrackedEntity)
            {
                ApplySensorRowStyle(castSensor, selected: false);
            }
            else if (castSensor.SuitSensorUid == currTrackedEntity)
            {
                ApplySensorRowStyle(castSensor, selected: true);
            }

            if (castSensor?.Coordinates == null)
                continue;

            if (NavMap.TrackedEntities.TryGetValue(castSensor.SuitSensorUid, out var data))
            {
                var localCoords = CoordinatesToLocal(data.Coordinates);
                if (localCoords == null)
                    continue;

                // ADT-Tweak start
                var seconds = _timing.RealTime.TotalSeconds;
                var blipBase = castSensor.IsCritical
                    ? GetCritBlinkColor(seconds)
                    : castSensor.StatusColor;
                var blipColor = (currTrackedEntity == null || castSensor.SuitSensorUid == currTrackedEntity)
                    ? blipBase
                    : blipBase * Color.DimGray;
                // ADT-Tweak end
                data = new NavMapBlip
                    (localCoords.Value,
                    data.Texture,
                    blipColor, // ADT-Tweak
                    blinks: !castSensor.IsCritical && castSensor.SuitSensorUid == currTrackedEntity);

                NavMap.TrackedEntities[castSensor.SuitSensorUid] = data;
            }
        }
    }

    private void TryToScrollToFocus()
    {
        if (!_tryToScrollToListFocus)
            return;

        if (TryGetNextScrollPosition(out float? nextScrollPosition))
        {
            SensorScroller.VScrollTarget = nextScrollPosition.Value;

            if (MathHelper.CloseToPercent(SensorScroller.VScroll, SensorScroller.VScrollTarget))
            {
                _tryToScrollToListFocus = false;
                return;
            }
        }
    }

    private bool TryGetNextScrollPosition([NotNullWhen(true)] out float? nextScrollPosition)
    {
        nextScrollPosition = 0;

        foreach (var sensor in SensorsTable.Children)
        {
            if (sensor is CrewMonitoringButton sensorButton &&
                sensorButton.SuitSensorUid == _trackedEntity)
                return true;

            nextScrollPosition += sensor.Height;
        }

        // Failed to find control
        nextScrollPosition = null;

        return false;
    }

    /// <summary>
    /// Keeps each marker in its native coordinate frame. The radar converts
    /// every marker through map space, so moving grids and open space remain
    /// valid without re-parenting everything to the selected station grid.
    /// </summary>
    // #ADT-Tweak Start - New Monitor: nullable CoordinatesToLocal
    private EntityCoordinates? CoordinatesToLocal(EntityCoordinates refCoords)
    {
        if (!refCoords.IsValid(_entManager))
            return null;

        return refCoords;
    }
    // #ADT-Tweak End

    // ADT-Tweak start
    private Color? GetStatusColor(SuitSensorStatus sensor, out bool isCritical)
    {
        // Badge/blink "КРИТ." only for MobState.Critical (unconscious).
        // High DamagePercentage while still Alive uses health0..health4, not crit.
        isCritical = sensor.IsAlive && sensor.IsCritical;

        if (!sensor.IsAlive)
            return sensor.Coordinates == null ? null : Color.Gray;

        if (isCritical)
            return CritBlinkA;

        if (sensor.Coordinates == null)
            return null;

        if (sensor.DamagePercentage != null && sensor.DamagePercentage.Value >= 0.5f)
            return Color.Gold;

        return Color.LimeGreen;
    }
    // ADT-Tweak end

    private void ClearOutDatedData()
    {
        SensorsTable.RemoveAllChildren();
        NavMap.TrackedCoordinates.Clear();
        NavMap.TrackedEntities.Clear();
        NavMap.LocalizedNames.Clear();
        NavMap.SensorRangeCenter = null;
        NavMap.SensorRange = 0f;
    }
