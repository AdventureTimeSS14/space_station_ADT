using Content.Shared.ADT.Mech.EntitySystems;
using Content.Shared.ADT.Weapons.Ranged.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.ADT.Mech.UI;

[GenerateTypedNameReferences]
public sealed partial class MechGunUiFragment : BoxContainer
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IGameTiming _timing = default!;

    public event Action? ReloadAction;
    public EntityUid? FragmentOwner;

    public MechGunUiFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ReloadButton.OnPressed += _ => ReloadAction?.Invoke();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_entManager.TryGetComponent<BallisticMechAmmoProviderComponent>(FragmentOwner, out var ammo))
            return;

        var reload = _entManager.System<MechGunReloadSystem>();
        if (reload.IsReloading(ammo))
        {
            var left = Math.Max(0, (ammo.ReloadEnd - _timing.CurTime).TotalSeconds);
            ShotsCount.Text = Loc.GetString("adt-mech-gun-ui-reloading-time", ("time", left.ToString("0.0")));
            ReloadButton.Disabled = true;
            return;
        }

        var shots = ammo.Shots + ammo.PendingRounds;
        ShotsCount.Text = $"{shots} / {ammo.Capacity}";
        ReloadButton.Disabled = shots >= ammo.Capacity;
    }
}
