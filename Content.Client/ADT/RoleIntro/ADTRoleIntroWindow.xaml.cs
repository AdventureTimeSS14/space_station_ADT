using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.RoleIntro;
using Robust.Client.Player;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.ADT.RoleIntro;

[GenerateTypedNameReferences]
public sealed partial class ADTRoleIntroWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IPlayerManager _player = default!;

    private float _timer;

    public ADTRoleIntroWindow(string title, string text, TimeSpan lockTime)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Title = title;
        IntroText.SetMessage(FormattedMessage.FromMarkupPermissive(text));

        _timer = (float) lockTime.TotalSeconds;
        CloseButton.Visible = false;
        UpdateButton();

        AcceptButton.OnPressed += _ => Close();
    }

    private bool Locked => _timer > 0f;

    public override void Close()
    {
        if (Locked && _entMan.HasComponent<ADTRoleIntroComponent>(_player.LocalEntity))
            return;

        base.Close();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!Locked)
            return;

        _timer = MathF.Max(0f, _timer - args.DeltaSeconds);
        UpdateButton();
    }

    private void UpdateButton()
    {
        if (Locked)
        {
            AcceptButton.Disabled = true;
            AcceptButton.Text = Loc.GetString("adt-role-intro-accept-timer", ("time", (int) MathF.Ceiling(_timer)));
            return;
        }

        AcceptButton.Disabled = false;
        AcceptButton.Text = Loc.GetString("adt-role-intro-accept");
        CloseButton.Visible = true;
    }
}
