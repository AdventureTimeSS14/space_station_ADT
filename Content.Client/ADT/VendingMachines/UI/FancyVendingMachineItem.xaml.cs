using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.ADT.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class FancyVendingMachineItem : PanelContainer
{
    private const int MaxSelectable = 5;

    private static readonly StyleBoxFlat StripeBox = new() { BackgroundColor = Color.FromHex("#1F1F23") };

    private static readonly Color ButtonBackground = Color.FromHex("#2E2E36");
    private static readonly Color ButtonHovered = Color.FromHex("#383840");
    private static readonly Color ButtonDisabled = Color.FromHex("#222228");
    private static readonly Color ButtonBorder = Color.FromHex("#4A4A52");

    public Action? BuyPressed;

    private int _unitPrice;
    private StyleBoxFlat _buyBox = new();

    public int SelectedAmount => AmountSelector.SelectedId + 1;

    public FancyVendingMachineItem(EntProtoId entProto, string text, uint count, uint maxAmount, int price, bool striped)
    {
        RobustXamlLoader.Load(this);
        BuyButton.OnPressed += _ => BuyPressed?.Invoke();

        _unitPrice = price;

        EntryPanel.PanelOverride = striped ? StripeBox : null;

        ItemPrototype.SetPrototype(entProto);

        NameLabel.Text = text;

        _buyBox = (StyleBoxFlat) BuyPanel.PanelOverride!;
        BuyButton.OnMouseEntered += _ => _buyBox.BackgroundColor = BuyButton.Disabled ? ButtonDisabled : ButtonHovered;
        BuyButton.OnMouseExited += _ => _buyBox.BackgroundColor = BuyButton.Disabled ? ButtonDisabled : ButtonBackground;

        AmountSelector.StyleBoxOverride = MakeFlatButtonStyle(AmountSelector);

        AmountSelector.OnItemSelected += args =>
        {
            AmountSelector.SelectId(args.Id);
            UpdateCost();
        };

        UpdateCount(count, maxAmount);
        SetupInfoTooltip(entProto, text);
    }

    private static StyleBoxFlat MakeFlatButtonStyle(BaseButton button)
    {
        var box = new StyleBoxFlat
        {
            BackgroundColor = ButtonBackground,
            BorderColor = ButtonBorder,
            BorderThickness = new Thickness(1),
        };

        button.ModulateSelfOverride = Color.White;
        button.OnMouseEntered += _ => box.BackgroundColor = button.Disabled ? ButtonDisabled : ButtonHovered;
        button.OnMouseExited += _ => box.BackgroundColor = button.Disabled ? ButtonDisabled : ButtonBackground;

        return box;
    }

    private void SetupInfoTooltip(EntProtoId entProto, string text)
    {
        if (!IoCManager.Resolve<IPrototypeManager>().TryIndex(entProto, out EntityPrototype? proto))
            return;

        var msg = new FormattedMessage();
        msg.AddText(text);

        if (!string.IsNullOrWhiteSpace(proto.Description))
        {
            msg.PushNewline();
            msg.AddText(proto.Description);
        }

        var tooltip = new Tooltip();
        tooltip.SetMessage(msg);
        tooltip.MaxWidth = 250f;

        InfoButton.ToolTip = proto.Description;
        InfoButton.TooltipDelay = 0;
        InfoButton.TooltipSupplier = _ => tooltip;
    }

    public void UpdateCount(uint count, uint maxAmount)
    {
        var color = count <= 0 ? "red" : maxAmount > 0 && count <= maxAmount / 2 ? "yellow" : "green";
        CountLabel.SetMarkup(Loc.GetString("vending-machine-ui-count", ("count", count), ("color", $"[color={color}]")));

        var maxChoice = count <= 0 ? 1 : Math.Min(MaxSelectable, (int) count);
        if (AmountSelector.ItemCount != maxChoice)
        {
            var selected = Math.Clamp(AmountSelector.SelectedId + 1, 1, maxChoice);
            AmountSelector.Clear();
            for (var i = 1; i <= maxChoice; i++)
                AmountSelector.AddItem(i.ToString());
            AmountSelector.SelectId(selected - 1);
        }

        UpdateCost();

        Modulate = count <= 0 ? new Color(1f, 1f, 1f, 0.5f) : Color.White;
    }

    private void UpdateCost()
    {
        var total = _unitPrice * SelectedAmount;
        CostLabel.SetMarkup(total <= 0
            ? Loc.GetString("vending-machine-ui-price-free")
            : Loc.GetString("vending-machine-ui-price", ("price", total)));
    }

    public void SetBuyDisabled(bool disabled)
    {
        BuyButton.Disabled = disabled;
        _buyBox.BackgroundColor = disabled ? ButtonDisabled : ButtonBackground;
    }
}