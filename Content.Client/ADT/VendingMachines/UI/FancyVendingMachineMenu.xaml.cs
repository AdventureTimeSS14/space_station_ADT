using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client.ADT.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class FancyVendingMachineMenu : FancyWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;
    [Dependency] private readonly IComponentFactory _componentFactory = default!;

    private readonly Dictionary<string, Color?> _paintColors = [];
    private List<FancyVendingMachineData> _cachedItems = [];

    private static readonly StyleBoxFlat ItemButtonBox = new() { BackgroundColor = Color.Transparent };

    /// <summary>
    /// Whether the vending machine is able to be interacted with or not.
    /// </summary>
    private bool _enabled = true;

    private bool _closed;

    private double _priceMultiplier = 1;
    private int _machineCredits;
    private int _userBalance;
    private string? _selectedCategory;
    private Label? _emptyLabel;

    public event Action<VendingMachineInventoryEntry, int, Color?>? OnItemSelected;
    public Action? OnWithdraw;

    private static readonly VendingCategoryInfo ContrabandCategory = new(
        "vending-contraband", Loc.GetString("vending-category-contraband"), "CigPackGreen");

    private static readonly VendingCategoryInfo EmaggedCategory = new(
        "vending-emagged", Loc.GetString("vending-category-emagged"), "Emag");

    private static readonly VendingCategoryInfo MiscCategory = new(
        "vending-misc", Loc.GetString("vending-category-misc"), "BoxCardboard");

    public FancyVendingMachineMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        VendingContents.GenerateItem = GenerateItem;

        SearchBar.OnTextChanged += _ => ApplyFilter();
        WithdrawButton.OnPressed += _ => OnWithdraw?.Invoke();
    }

    private void GenerateItem(ListData data, ListContainerButton button)
    {
        if (data is not FancyVendingMachineData itemData)
            return;

        button.StyleBoxOverride = ItemButtonBox;
        button.MouseFilter = MouseFilterMode.Ignore;
        button.AddChild(CreateItem(itemData, button.Index % 2 == 1));
    }

    public void SetUserInfo(int balance, bool ignoreBalance = false)
    {
        if (_closed || Disposed)
            return;

        _userBalance = ignoreBalance ? int.MaxValue : balance;
        UserBalanceLabel.Text = ignoreBalance
            ? Loc.GetString("vending-user-balance-admin")
            : Loc.GetString("vending-user-balance", ("balance", balance));

        UpdateVisibleItems();
    }

    /// <summary>
    /// Обновляет количества и доступность покупки на месте, без пересоздания списка.
    /// </summary>
    public void UpdateAmounts(List<VendingMachineInventoryEntry> cachedInventory, bool enabled)
    {
        if (_closed || Disposed)
            return;

        _enabled = enabled;

        foreach (var cached in _cachedItems)
        {
            if (!cachedInventory.TryFirstOrDefault(o => o.ID == cached.Entry.ID, out var entry))
                continue;

            cached.Entry.Amount = entry.Amount;
        }

        UpdateVisibleItems();
    }

    private void UpdateVisibleItems()
    {
        foreach (var child in VendingContents.Children)
        {
            if (child is not ListContainerButton button || button.Data is not FancyVendingMachineData data)
                continue;

            if (button.Children.FirstOrDefault() is not FancyVendingMachineItem item)
                continue;

            item.UpdateData(data.Name, data.Entry.Amount, data.Entry.MaxAmount, GetPrice(data.Entry));
            UpdateItemDisabled(data, item);
        }
    }

    private void UpdateItemDisabled(FancyVendingMachineData data, FancyVendingMachineItem item)
    {
        var price = GetPrice(data.Entry);
        var total = price * item.SelectedAmount;

        item.SetBuyDisabled(!_enabled || data.Entry.Amount == 0 ||
                            total > 0 && _machineCredits < total && _userBalance < total);
    }

    public override void Close()
    {
        if (_closed)
            return;

        _closed = true;
        base.Close();
        Cleanup();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            Cleanup();

        base.Dispose(disposing);
    }

    private void Cleanup()
    {
        _colorWindow?.Close();
        _colorWindow = null;

        if (_pickerDummy is { } dummy)
        {
            _entityManager.DeleteEntity(dummy);
            _pickerDummy = null;
        }
    }

    /// <summary>
    /// Populates the list of available items on the vending machine interface
    /// and sets icons based on their prototypes
    /// </summary>
    public void Populate(EntityUid entityUid, List<VendingMachineInventoryEntry> inventory, double priceMultiplier, int credits)
    {
        if (_closed || Disposed)
            return;

        var comp = _entityManager.GetComponentOrNull<VendingMachineComponent>(entityUid);
        _priceMultiplier = comp == null || comp.AllForFree ? 0 : priceMultiplier;
        _machineCredits = credits;

        CreditsLabel.Text = Loc.GetString("vending-ui-credits-amount", ("credits", credits));
        WithdrawButton.Disabled = credits == 0;

        if (_emptyLabel != null)
        {
            MainContainer.RemoveChild(_emptyLabel);
            _emptyLabel = null;
        }

        if (inventory.Count == 0)
        {
            SearchBar.Visible = false;
            VendingContents.Visible = false;
            CategoryBarPanel.Visible = false;
            VendingContents.PopulateList([]);
            _cachedItems.Clear();

            _emptyLabel = new Label()
            {
                Text = Loc.GetString("vending-machine-component-try-eject-out-of-stock"),
                Margin = new Thickness(4, 8),
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Center
            };

            MainContainer.AddChild(_emptyLabel);
            return;
        }

        SearchBar.Visible = true;
        VendingContents.Visible = true;

        if (HasStructuralChange(inventory))
        {
            _cachedItems = BuildItems(inventory);
            BuildCategoryBar();
            ApplyFilter();
            return;
        }

        for (var i = 0; i < inventory.Count; i++)
        {
            var old = _cachedItems[i];
            var next = inventory[i];
            old.Entry.Amount = next.Amount;
            old.Entry.Price = next.Price;
            old.Entry.MaxAmount = next.MaxAmount;
        }

        UpdateVisibleItems();
    }

    private List<FancyVendingMachineData> BuildItems(List<VendingMachineInventoryEntry> inventory)
    {
        var items = new List<FancyVendingMachineData>(inventory.Count);
        foreach (var entry in inventory)
        {
            _prototypeManager.TryIndex<EntityPrototype>(entry.ID, out var proto);
            items.Add(new FancyVendingMachineData(GetItemName(proto, entry.ID), entry, GetCategoryId(entry), proto));
        }

        return items;
    }

    private bool HasStructuralChange(List<VendingMachineInventoryEntry> inventory)
    {
        if (_cachedItems.Count != inventory.Count)
            return true;

        for (var i = 0; i < inventory.Count; i++)
        {
            var old = _cachedItems[i];
            var next = inventory[i];
            if (old.Entry.ID != next.ID || old.Entry.Type != next.Type || old.CategoryId != GetCategoryId(next))
                return true;
        }

        return false;
    }

    private string GetItemName(EntityPrototype? proto, string id)
    {
        if (proto == null || string.IsNullOrEmpty(proto.Name))
            return id;

        var name = new StringBuilder(proto.Name);
        if (name.Length > 0)
            name[0] = char.ToUpper(name[0]);

        return name.ToString();
    }

    private bool IsPaintable(EntityPrototype? proto)
    {
        return proto != null && proto.TryGetComponent<ClothingComponent>(out _, _componentFactory);
    }

    private int GetPrice(VendingMachineInventoryEntry entry)
    {
        return (int)(entry.Price * _priceMultiplier);
    }

    private void ApplyFilter()
    {
        VendingContents.PopulateList(_cachedItems.Where(FilterItem).ToList());
    }

    private FancyVendingMachineItem CreateItem(FancyVendingMachineData data, bool striped)
    {
        var canPaint = IsPaintable(data.Proto);

        var listItem = new FancyVendingMachineItem(
            data.Proto, data.Name, data.Entry.Amount,
            data.Entry.MaxAmount, GetPrice(data.Entry), striped, canPaint);

        if (_paintColors.TryGetValue(data.Entry.ID, out var savedColor))
            listItem.SetPaintColor(savedColor);

        UpdateItemDisabled(data, listItem);
        listItem.BuyPressed += () => OnItemSelected?.Invoke(data.Entry, listItem.SelectedAmount, listItem.PaintColor);
        listItem.OnAmountChanged += () => UpdateItemDisabled(data, listItem);

        if (canPaint)
            listItem.ColorPressed += () => OpenColorWindow(data.Entry, listItem);

        return listItem;
    }

    private void BuildCategoryBar()
    {
        CategoryBar.RemoveAllChildren();

        var categories = _cachedItems
            .Select(item => item.CategoryId)
            .Distinct()
            .Select(GetCategoryInfo)
            .ToList();

        var hasSpecial = categories.Any(c => c.Id == ContrabandCategory.Id || c.Id == EmaggedCategory.Id);
        if (categories.Count == 0 || (categories.Count == 1 && !hasSpecial))
        {
            CategoryBarPanel.Visible = false;
            _selectedCategory = null;
            return;
        }

        if (_selectedCategory != null && categories.All(c => c.Id != _selectedCategory))
            _selectedCategory = null;

        categories.Sort(CompareCategories);

        CategoryBarPanel.Visible = true;

        foreach (var category in categories)
        {
            var button = new Button
            {
                Margin = new Thickness(4, 2),
                StyleBoxOverride = GetCategoryButtonStyle(category.Id == _selectedCategory),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(8, 4),
            };

            if (!string.IsNullOrEmpty(category.IconProto) &&
                _prototypeManager.TryIndex<EntityPrototype>(category.IconProto, out var iconProto))
            {
                var icon = new VendingItemIcon
                {
                    MinSize = new Vector2(29, 29),
                    Margin = new Thickness(0, 0, 6, 0),
                };
                icon.SetPrototype(iconProto);
                content.AddChild(icon);
            }

            content.AddChild(new Label
            {
                Text = category.Name,
                VerticalAlignment = VAlignment.Center,
            });

            button.AddChild(content);

            button.OnPressed += _ =>
            {
                _selectedCategory = _selectedCategory == category.Id ? null : category.Id;
                BuildCategoryBar();
                ApplyFilter();
            };

            CategoryBar.AddChild(button);
        }
    }

    private static StyleBox GetCategoryButtonStyle(bool selected)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = selected ? Color.FromHex("#2A2A2E") : Color.Transparent,
            BorderColor = selected ? Color.FromHex("#4A4A52") : Color.Transparent,
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 0,
            ContentMarginRightOverride = 0,
        };
    }

    private static int CompareCategories(VendingCategoryInfo left, VendingCategoryInfo right)
    {
        if (left.Priority != right.Priority)
            return left.Priority.CompareTo(right.Priority);

        return string.Compare(left.Name, right.Name, StringComparison.CurrentCultureIgnoreCase);
    }

    private string GetCategoryId(VendingMachineInventoryEntry entry)
    {
        if (entry.Type == InventoryType.Contraband)
            return ContrabandCategory.Id;

        if (entry.Type == InventoryType.Emagged)
            return EmaggedCategory.Id;

        if (entry.Category != null)
            return entry.Category;

        return MiscCategory.Id;
    }

    private VendingCategoryInfo GetCategoryInfo(string id)
    {
        if (id == ContrabandCategory.Id)
            return ContrabandCategory;

        if (id == EmaggedCategory.Id)
            return EmaggedCategory;

        if (id == MiscCategory.Id)
            return MiscCategory;

        if (_prototypeManager.TryIndex<VendingMachineCategoryPrototype>(id, out var category))
            return new VendingCategoryInfo(category.ID, Loc.GetString(category.Name), category.Icon, category.Priority);

        return MiscCategory;
    }

    private bool FilterItem(FancyVendingMachineData item)
    {
        if (!string.IsNullOrEmpty(SearchBar.Text))
            return item.Name.Contains(SearchBar.Text, StringComparison.CurrentCultureIgnoreCase);

        if (_selectedCategory != null)
            return item.CategoryId == _selectedCategory;

        return true;
    }

    private ClothingColorWindow? _colorWindow;
    private EntityUid? _pickerDummy;

    private void OpenColorWindow(VendingMachineInventoryEntry entry, FancyVendingMachineItem listItem)
    {
        if (_closed || Disposed)
            return;

        _colorWindow?.Close();
        _colorWindow = new ClothingColorWindow
        {
            Title = Loc.GetString("vending-paint-window-title"),
        };

        _entityManager.DeleteEntity(_pickerDummy);
        _pickerDummy = _entityManager.Spawn(entry.ID);
        _colorWindow.SetDummy(_pickerDummy.Value);

        if (listItem.PaintColor is { } color)
            _colorWindow.SetColor(color);

        _colorWindow.OnColorChanged += color =>
        {
            listItem.SetPaintColor(color);
            _paintColors[entry.ID] = color;
        };
        _colorWindow.OnClose += () =>
        {
            _entityManager.DeleteEntity(_pickerDummy);
            _pickerDummy = null;
            _colorWindow.Dispose();
            _colorWindow = null;
        };
        _colorWindow.OpenCentered();
    }

    private sealed record FancyVendingMachineData(string Name, VendingMachineInventoryEntry Entry, string CategoryId, EntityPrototype? Proto) : ListData;

    private record struct VendingCategoryInfo(string Id, string Name, string IconProto, int Priority = 100);
}

