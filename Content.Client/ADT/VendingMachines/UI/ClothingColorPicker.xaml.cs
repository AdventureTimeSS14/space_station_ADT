using System.Collections.Generic;
using System.Numerics;
using Content.Shared.ADT.VendingMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Maths;

namespace Content.Client.ADT.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class ClothingColorPicker : Control
{
    [Dependency] private readonly IEntityManager _entMan = default!;

    public event Action<Color?>? OnColorChanged;

    private EntityUid? _dummy;
    private readonly List<(int Index, Color Color)> _originalColors = new();

    private bool _updating;
    private ColorMode _mode = ColorMode.Rgb;
    private Color _currentColor = Color.White;

    private static readonly float[] HsvScale = [360f, 100f, 100f];
    private static readonly float[] RgbScale = [255f, 255f, 255f];
    private float[] Scale => _mode == ColorMode.Hsv ? HsvScale : RgbScale;

    private ColorableSlider _topSlider = default!;
    private ColorableSlider _middleSlider = default!;
    private ColorableSlider _bottomSlider = default!;
    private ColorSelectorStyleBox _topStyle = default!;
    private ColorSelectorStyleBox _middleStyle = default!;
    private ColorSelectorStyleBox _bottomStyle = default!;
    private SpinBox _topInput = default!;
    private SpinBox _middleInput = default!;
    private SpinBox _bottomInput = default!;
    private Label _topLabel = default!;
    private Label _middleLabel = default!;
    private Label _bottomLabel = default!;

    private enum ColorMode
    {
        Rgb,
        Hsv,
        Hex,
    }

    public Color CurrentColor => _currentColor;

    public ClothingColorPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        RgbModeButton.OnPressed += _ => SetMode(ColorMode.Rgb);
        HsvModeButton.OnPressed += _ => SetMode(ColorMode.Hsv);
        HexModeButton.OnPressed += _ => SetMode(ColorMode.Hex);

        HexInput.OnTextEntered += args =>
        {
            if (Color.TryParse(args.Text, out var color))
                SetColor(color);
        };

        ResetButton.OnPressed += _ => ResetColor();

        BuildSliders();
        SetMode(ColorMode.Rgb);
    }

    public void SetDummy(EntityUid? dummy)
    {
        _dummy = dummy;
        Preview.SetEntity(dummy);
        SaveOriginalColors();
    }

    public void SetColor(Color color)
    {
        _currentColor = color;
        UpdateSliders(color);
        UpdateHex(color);
        UpdatePreview(color);
        UpdatePreviewHex(color);
        OnColorChanged?.Invoke(color);
    }

    private void SetMode(ColorMode mode)
    {
        _mode = mode;

        RgbModeButton.Pressed = mode == ColorMode.Rgb;
        HsvModeButton.Pressed = mode == ColorMode.Hsv;
        HexModeButton.Pressed = mode == ColorMode.Hex;

        SlidersPanel.Visible = mode != ColorMode.Hex;
        HexPanel.Visible = mode == ColorMode.Hex;

        _updating = true;

        if (mode == ColorMode.Hsv)
        {
            _topLabel.Text = Loc.GetString("vending-paint-hue");
            _middleLabel.Text = Loc.GetString("vending-paint-saturation");
            _bottomLabel.Text = Loc.GetString("vending-paint-value");

            _topStyle.ConfigureSlider(ColorSelectorStyleBox.ColorSliderPreset.Hue);
            _middleStyle.ConfigureSlider(ColorSelectorStyleBox.ColorSliderPreset.Saturation);
            _bottomStyle.ConfigureSlider(ColorSelectorStyleBox.ColorSliderPreset.Value);
        }
        else
        {
            _topLabel.Text = Loc.GetString("vending-paint-red");
            _middleLabel.Text = Loc.GetString("vending-paint-green");
            _bottomLabel.Text = Loc.GetString("vending-paint-blue");

            _topStyle.ConfigureSlider(ColorSelectorStyleBox.ColorSliderPreset.Red);
            _middleStyle.ConfigureSlider(ColorSelectorStyleBox.ColorSliderPreset.Green);
            _bottomStyle.ConfigureSlider(ColorSelectorStyleBox.ColorSliderPreset.Blue);
        }

        var scale = Scale;
        _topSlider.MaxValue = scale[0];
        _middleSlider.MaxValue = scale[1];
        _bottomSlider.MaxValue = scale[2];

        _topInput.IsValid = v => v >= 0 && v <= scale[0];
        _middleInput.IsValid = v => v >= 0 && v <= scale[1];
        _bottomInput.IsValid = v => v >= 0 && v <= scale[2];

        _updating = false;

        // Слайдеры инертны и не перерисуются сами после смены градиента
        _topSlider.UpdateDraw();
        _middleSlider.UpdateDraw();
        _bottomSlider.UpdateDraw();

        UpdateSliders(_currentColor);
    }

    private void BuildSliders()
    {
        _topStyle = new ColorSelectorStyleBox();
        _middleStyle = new ColorSelectorStyleBox();
        _bottomStyle = new ColorSelectorStyleBox();

        (_topSlider, _topInput, _topLabel) = BuildSliderRow(_topStyle);
        (_middleSlider, _middleInput, _middleLabel) = BuildSliderRow(_middleStyle);
        (_bottomSlider, _bottomInput, _bottomLabel) = BuildSliderRow(_bottomStyle);
    }

    private (ColorableSlider, SpinBox, Label) BuildSliderRow(ColorSelectorStyleBox style)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };

        var label = new Label { MinSize = new Vector2(90, 0), VerticalAlignment = VAlignment.Center };
        row.AddChild(label);

        var slider = new ColorableSlider
        {
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            BackgroundStyleBoxOverride = style,
        };
        row.AddChild(slider);

        var input = new SpinBox { MinSize = new Vector2(56, 0), VerticalAlignment = VAlignment.Center };
        input.InitDefaultButtons();
        row.AddChild(input);

        SlidersBox.AddChild(row);

        slider.OnValueChanged += _ => OnSliderChanged();
        input.ValueChanged += _ => OnInputChanged();

        return (slider, input, label);
    }

    private void OnSliderChanged()
    {
        if (_updating)
            return;

        SetColor(CurrentSliderColor());
    }

    private void OnInputChanged()
    {
        if (_updating)
            return;

        SetColor(CurrentInputColor());
    }

    private Color CurrentInputColor()
    {
        var scale = Scale;

        if (_mode == ColorMode.Hsv)
            return Color.FromHsv(new Vector4(_topInput.Value / scale[0], _middleInput.Value / scale[1], _bottomInput.Value / scale[2], 1f));

        return new Color(_topInput.Value / scale[0], _middleInput.Value / scale[1], _bottomInput.Value / scale[2]);
    }

    private Color CurrentSliderColor()
    {
        var scale = Scale;

        if (_mode == ColorMode.Hsv)
            return Color.FromHsv(new Vector4(_topSlider.Value / scale[0], _middleSlider.Value / scale[1], _bottomSlider.Value / scale[2], 1f));

        return new Color(_topSlider.Value / scale[0], _middleSlider.Value / scale[1], _bottomSlider.Value / scale[2]);
    }

    private void UpdateSliders(Color color)
    {
        if (_updating)
            return;

        _updating = true;

        var scale = Scale;
        var (top, middle, bottom) = _mode == ColorMode.Hsv
            ? (Color.ToHsv(color).X, Color.ToHsv(color).Y, Color.ToHsv(color).Z)
            : (color.R, color.G, color.B);

        _topSlider.SetValueWithoutEvent(top * scale[0]);
        _middleSlider.SetValueWithoutEvent(middle * scale[1]);
        _bottomSlider.SetValueWithoutEvent(bottom * scale[2]);

        _topInput.OverrideValue((int)(top * scale[0]));
        _middleInput.OverrideValue((int)(middle * scale[1]));
        _bottomInput.OverrideValue((int)(bottom * scale[2]));

        _topStyle.SetBaseColor(color);
        _middleStyle.SetBaseColor(color);
        _bottomStyle.SetBaseColor(color);

        _updating = false;
    }

    private void UpdateHex(Color color)
    {
        HexInput.Text = color.ToHexNoAlpha();
    }

    private void UpdatePreview(Color color)
    {
        if (_dummy is not { } dummy || !_entMan.TryGetComponent(dummy, out SpriteComponent? sprite))
            return;

        _entMan.TryGetComponent(dummy, out ADTClothingPaintComponent? paint);
        var spriteSystem = _entMan.System<SpriteSystem>();
        var i = 0;
        foreach (var layer in sprite.AllLayers)
        {
            if (ADTClothingPaintSystem.IsPaintable(paint, layer))
                spriteSystem.LayerSetColor((dummy, sprite), i, color);

            i++;
        }

        Preview.UpdateDraw();
    }

    private void UpdatePreviewHex(Color color)
    {
        PreviewHexLabel.Text = color.ToHexNoAlpha();
    }

    private void ResetColor()
    {
        _currentColor = Color.White;
        UpdateSliders(Color.White);
        UpdateHex(Color.White);
        UpdatePreviewHex(Color.White);
        RestoreOriginalColors();
        OnColorChanged?.Invoke(null);
    }

    private void SaveOriginalColors()
    {
        _originalColors.Clear();

        if (_dummy is not { } dummy || !_entMan.TryGetComponent(dummy, out SpriteComponent? sprite))
            return;

        var i = 0;
        foreach (var layer in sprite.AllLayers)
        {
            if (layer.RsiState.IsValid)
                _originalColors.Add((i, layer.Color));

            i++;
        }
    }

    private void RestoreOriginalColors()
    {
        if (_dummy is not { } dummy || !_entMan.TryGetComponent(dummy, out SpriteComponent? sprite))
            return;

        var spriteSystem = _entMan.System<SpriteSystem>();
        foreach (var (index, color) in _originalColors)
        {
            spriteSystem.LayerSetColor((dummy, sprite), index, color);
        }

        Preview.UpdateDraw();
    }
}