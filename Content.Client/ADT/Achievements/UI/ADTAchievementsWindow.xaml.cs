using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.Achievements;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.Achievements.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTAchievementsWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly Dictionary<string, BoxContainer> _tabs = new();

    private IReadOnlyDictionary<string, ADTAchievementState> _states =
        new Dictionary<string, ADTAchievementState>();

    public ADTAchievementsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        HideUnlockedButton.OnToggled += _ => Refresh();

        BuildTabs();
    }

    private void BuildTabs()
    {
        var categories = _prototype.EnumeratePrototypes<ADTAchievementCategoryPrototype>()
            .OrderBy(c => c.Priority)
            .ThenBy(c => c.ID)
            .ToList();

        var index = 0;

        foreach (var category in categories)
        {
            var list = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                Margin = new Thickness(4),
            };

            var scroll = new ScrollContainer
            {
                HorizontalExpand = true,
                VerticalExpand = true,
                HScrollEnabled = false,
            };

            scroll.AddChild(list);
            Categories.AddChild(scroll);
            Categories.SetTabTitle(index++, Loc.GetString(category.Name));

            _tabs[category.ID] = list;
        }
    }

    public void UpdateState(IReadOnlyDictionary<string, ADTAchievementState> states)
    {
        _states = states;
        Refresh();
    }

    private void Refresh()
    {
        foreach (var list in _tabs.Values)
        {
            list.RemoveAllChildren();
        }

        var unlocked = 0;
        var total = 0;
        var points = 0;
        var earned = 0;

        var achievements = _prototype.EnumeratePrototypes<ADTAchievementPrototype>()
            .OrderBy(a => a.Priority)
            .ThenBy(a => a.ID);

        foreach (var achievement in achievements)
        {
            var state = _states.GetValueOrDefault(achievement.ID);

            total++;
            points += achievement.Points;

            if (state.Unlocked)
            {
                unlocked++;
                earned += achievement.Points;
            }

            if (!_tabs.TryGetValue(achievement.Category, out var list))
                continue;

            if (HideUnlockedButton.Pressed && state.Unlocked)
                continue;

            list.AddChild(new ADTAchievementEntry(achievement, state));
        }

        SummaryLabel.Text = Loc.GetString("adt-achievements-summary",
            ("unlocked", unlocked),
            ("total", total),
            ("earned", earned),
            ("points", points));
    }
}
