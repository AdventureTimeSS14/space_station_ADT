using Content.Shared.ADT.Achievements;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Utility;

namespace Content.Client.ADT.Achievements.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTAchievementEntry : PanelContainer
{
    private static readonly Color UnlockedColor = new(0.18f, 0.26f, 0.18f);
    private static readonly Color LockedColor = new(0.14f, 0.14f, 0.16f);

    public ADTAchievementEntry(ADTAchievementPrototype achievement, ADTAchievementState state)
    {
        RobustXamlLoader.Load(this);

        PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = state.Unlocked ? UnlockedColor : LockedColor,
        };

        var secret = achievement.Hidden && !state.Unlocked;

        NameLabel.Text = secret
            ? Loc.GetString("adt-achievements-hidden-name")
            : Loc.GetString(achievement.Name);

        DescriptionLabel.SetMessage(secret
            ? Loc.GetString("adt-achievements-hidden-description")
            : Loc.GetString(achievement.Description));

        if (achievement.Icon != null && !secret)
            Icon.Texture = achievement.Icon.Frame0();

        Icon.Modulate = state.Unlocked ? Color.White : new Color(0.4f, 0.4f, 0.4f);

        var showProgress = achievement.ShowProgress && achievement.Goal > 1 && !secret;
        ProgressBox.Visible = showProgress;

        if (!showProgress)
            return;

        ProgressBar.MaxValue = achievement.Goal;
        ProgressBar.Value = Math.Clamp(state.Progress, 0, achievement.Goal);
        ProgressLabel.Text = $"{Math.Clamp(state.Progress, 0, achievement.Goal)} / {achievement.Goal}";
    }
}
