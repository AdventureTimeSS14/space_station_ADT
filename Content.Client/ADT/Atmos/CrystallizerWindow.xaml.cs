using Content.Shared.ADT.Atmos.Prototypes;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Prototypes;
using Content.Shared.Atmos;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Shared.Timing;
using System.Numerics;

namespace Content.Client.ADT.Atmos;

[GenerateTypedNameReferences]
public sealed partial class CrystallizerWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    public bool Active = true;
    private Button? _selectedButton;
    private string? _selectedButtonId;
    private Button _nothingButton = new Button();
    private readonly Dictionary<Button, string?> _buttonToRecipeId = new();
    private GasMixture? _gasMixture;
    private float _lastProgress;
    private float _lastParentWidth;
    public event Action<Button, string?>? OnRecipeButtonPressed;
    public event Action<float>? OnGasInputChanged;

    private const float MinDeviationRate = 0.90f;
    private const float MaxDeviationRate = 1.10f;

    // Локализованные полные имена газов для UI (в движке есть только аббревиатуры).
    private static readonly Dictionary<Gas, string> GasNames = new()
    {
        [Gas.Ammonia] = Loc.GetString("gases-ammonia"),
        [Gas.CarbonDioxide] = Loc.GetString("gases-co2"),
        [Gas.Frezon] = Loc.GetString("gases-frezon"),
        [Gas.Nitrogen] = Loc.GetString("gases-nitrogen"),
        [Gas.NitrousOxide] = Loc.GetString("gases-n2o"),
        [Gas.Oxygen] = Loc.GetString("gases-oxygen"),
        [Gas.Plasma] = Loc.GetString("gases-plasma"),
        [Gas.Tritium] = Loc.GetString("gases-tritium"),
        [Gas.WaterVapor] = Loc.GetString("gases-water-vapor"),
    };

    public CrystallizerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        InitializeRecipeButtons();

        GasInput.OnValueChanged += args => OnGasInputChanged?.Invoke(args.Value);
    }

    public void SetActive(bool active)
    {
        Active = active;
        ToggleStatusButton.Text = Loc.GetString(active
            ? "comp-gas-thermomachine-ui-status-enabled"
            : "comp-gas-thermomachine-ui-status-disabled");
        ToggleStatusButton.Pressed = active;
    }

    public void SetGasMixture(GasMixture? mixture)
    {
        _gasMixture = mixture;
        if (_selectedButton == null)
            return;

        CrystallizerRecipePrototype? recipe = null;
        if (_selectedButtonId != null && _prototypeManager.TryIndex<CrystallizerRecipePrototype>(_selectedButtonId, out var proto))
        {
            recipe = proto;
        }
        SelectRecipeButton(_selectedButton, recipe);
        SetTemperatureBar(mixture, recipe);
    }

    public void SetProgressBar(float progressBar)
    {
        _lastProgress = Math.Clamp(progressBar / 100f, 0f, 1f);
        FillProgressBar(_lastProgress);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (ProgressBarPanel.Parent?.Parent is not PanelContainer parent)
            return;

        if (MathHelper.CloseTo(parent.Size.X, _lastParentWidth))
            return;

        _lastParentWidth = parent.Size.X;
        FillProgressBar(_lastProgress);
    }

    private void FillProgressBar(float progressFillPercentage)
    {
        if (progressFillPercentage < 0.0001f)
        {
            ProgressBarPanel.MinSize = new Vector2(0, 20);
            return;
        }

        if (ProgressBarPanel.Parent?.Parent is PanelContainer parentContainer)
        {
            var targetWidth = parentContainer.Size.X * progressFillPercentage;
            ProgressBarPanel.MinSize = new Vector2(targetWidth, 20);
        }
    }

    private void SetTemperatureBar(GasMixture? mixture, CrystallizerRecipePrototype? recipe)
    {
        if (recipe == null || mixture == null || mixture.TotalMoles <= 0)
        {
            TemperatureBarPanel.MinSize = new Vector2(0, 20);
            TemperatureBarPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.White };
            return;
        }

        var temperature = mixture.Temperature;
        var minTemp = recipe.MinimumTemperature;
        var maxTemp = recipe.MaximumTemperature;
        var minRange = minTemp * MinDeviationRate;
        var maxRange = maxTemp * MaxDeviationRate;
        var medianTemp = (minTemp + maxTemp) / 2f;
        var optimalMin = medianTemp * MinDeviationRate;
        var optimalMax = medianTemp * MaxDeviationRate;

        var fillPercentage = Math.Clamp((temperature - minRange) / (maxRange - minRange), 0f, 1f);

        Color barColor;
        if (temperature >= minRange && temperature <= minTemp ||
            temperature >= maxTemp && temperature <= maxRange ||
            temperature >= maxRange)
        {
            barColor = Color.Red;
        }
        else if (temperature >= optimalMin && temperature <= optimalMax)
        {
            barColor = Color.Green;
        }
        else
        {
            barColor = Color.White;
        }

        if (TemperatureBarPanel.Parent?.Parent is PanelContainer parentContainer)
        {
            var targetWidth = (parentContainer.Size.X - 2) * fillPercentage;
            TemperatureBarPanel.MinSize = new Vector2(targetWidth, 18);
            TemperatureBarPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = barColor };
        }
    }

    private void InitializeRecipeButtons()
    {
        RecipesContainer.Children.Clear();
        _buttonToRecipeId.Clear();

        _nothingButton.Text = Loc.GetString("crystallizer-ui-nothing");
        _nothingButton.HorizontalExpand = true;
        _nothingButton.Pressed = true;

        _nothingButton.OnPressed += _ =>
        {
            SelectRecipeButton(_nothingButton);
            OnRecipeButtonPressed?.Invoke(_nothingButton, null);
        };
        _selectedButton = _nothingButton;
        _selectedButtonId = null;
        _buttonToRecipeId[_nothingButton] = null;
        RecipesContainer.AddChild(_nothingButton);

        foreach (var recipe in _prototypeManager.EnumeratePrototypes<CrystallizerRecipePrototype>())
        {
            var button = new Button
            {
                Text = GetRecipeName(recipe),
                HorizontalExpand = true
            };

            button.OnPressed += _ =>
            {
                SelectRecipeButton(button, recipe);
                OnRecipeButtonPressed?.Invoke(button, recipe.ID);
            };
            _buttonToRecipeId[button] = recipe.ID;
            RecipesContainer.AddChild(button);
        }
    }

    public void SelectRecipeById(string? recipeId)
    {
        Button button = _nothingButton;
        CrystallizerRecipePrototype? recipe = null;

        foreach (var (btn, id) in _buttonToRecipeId)
        {
            if (Equals(id, recipeId))
            {
                button = btn;
                if (recipeId != null && _prototypeManager.TryIndex<CrystallizerRecipePrototype>(recipeId, out var proto))
                {
                    recipe = proto;
                }
                break;
            }
        }

        SelectRecipeButton(button, recipe);
    }

    private static string GetRecipeName(CrystallizerRecipePrototype recipe)
    {
        return Loc.GetString($"crystallizer-recipe-{recipe.ID}");
    }

    private void SelectRecipeButton(Button button, CrystallizerRecipePrototype? recipe = null)
    {
        if (_selectedButton != null)
        {
            _selectedButton.Pressed = false;
        }
        _selectedButton = button;
        _selectedButton.Pressed = true;
        _selectedButtonId = _buttonToRecipeId[button];

        RequirementsContainer.Children.Clear();

        if (recipe == null)
        {
            RequirementsContainer.AddChild(new Label { Text = Loc.GetString("crystallizer-ui-select-recipe") });
            GasList.Children.Clear();
            return;
        }

        RequirementsContainer.AddChild(new Label { Text = Loc.GetString("crystallizer-ui-temperature") });
        RequirementsContainer.AddChild(new Label { Text = Loc.GetString("crystallizer-ui-minimum", ("temp", $"{recipe.MinimumTemperature}K")) });
        RequirementsContainer.AddChild(new Label { Text = Loc.GetString("crystallizer-ui-maximum", ("temp", $"{recipe.MaximumTemperature}K")) });

        RequirementsContainer.AddChild(new Label { Text = Loc.GetString("crystallizer-ui-gases") });
        for (int i = 0; i < recipe.MinimumRequirements.Length && i < Atmospherics.TotalNumberOfGases; i++)
        {
            if (recipe.MinimumRequirements[i] > 0 && GasNames.TryGetValue((Gas) i, out var gasName))
            {
                RequirementsContainer.AddChild(new Label
                {
                    Text = Loc.GetString("crystallizer-ui-gas-requirement",
                        ("gas", gasName), ("moles", $"{recipe.MinimumRequirements[i]}")),
                });
            }
        }

        RequirementsContainer.AddChild(new Label { Text = " " });
        RequirementsContainer.AddChild(new Label
        {
            Text = Loc.GetString(recipe.EnergyRelease > 0
                ? "crystallizer-ui-exothermic"
                : "crystallizer-ui-endothermic"),
        });

        // Update GasList
        GasList.Children.Clear();

        var index = 0;
        for (int i = 0; i < recipe.MinimumRequirements.Length && i < Atmospherics.TotalNumberOfGases; i++)
        {
            if (recipe.MinimumRequirements[i] > 0 && GasNames.TryGetValue((Gas) i, out var gasName))
            {
                var moles = _gasMixture != null ? _gasMixture.GetMoles(i) : 0f;

                var gasContainer = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    HorizontalExpand = true
                };

                var gasLabel = new Label { Text = gasName, Margin = new Thickness(5) };
                var gasControl = new Control { HorizontalExpand = true };
                var molesLabel = new Label { Text = Loc.GetString("crystallizer-ui-moles", ("moles", $"{moles:F2}")), Margin = new Thickness(5) };

                gasContainer.AddChild(gasLabel);
                gasContainer.AddChild(gasControl);
                gasContainer.AddChild(molesLabel);

                var panel = new PanelContainer
                {
                    Children = { gasContainer },
                    HorizontalExpand = true
                };

                var backgroundColor = (index % 2 == 0) ? Color.FromHex("#1B1B1E") : Color.FromHex("#2F2F38");
                panel.PanelOverride = new StyleBoxFlat { BackgroundColor = backgroundColor };

                GasList.AddChild(panel);
                index++;
            }
        }

        SetTemperatureBar(_gasMixture, recipe);
    }
}
