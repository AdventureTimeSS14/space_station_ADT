using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.OreFurnace;
using Content.Shared.ADT.OreFurnace.Components;
using Content.Shared.ADT.OreFurnace.Prototypes;
using Content.Shared.Materials;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.OreFurnace.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTOreFurnaceWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private readonly ADTSharedOreFurnaceSystem _furnace;
    private readonly SharedMaterialStorageSystem _materialStorage;
    private readonly SpriteSystem _sprite;

    public event Action<ProtoId<OreSmeltRecipePrototype>, int>? OnSmelt;
    public event Action? OnSmeltEverything;
    public event Action? OnClaimPoints;

    private readonly List<ADTOreFurnaceRecipeRow> _rows = new();

    private EntityUid _entity;

    public ADTOreFurnaceWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _furnace = _entityManager.System<ADTSharedOreFurnaceSystem>();
        _materialStorage = _entityManager.System<SharedMaterialStorageSystem>();
        _sprite = _entityManager.System<SpriteSystem>();

        SmeltEverythingButton.OnPressed += _ => OnSmeltEverything?.Invoke();
        ClaimPointsButton.OnPressed += _ => OnClaimPoints?.Invoke();
    }

    public void SetEntity(EntityUid uid)
    {
        _entity = uid;
        this.SetInfoFromEntity(_entityManager, uid);
        MaterialsList.SetOwner(uid);

        BuildRows();
    }

    private void BuildRows()
    {
        RecipeList.RemoveAllChildren();
        _rows.Clear();

        if (!_entityManager.TryGetComponent<ADTOreFurnaceComponent>(_entity, out var furnace))
            return;

        foreach (var recipe in _furnace.GetRecipes(furnace))
        {
            var row = new ADTOreFurnaceRecipeRow(
                recipe.ID,
                _furnace.GetRecipeName(recipe),
                GetCostText(furnace, recipe),
                GetIcon(recipe),
                furnace.DefaultAmount,
                furnace.MaxSmeltAmount);

            row.OnSmelt += (id, amount) => OnSmelt?.Invoke(id, amount);

            RecipeList.AddChild(row);
            _rows.Add(row);
        }
    }

    public void Update(uint points, bool canClaim)
    {
        PointsContainer.Visible = canClaim;
        PointsLabel.Text = Loc.GetString("ore-furnace-menu-points", ("points", points));
        ClaimPointsButton.Disabled = points == 0;

        UpdateRows();
    }

    private void UpdateRows()
    {
        if (!_entityManager.TryGetComponent<ADTOreFurnaceComponent>(_entity, out var furnace))
            return;

        foreach (var row in _rows)
        {
            if (!_proto.TryIndex(row.Recipe, out var recipe))
                continue;

            var available = _furnace.GetMaxSmeltAmount((_entity, furnace), recipe);
            var text = available > 0
                ? Loc.GetString("ore-furnace-menu-available", ("amount", available))
                : Loc.GetString("ore-furnace-menu-not-enough");

            row.SetAvailable(available, text);
        }
    }

    private string GetCostText(ADTOreFurnaceComponent furnace, OreSmeltRecipePrototype recipe)
    {
        var entries = new List<string>();

        foreach (var (materialId, needed) in recipe.Materials)
        {
            if (!_proto.TryIndex(materialId, out var material))
                continue;

            var cost = _furnace.GetMaterialCost(furnace, needed);
            var chunks = cost / (float) _materialStorage.GetSheetVolume(material);

            entries.Add(Loc.GetString("ore-furnace-menu-cost-entry",
                ("material", Loc.GetString(material.Name)),
                ("amount", chunks.ToString("0.##"))));
        }

        return string.Join(", ", entries);
    }

    private Control GetIcon(OreSmeltRecipePrototype recipe)
    {
        if (recipe.Icon != null)
        {
            return new TextureRect
            {
                Texture = _sprite.Frame0(recipe.Icon),
            };
        }

        var view = new EntityPrototypeView();
        view.SetPrototype(recipe.Result);
        return view;
    }
}
