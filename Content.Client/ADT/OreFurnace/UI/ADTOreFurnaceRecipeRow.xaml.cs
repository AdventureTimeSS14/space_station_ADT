using Content.Shared.ADT.OreFurnace.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.OreFurnace.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTOreFurnaceRecipeRow : Control
{
    public event Action<ProtoId<OreSmeltRecipePrototype>, int>? OnSmelt;

    public readonly ProtoId<OreSmeltRecipePrototype> Recipe;

    private readonly int _maxAmount;

    public ADTOreFurnaceRecipeRow(
        ProtoId<OreSmeltRecipePrototype> recipe,
        string name,
        string cost,
        Control icon,
        int defaultAmount,
        int maxAmount)
    {
        RobustXamlLoader.Load(this);

        Recipe = recipe;
        _maxAmount = maxAmount;

        NameLabel.Text = name;
        CostLabel.Text = cost;
        IconContainer.AddChild(icon);

        AmountEdit.SetText(Math.Clamp(defaultAmount, 1, maxAmount).ToString());
        AmountEdit.OnTextChanged += _ => ClampAmount();

        SmeltButton.OnPressed += _ => OnSmelt?.Invoke(Recipe, GetAmount());
        SmeltMaxButton.OnPressed += _ => OnSmelt?.Invoke(Recipe, _maxAmount);
    }

    public void SetAvailable(int available, string availableText)
    {
        AvailableLabel.Text = availableText;

        SmeltButton.Disabled = available <= 0;
        SmeltMaxButton.Disabled = available <= 0;
    }

    private int GetAmount()
    {
        if (!int.TryParse(AmountEdit.Text, out var amount) || amount <= 0)
            return 1;

        return Math.Min(amount, _maxAmount);
    }

    private void ClampAmount()
    {
        if (!int.TryParse(AmountEdit.Text, out var amount))
            return;

        if (amount > _maxAmount)
            AmountEdit.SetText(_maxAmount.ToString());
        else if (amount < 0)
            AmountEdit.SetText("0");
    }
}
