using System.Diagnostics.CodeAnalysis;
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using Content.Shared.ADT.Rituals;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.Guidebook.Ashwalkers;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideAshwalkerRitualEmbed : BoxContainer, IDocumentTag, ISearchableControl
{
    [Dependency] private readonly ILogManager _logManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly ISawmill _sawmill;

    public GuideAshwalkerRitualEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.ashwalkers.ritual");
        MouseFilter = MouseFilterMode.Stop;
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        if (!args.TryGetValue("Ritual", out var id))
        {
            _sawmill.Error("Ashwalker ritual embed is missing the Ritual argument");
            return false;
        }

        if (!_prototype.TryIndex<ADTRitualPrototype>(id, out var ritual))
        {
            _sawmill.Error($"Unknown ashwalker ritual prototype \"{id}\"");
            return false;
        }

        args.TryGetValue("Quirk", out var quirk);
        GenerateControl(ritual, quirk);

        control = this;
        return true;
    }

    private void GenerateControl(ADTRitualPrototype ritual, string? quirk)
    {
        var accent = AshwalkerGuideColors.ForDye(ritual.NeededDye);

        AccentBar.PanelOverride = new StyleBoxFlat { BackgroundColor = accent };
        DyeSwatch.PanelOverride = new StyleBoxFlat { BackgroundColor = accent };

        NameLabel.SetMarkupPermissive($"[bold][color={AshwalkerGuideColors.ToMarkup(accent)}]{Loc.GetString(ritual.Name)}[/color][/bold]");

        if (ritual.ShamanOnly)
        {
            BadgeLabel.Visible = true;
            BadgeLabel.SetMarkupPermissive($"[color={AshwalkerGuideColors.ToMarkup(AshwalkerGuideColors.Danger)}]{Loc.GetString("adt-ritual-req-shaman")}[/color]");
        }

        DescriptionLabel.SetMarkupPermissive(ritual.Description.HasValue
            ? Loc.GetString(ritual.Description.Value)
            : Loc.GetString("heretic-guide-ritual-no-description"));

        BuildStats(ritual);
        BuildRequired(ritual, accent);
        BuildRisk(ritual);

        if (string.IsNullOrWhiteSpace(quirk))
            return;

        QuirkBox.Visible = true;
        QuirkHeader.SetMarkupPermissive($"[bold][color={AshwalkerGuideColors.ToMarkup(AshwalkerGuideColors.Danger)}]{Loc.GetString("adt-ritual-risk-conditional")}[/color][/bold]");
        QuirkLabel.SetMarkupPermissive(quirk);
    }

    private void BuildStats(ADTRitualPrototype ritual)
    {
        var participants = ritual.ExtraInvokers + 1;
        StatsContainer.AddChild(AshwalkerGuideWidgets.BuildTextRow(
            Loc.GetString("adt-ashwalker-guide-participants"),
            Loc.GetString("adt-ritual-req-invokers", ("total", participants))));

        if (!string.IsNullOrEmpty(ritual.NeededDye))
        {
            var dyeFluff = ritual.DyeFluff.HasValue
                ? Loc.GetString(ritual.DyeFluff.Value)
                : Loc.GetString("adt-ritual-dye-amber");

            StatsContainer.AddChild(AshwalkerGuideWidgets.BuildTextRow(
                Loc.GetString("adt-ashwalker-guide-dye"),
                Loc.GetString("adt-ritual-req-dye", ("dye", dyeFluff))));
        }

        StatsContainer.AddChild(AshwalkerGuideWidgets.BuildTextRow(
            Loc.GetString("adt-ashwalker-guide-charges"),
            ritual.Charges < 0
                ? Loc.GetString("adt-ashwalker-guide-charges-unlimited")
                : Loc.GetString("adt-ritual-price-charges", ("left", ritual.Charges))));

        StatsContainer.AddChild(AshwalkerGuideWidgets.BuildTextRow(
            Loc.GetString("adt-ashwalker-guide-cast-time"),
            Loc.GetString("adt-ritual-price-cast", ("seconds", (int) ritual.CastTime.TotalSeconds))));

        StatsContainer.AddChild(AshwalkerGuideWidgets.BuildTextRow(
            Loc.GetString("adt-ashwalker-guide-cooldown"),
            Loc.GetString("adt-ritual-price-cooldown", ("seconds", (int) ritual.Cooldown.TotalSeconds))));
    }

    private void BuildRequired(ADTRitualPrototype ritual, Color accent)
    {
        if (ritual.RequiredThings.Count == 0)
            return;

        foreach (var thing in ritual.RequiredThings)
        {
            var label = thing.Amount > 1
                ? Loc.GetString("adt-ritual-req-thing-amount", ("name", Loc.GetString(thing.Name)), ("amount", thing.Amount))
                : Loc.GetString(thing.Name);

            if (!thing.Consume)
                label = $"{label} {Loc.GetString("adt-ashwalker-guide-not-consumed")}";

            RequiredContainer.AddChild(new GuideAshwalkerChip(label, accent));
        }

        RequiredBox.Visible = true;
        RequiredHeader.SetMarkupPermissive(Loc.GetString("adt-ritual-window-requirements"));
    }

    private void BuildRisk(ADTRitualPrototype ritual)
    {
        RiskContainer.AddChild(AshwalkerGuideWidgets.BuildBarRow(Loc.GetString("adt-ashwalker-guide-fail"), ritual.FailChance * 100f, AshwalkerGuideColors.Danger));
        RiskContainer.AddChild(AshwalkerGuideWidgets.BuildBarRow(Loc.GetString("adt-ashwalker-guide-disaster"), ritual.DisasterChance * 100f, AshwalkerGuideColors.Danger));

        if (!ritual.DeleteThingsOnFail)
            return;

        var note = new RichTextLabel { Margin = new Thickness(0, 4, 0, 0) };
        note.SetMarkupPermissive($"[color={AshwalkerGuideColors.ToMarkup(AshwalkerGuideColors.Note)}]{Loc.GetString("adt-ritual-risk-loses-things")}[/color]");
        RiskContainer.AddChild(note);
    }
}
