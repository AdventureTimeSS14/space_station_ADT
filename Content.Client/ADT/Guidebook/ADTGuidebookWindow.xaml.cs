namespace Content.Client.ADT.Guidebook;

[GenerateTypedNameReferences]
public sealed partial class ADTGuidebookWindow : FancyWindow, ILinkClickHandler, IAnchorClickHandler
{
    [Dependency] private DocumentParsingManager _parsing = default!;
    [Dependency] private IResourceManager _resources = default!;
    [Dependency] private IResourceCache _cache = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private static readonly ResPath BookmarkPath = ADTUserData.Root / "guidebook_bookmarks.txt";

    private Dictionary<ProtoId<GuideEntryPrototype>, GuideEntry> _entries = new();
    private readonly Dictionary<string, Category> _categories = new();
    private readonly Dictionary<string, string> _entryCategories = new();
    private readonly Dictionary<string, string> _parents = new();
    private readonly HashSet<string> _visibleEntries = new();
    private readonly HashSet<string> _bookmarks = new();
    private readonly List<Page> _history = new();
    private List<ProtoId<GuideEntryPrototype>>? _requestedRoots;
    private ProtoId<GuideEntryPrototype>? _forcedRoot;
    private string? _rulesRoot;
    private int _historyIndex = -1;
    private Page? _page;
    private Page? _searchOrigin;
    private BoxContainer? _article;
    private RichTextLabel? _description;
    private CancellationTokenSource? _searchCancel;
    private bool _settingSearch;

    public ProtoId<GuideEntryPrototype>? Selected
    {
        get
        {
            if (_page is { Kind: PageKind.Entry } page)
                return new ProtoId<GuideEntryPrototype>(page.Id);

            return null;
        }
    }

    public ADTGuidebookWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        HomeNav.OnPressed += _ => Navigate(new Page(PageKind.Home));
        BookmarksNav.OnPressed += _ => Navigate(new Page(PageKind.Bookmarks));
        BackButton.OnPressed += _ => MoveHistory(-1);
        ForwardButton.OnPressed += _ => MoveHistory(1);
        ClearSearchButton.OnPressed += _ => ClearSearch();
        SearchBar.OnTextChanged += _ => QueueSearch();
        BookmarkButton.OnPressed += _ => ToggleBookmark();
        FilterBar.OnTextChanged += _ => FilterArticle();
        ClearFilterButton.OnPressed += _ => FilterBar.Clear();
        CategoryMenu.OnItemSelected += args => SelectCategory(args.Id);
        LegacyGuidebookButton.OnPressed += _ => OpenLegacyGuidebook();
        OnClose += () =>
        {
            if (!IsPoppedOut)
                CancelSearch();
        };
        OnOpen += ResumeSearch;

        LoadBookmarks();
        InitializeLayout();
    }

    public bool UpdateGuides(
        Dictionary<ProtoId<GuideEntryPrototype>, GuideEntry> entries,
        List<ProtoId<GuideEntryPrototype>>? rootEntries = null,
        ProtoId<GuideEntryPrototype>? forceRoot = null,
        ProtoId<GuideEntryPrototype>? selected = null)
    {
        var rulesRoot = UserInterfaceManager
            .GetUIController<Content.Client.UserInterface.Systems.Info.InfoUIController>().RulesEntryId.Id;
        var sameRoots = rootEntries == null
            ? _requestedRoots == null
            : _requestedRoots != null && rootEntries.SequenceEqual(_requestedRoots);
        var changed = entries.Count != _entries.Count
            || entries.Any(pair => !_entries.TryGetValue(pair.Key, out var previous) || !ReferenceEquals(previous, pair.Value))
            || !sameRoots
            || forceRoot != _forcedRoot
            || rulesRoot != _rulesRoot;

        if (changed)
        {
            CancelSearch();
            _entries = new Dictionary<ProtoId<GuideEntryPrototype>, GuideEntry>(entries);
            _requestedRoots = rootEntries?.ToList();
            _forcedRoot = forceRoot;
            _rulesRoot = rulesRoot;
            _documents.Clear();
            _embedSearchText.Clear();
            _history.Clear();
            _historyIndex = -1;
            _page = null;
            _searchOrigin = null;
            BuildCategories();
            BuildSidebar();
        }

        if (selected is { } id && _visibleEntries.Contains(id.Id))
        {
            OpenEntry(id.Id);
        }
        else if (_page == null)
        {
            if (forceRoot is { } root && _entries.ContainsKey(root))
                OpenEntry(root.Id);
            else
                Navigate(new Page(PageKind.Home));
        }

        return changed;
    }

    public void HandleClick(string link)
    {
        OpenEntry(link);
    }

    private void OpenLegacyGuidebook()
    {
        UserInterfaceManager.GetUIController<GuidebookUIController>()
            .OpenLegacyGuidebook(_entries, _requestedRoots, _forcedRoot, Selected);
    }

    private void OpenEntry(string id)
    {
        if (!_entries.ContainsKey(id))
            return;

        var category = _entryCategories.GetValueOrDefault(id, string.Empty);
        Navigate(new Page(PageKind.Entry, id, category));
    }

    private void Navigate(Page page)
    {
        if (_page != null && _page.Kind == page.Kind && _page.Id == page.Id && _page.Query == page.Query)
        {
            UpdateNavigationButtons();
            return;
        }

        SaveScrollPosition();
        CancelSearch();

        if (_historyIndex + 1 < _history.Count)
            _history.RemoveRange(_historyIndex + 1, _history.Count - _historyIndex - 1);

        if (_page?.Kind == PageKind.Search && page.Kind == PageKind.Search)
        {
            _history[_historyIndex] = page;
        }
        else
        {
            _history.Add(page);
            _historyIndex++;
        }

        if (_history.Count > 100)
        {
            _history.RemoveAt(0);
            _historyIndex--;
        }

        _page = page;
        RenderPage();
    }

    private void MoveHistory(int direction)
    {
        var index = _historyIndex + direction;
        if (index < 0 || index >= _history.Count)
            return;

        SaveScrollPosition();
        CancelSearch();
        _historyIndex = index;
        _page = _history[index];
        RenderPage();
    }

    private void SaveScrollPosition()
    {
        if (_page != null)
            _page.Scroll = ContentScroll.GetScrollValue();
    }

    private void RenderPage()
    {
        if (_page == null)
            return;

        var page = _page;
        _article = null;
        _description = null;
        _articleFilters.Clear();
        _representations.Clear();
        ClearControls(PageBody);
        ClearControls(PathBar);
        ClearControls(OutlineList);
        FilterBar.Clear();
        FilterTools.Visible = false;
        BookmarkButton.Visible = false;
        _settingSearch = true;
        var searchText = page.Kind == PageKind.Search ? page.Query : string.Empty;
        if (SearchBar.Text != searchText)
            SearchBar.Text = searchText;
        _settingSearch = false;
        ClearSearchButton.Disabled = string.IsNullOrEmpty(SearchBar.Text);

        if (page.Kind != PageKind.Search)
            _searchOrigin = null;
        else if (_searchOrigin == null)
            _searchOrigin = _history.Take(_historyIndex).LastOrDefault(previous => previous.Kind != PageKind.Search);

        switch (page.Kind)
        {
            case PageKind.Home:
                ShowHome();
                break;
            case PageKind.Category:
                ShowCategory(page.Id);
                break;
            case PageKind.Entry:
                ShowEntry(page.Id);
                break;
            case PageKind.Bookmarks:
                ShowBookmarks();
                break;
            case PageKind.Search:
                ShowSearch(page.Query);
                break;
        }

        if (page.Kind == PageKind.Entry)
            ExpandPathTo(page.Id);

        BackButton.Disabled = _historyIndex <= 0;
        ForwardButton.Disabled = _historyIndex + 1 >= _history.Count;
        UpdateNavigationButtons();
        UpdateResponsiveLayout();

        ContentScroll.SetScrollValue(Vector2.Zero);
        UserInterfaceManager.DeferAction(() =>
        {
            if (!Disposed && ReferenceEquals(_page, page))
                ContentScroll.SetScrollValue(page.Scroll);
        });
    }

    private void UpdateNavigationButtons()
    {
        if (_page is not { } page)
            return;

        HomeNav.Pressed = page.Kind == PageKind.Home;
        BookmarksNav.Pressed = page.Kind == PageKind.Bookmarks;
        RebuildSidebar();

        var selectedCategory = page.Kind == PageKind.Category ? page.Id : page.Category;
        var index = _categoryIds.IndexOf(selectedCategory);
        CategoryMenu.SelectId(index + 1);
    }

    private void LoadBookmarks()
    {
        try
        {
            if (!_resources.UserData.Exists(BookmarkPath))
                return;

            using var reader = _resources.UserData.OpenText(BookmarkPath);
            while (reader.ReadLine() is { } line)
            {
                if (!string.IsNullOrWhiteSpace(line))
                    _bookmarks.Add(line.Trim());
            }
        }
        catch (Exception e)
        {
            Logger.GetSawmill("adt.guidebook").Error($"Failed to load guidebook bookmarks: {e}");
        }
    }

    private void ToggleBookmark()
    {
        if (_page is not { Kind: PageKind.Entry } page)
            return;

        if (!_bookmarks.Remove(page.Id))
            _bookmarks.Add(page.Id);

        try
        {
            _resources.UserData.CreateDir(BookmarkPath.Directory);
            using var writer = _resources.UserData.OpenWriteText(BookmarkPath);
            foreach (var id in _bookmarks.OrderBy(id => id))
            {
                writer.WriteLine(id);
            }
        }
        catch (Exception e)
        {
            Logger.GetSawmill("adt.guidebook").Error($"Failed to save guidebook bookmarks: {e}");
        }

        UpdateBookmarkButton(page.Id);
    }

    private void UpdateBookmarkButton(string id)
    {
        var bookmarked = _bookmarks.Contains(id);
        BookmarkButton.Visible = true;
        BookmarkButton.Pressed = bookmarked;
        BookmarkButton.Text = Loc.GetString(bookmarked
            ? "adt-guidebook-remove-bookmark"
            : "adt-guidebook-add-bookmark");
    }

    private void CancelSearch()
    {
        _searchCancel?.Cancel();
        _searchCancel?.Dispose();
        _searchCancel = null;
    }

    private void ResumeSearch()
    {
        if (_page?.Kind == PageKind.Search || !string.IsNullOrWhiteSpace(SearchBar.Text))
            QueueSearch();
    }

    protected override void Dispose(bool disposing)
    {
        CancelSearch();
        DisposeLayout();
        base.Dispose(disposing);
    }

    private static void ClearControls(Control control)
    {
        foreach (var child in control.Children.ToArray())
        {
            child.Dispose();
        }
    }

    private enum PageKind : byte
    {
        Home,
        Category,
        Entry,
        Bookmarks,
        Search,
    }

    private sealed record Page(PageKind Kind, string Id = "", string Category = "", string Query = "")
    {
        public Vector2 Scroll;
    }
}
