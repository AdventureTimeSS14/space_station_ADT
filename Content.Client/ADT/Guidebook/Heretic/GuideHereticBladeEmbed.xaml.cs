using System.Diagnostics.CodeAnalysis;
using System.Linq;
using System.Text;
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using Content.Shared.Damage.Prototypes;
using Content.Shared.Weapons.Melee;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.Guidebook.Heretic;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideHereticBladeEmbed : BoxContainer, IDocumentTag, ISearchableControl
{
    [Dependency] private readonly IComponentFactory _componentFactory = default!;
    [Dependency] private readonly ILogManager _logManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly ISawmill _sawmill;

    public GuideHereticBladeEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.heretic.blade");
        MouseFilter = MouseFilterMode.Stop;
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        if (!args.TryGetValue("Blade", out var id))
        {
            _sawmill.Error("Heretic blade embed is missing the Blade argument");
            return false;
        }

        if (!_prototype.TryIndex<EntityPrototype>(id, out var blade))
        {
            _sawmill.Error($"Unknown blade prototype \"{id}\"");
            return false;
        }

        args.TryGetValue("Path", out var path);
        args.TryGetValue("Bonus", out var bonus);

        GenerateControl(id, blade, HereticGuideColors.ForPath(path), bonus);

        control = this;
        return true;
    }

    private void GenerateControl(string id, EntityPrototype blade, Color accent, string? bonusKey)
    {
        AccentBar.PanelOverride = new StyleBoxFlat { BackgroundColor = accent };
        BladeViewContainer.AddChild(new GuideEntityEmbed(id, false, false));

        NameLabel.SetMarkupPermissive($"[bold][color={HereticGuideColors.ToMarkup(accent)}]{blade.Name}[/color][/bold]");
        DamageLabel.SetMarkupPermissive(BuildDamageText(blade));

        BonusLabel.SetMarkupPermissive(bonusKey != null
            ? Loc.GetString(bonusKey)
            : Loc.GetString("heretic-guide-blade-no-bonus"));
    }

    private string BuildDamageText(EntityPrototype blade)
    {
        if (!blade.TryGetComponent<MeleeWeaponComponent>(out var melee, _componentFactory))
            return Loc.GetString("heretic-guide-blade-no-damage");

        var parts = new List<string>();

        foreach (var (type, amount) in melee.Damage.DamageDict.OrderByDescending(x => x.Value))
        {
            var name = _prototype.TryIndex(type, out var damageType)
                ? damageType.LocalizedName
                : type.Id;

            parts.Add($"[color=#d8dee9]{name}[/color] {amount.Float():0.#}");
        }

        if (parts.Count == 0)
            return Loc.GetString("heretic-guide-blade-no-damage");

        var builder = new StringBuilder();
        builder.Append(Loc.GetString("heretic-guide-blade-damage"));
        builder.Append(' ');
        builder.Append(string.Join(", ", parts));
        builder.Append("    ");
        builder.Append(Loc.GetString("heretic-guide-blade-rate", ("rate", melee.AttackRate.ToString("0.##"))));

        return builder.ToString();
    }
}
