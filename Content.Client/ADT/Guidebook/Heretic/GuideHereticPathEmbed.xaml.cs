namespace Content.Client.ADT.Guidebook.Heretic;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideHereticPathEmbed : BoxContainer, IDocumentTag, ISearchableControl
{
    [Dependency] private readonly IEntitySystemManager _systemManager = default!;
    [Dependency] private readonly ILogManager _logManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly SpriteSystem _sprite;
    private readonly ISawmill _sawmill;

    public GuideHereticPathEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _systemManager.GetEntitySystem<SpriteSystem>();
        _sawmill = _logManager.GetSawmill("guidebook.heretic.path");
        MouseFilter = MouseFilterMode.Stop;
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        if (!args.TryGetValue("Path", out var path))
        {
            _sawmill.Error("Heretic path embed is missing the Path argument");
            return false;
        }

        GenerateControl(path);

        control = this;
        return true;
    }

    private const string SidePath = "Side";

    private void GenerateControl(string path)
    {
        var side = path == SidePath;
        var accent = side ? HereticGuideColors.Side : HereticGuideColors.ForPath(path);
        AccentBar.PanelOverride = new StyleBoxFlat { BackgroundColor = accent };

        var listings = BuildListingIndex();

        var knowledge = _prototype.EnumeratePrototypes<HereticKnowledgePrototype>()
            .Where(x => side ? x.Path == null : x.Path == path)
            .OrderBy(x => x.Stage)
            .ThenBy(x => x.SideKnowledge)
            .ThenBy(x => x.ID)
            .ToList();

        var shown = 0;
        var total = 0;

        foreach (var entry in knowledge)
        {
            if (!listings.TryGetValue(entry.ID, out var listing))
                continue;

            if (shown == 0 && listing.Icon != null)
                PathIcon.Texture = _sprite.Frame0(listing.Icon);

            StageContainer.AddChild(new GuideHereticStageRow(entry, listing, accent, _sprite));
            shown++;

            foreach (var (_, amount) in listing.Cost)
            {
                total += amount.Int();
                break;
            }
        }

        if (shown == 0)
            _sawmill.Warning($"Heretic path \"{path}\" has no purchasable knowledge");

        var nameKey = side ? "store-heretic-path-side" : $"store-heretic-path-{path.ToLowerInvariant()}";
        var pathName = Loc.TryGetString(nameKey, out var localized) ? localized : path;

        PathLabel.SetMarkupPermissive($"[bold][color={HereticGuideColors.ToMarkup(accent)}]{pathName}[/color][/bold]");
        TotalLabel.SetMarkupPermissive(Loc.GetString("heretic-guide-path-total", ("cost", total)));
        LegendLabel.SetMarkupPermissive(Loc.GetString("heretic-guide-path-legend",
            ("side", HereticGuideColors.ToMarkup(HereticGuideColors.Side)),
            ("ascension", HereticGuideColors.ToMarkup(HereticGuideColors.Ascension))));
    }

    private Dictionary<string, ListingPrototype> BuildListingIndex()
    {
        var index = new Dictionary<string, ListingPrototype>();

        foreach (var listing in _prototype.EnumeratePrototypes<ListingPrototype>())
        {
            if (listing.ProductHereticKnowledge is not { } knowledge)
                continue;

            index[knowledge.Id] = listing;
        }

        return index;
    }
}
