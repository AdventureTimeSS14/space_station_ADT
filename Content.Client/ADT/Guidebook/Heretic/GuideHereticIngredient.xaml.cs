using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Guidebook.Heretic;

[GenerateTypedNameReferences]
public sealed partial class GuideHereticIngredient : PanelContainer
{
    public GuideHereticIngredient()
    {
        RobustXamlLoader.Load(this);
    }

    public GuideHereticIngredient(string name, int count, Color accent, bool output) : this()
    {
        PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = output ? HereticGuideColors.Output : HereticGuideColors.Ingredient,
            BorderThickness = new Thickness(1),
            BorderColor = accent.WithAlpha(0.55f),
        };

        CountLabel.SetMarkupPermissive($"[bold][color={HereticGuideColors.ToMarkup(accent)}]{count}x[/color][/bold]");
        NameLabel.SetMarkupPermissive(name);
    }
}
