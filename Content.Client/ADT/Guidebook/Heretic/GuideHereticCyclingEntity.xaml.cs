using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.ADT.Guidebook.Heretic;

[GenerateTypedNameReferences]
public sealed partial class GuideHereticCyclingEntity : BoxContainer
{
    private const float Interval = 1.6f;

    private readonly List<Texture> _textures = new();
    private readonly List<string> _names = new();

    private float _accumulated;
    private int _index;

    public GuideHereticCyclingEntity()
    {
        RobustXamlLoader.Load(this);
    }

    public GuideHereticCyclingEntity(
        IEnumerable<string> prototypes,
        SpriteSystem sprite,
        IPrototypeManager prototypeManager,
        Color accent) : this()
    {
        foreach (var id in prototypes)
        {
            if (!prototypeManager.TryIndex<EntityPrototype>(id, out var proto))
                continue;

            _textures.Add(sprite.Frame0(new SpriteSpecifier.EntityPrototype(id)));
            _names.Add(proto.Name);
        }

        CaptionLabel.SetMarkupPermissive($"[color={HereticGuideColors.ToMarkup(accent)}]{_names.Count}[/color]");
        Apply();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_textures.Count < 2)
            return;

        _accumulated += args.DeltaSeconds;

        if (_accumulated < Interval)
            return;

        _accumulated = 0f;
        _index = (_index + 1) % _textures.Count;
        Apply();
    }

    private void Apply()
    {
        if (_textures.Count == 0)
            return;

        Icon.Texture = _textures[_index];
        CaptionLabel.SetMarkupPermissive(_names[_index]);
    }
}
