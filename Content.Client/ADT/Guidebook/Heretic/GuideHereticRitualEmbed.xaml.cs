using System.Diagnostics.CodeAnalysis;
using System.Linq;
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using Content.Shared.Heretic.Prototypes;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.Guidebook.Heretic;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideHereticRitualEmbed : BoxContainer, IDocumentTag, ISearchableControl
{
    [Dependency] private readonly IEntitySystemManager _systemManager = default!;
    [Dependency] private readonly ILogManager _logManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly SpriteSystem _sprite;
    private readonly ISawmill _sawmill;

    public GuideHereticRitualEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _systemManager.GetEntitySystem<SpriteSystem>();
        _sawmill = _logManager.GetSawmill("guidebook.heretic.ritual");
        MouseFilter = MouseFilterMode.Stop;
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        if (!args.TryGetValue("Ritual", out var id))
        {
            _sawmill.Error("Heretic ritual embed is missing the Ritual argument");
            return false;
        }

        if (!_prototype.TryIndex<HereticRitualPrototype>(id, out var ritual))
        {
            _sawmill.Error($"Unknown heretic ritual prototype \"{id}\"");
            return false;
        }

        args.TryGetValue("Path", out var path);
        args.TryGetValue("CycleOutput", out var cycle);
        GenerateControl(ritual, HereticGuideColors.ForPath(path), cycle);

        control = this;
        return true;
    }

    private void GenerateControl(HereticRitualPrototype ritual, Color accent, string? cycle)
    {
        AccentBar.PanelOverride = new StyleBoxFlat { BackgroundColor = accent };
        RitualIcon.Texture = _sprite.Frame0(ritual.Icon);

        NameLabel.SetMarkupPermissive($"[bold][color={HereticGuideColors.ToMarkup(accent)}]{Loc.GetString(ritual.LocName)}[/color][/bold]");

        if (ritual.Limit > 0)
        {
            LimitLabel.Visible = true;
            LimitLabel.SetMarkupPermissive(Loc.GetString("heretic-guide-ritual-limit", ("count", ritual.Limit)));
        }

        DescriptionLabel.SetMarkupPermissive(string.IsNullOrWhiteSpace(ritual.LocDesc)
            ? Loc.GetString("heretic-guide-ritual-no-description")
            : Loc.GetString(ritual.LocDesc));

        BuildInputs(ritual, accent);
        BuildConditions(ritual);
        BuildOutputs(ritual, accent, cycle);
    }

    private void BuildInputs(HereticRitualPrototype ritual, Color accent)
    {
        if (ritual.RequiredTags != null)
        {
            foreach (var (tag, count) in ritual.RequiredTags.OrderBy(x => x.Key.Id))
            {
                InputContainer.AddChild(new GuideHereticIngredient(GetTagName(tag.Id), count, accent, false));
            }
        }

        if (ritual.RequiredEntityNames != null)
        {
            foreach (var (entityName, count) in ritual.RequiredEntityNames.OrderBy(x => x.Key))
            {
                InputContainer.AddChild(new GuideHereticIngredient(entityName, count, accent, false));
            }
        }

        if (InputContainer.ChildCount == 0)
            return;

        InputBox.Visible = true;
        InputHeader.SetMarkupPermissive(Loc.GetString("heretic-guide-ritual-inputs"));
    }

    private void BuildConditions(HereticRitualPrototype ritual)
    {
        if (ritual.CustomBehaviors == null || ritual.CustomBehaviors.Count == 0)
            return;

        if (!Loc.TryGetString($"heretic-guide-behavior-{ritual.ID}", out var text))
            return;

        ConditionBox.Visible = true;
        ConditionHeader.SetMarkupPermissive(Loc.GetString("heretic-guide-ritual-conditions"));
        ConditionLabel.SetMarkupPermissive($"[color={HereticGuideColors.ToMarkup(HereticGuideColors.Ascension)}]{text}[/color]");
    }

    private void BuildOutputs(HereticRitualPrototype ritual, Color accent, string? cycle)
    {
        if (cycle != null)
        {
            var protos = cycle.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            OutputContainer.AddChild(new GuideHereticCyclingEntity(protos, _sprite, _prototype, accent));
            OutputBox.Visible = true;
            OutputHeader.SetMarkupPermissive(Loc.GetString("heretic-guide-ritual-outputs"));
            return;
        }

        if (ritual.Output == null || ritual.Output.Count == 0)
            return;

        foreach (var (proto, count) in ritual.Output)
        {
            if (!_prototype.HasIndex(proto))
            {
                _sawmill.Error($"Ritual {ritual.ID} outputs unknown prototype \"{proto}\"");
                continue;
            }

            OutputContainer.AddChild(new GuideEntityEmbed(proto, true, false));

            if (count > 1)
                OutputContainer.AddChild(new GuideHereticIngredient(Loc.GetString("heretic-guide-ritual-output-count"), count, accent, true));
        }

        if (OutputContainer.ChildCount == 0)
            return;

        OutputBox.Visible = true;
        OutputHeader.SetMarkupPermissive(Loc.GetString("heretic-guide-ritual-outputs"));
    }

    private static string GetTagName(string tag)
    {
        return Loc.TryGetString($"heretic-guide-tag-{tag}", out var name) ? name : tag;
    }
}
