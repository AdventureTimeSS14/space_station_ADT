using System.Diagnostics.CodeAnalysis;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Guidebook.Heretic;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideHereticQuote : BoxContainer, IDocumentTag
{
    public GuideHereticQuote()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        string text;
        if (args.TryGetValue("Loc", out var locId))
            text = Loc.GetString(locId);
        else if (args.TryGetValue("Text", out var raw))
            text = raw;
        else
            return false;

        var color = HereticGuideColors.Accent;
        if (args.TryGetValue("Path", out var path))
            color = HereticGuideColors.ForPath(path);

        Bar.PanelOverride = new StyleBoxFlat { BackgroundColor = color };
        QuoteLabel.SetMarkupPermissive($"[italic][color={HereticGuideColors.ToMarkup(color)}]{text}[/color][/italic]");

        control = this;
        return true;
    }
}
