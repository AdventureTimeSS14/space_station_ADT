using System.Diagnostics.CodeAnalysis;
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.Guidebook.WorldAnvil;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideWorldAnvilRecipeEmbed : BoxContainer, IDocumentTag, ISearchableControl
{
    [Dependency] private readonly IEntitySystemManager _systemManager = default!;
    [Dependency] private readonly ILogManager _logManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly ISawmill _sawmill;

    public GuideWorldAnvilRecipeEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.world-anvil.recipe");
        MouseFilter = MouseFilterMode.Stop;
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;

        if (!args.TryGetValue("Input", out var inputId))
        {
            _sawmill.Error("World anvil recipe embed is missing the Input argument");
            return false;
        }

        if (!args.TryGetValue("Result", out var resultId))
        {
            _sawmill.Error("World anvil recipe embed is missing the Result argument");
            return false;
        }

        args.TryGetValue("Cost", out var costStr);
        args.TryGetValue("Delay", out var delayStr);
        args.TryGetValue("Name", out var nameKey);
        args.TryGetValue("Note", out var noteKey);

        var cost = int.TryParse(costStr, out var parsedCost) ? parsedCost : 0;
        var delay = float.TryParse(delayStr, out var parsedDelay) ? parsedDelay : 0f;

        GenerateControl(inputId, resultId, cost, delay, nameKey, noteKey);

        control = this;
        return true;
    }

    private void GenerateControl(string inputId, string resultId, int cost, float delay, string? nameKey, string? noteKey)
    {
        var accent = WorldAnvilGuideColors.Magmite;
        AccentBar.PanelOverride = new StyleBoxFlat { BackgroundColor = accent };

        if (_prototype.TryIndex<EntityPrototype>(inputId, out var inputProto))
        {
            InputViewContainer.AddChild(AddEntity(inputId, inputProto));
        }
        else
        {
            _sawmill.Error($"World anvil recipe has unknown input prototype \"{inputId}\"");
        }

        ArrowLabel.SetMarkupPermissive($"[color={WorldAnvilGuideColors.ToMarkup(accent)}]→[/color]");

        if (_prototype.TryIndex<EntityPrototype>(resultId, out var resultProto))
        {
            OutputViewContainer.AddChild(AddEntity(resultId, resultProto));
        }
        else
        {
            _sawmill.Error($"World anvil recipe has unknown result prototype \"{resultId}\"");
        }

        var name = nameKey != null
            ? Loc.GetString(nameKey)
            : Loc.GetString("world-anvil-guide-recipe-forge");
        NameLabel.SetMarkupPermissive($"[bold][color={WorldAnvilGuideColors.ToMarkup(accent)}]{name}[/color][/bold]");

        var costColor = cost > 0 ? WorldAnvilGuideColors.Fuel : WorldAnvilGuideColors.Inert;
        var costText = cost > 0
            ? Loc.GetString("world-anvil-guide-cost", ("cost", cost), ("color", WorldAnvilGuideColors.ToMarkup(costColor)))
            : Loc.GetString("world-anvil-guide-cost-free", ("color", WorldAnvilGuideColors.ToMarkup(costColor)));
        CostLabel.SetMarkupPermissive(costText);

        if (delay > 0f)
            DelayLabel.SetMarkupPermissive(Loc.GetString("world-anvil-guide-delay", ("delay", delay.ToString("0.#"))));

        if (noteKey != null)
            NoteLabel.SetMarkupPermissive(Loc.GetString(noteKey));
    }

    private GuideEntityEmbed AddEntity(string id, EntityPrototype proto)
    {
        var embed = new GuideEntityEmbed(id, false, false);
        embed.ToolTip = Loc.TryGetString($"ent-{id}", out var name) ? name : proto.Name;
        return embed;
    }
}