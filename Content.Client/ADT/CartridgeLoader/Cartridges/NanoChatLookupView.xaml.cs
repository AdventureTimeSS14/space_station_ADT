using Content.Shared.ADT.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NanoChatLookupView : PanelContainer
{
    private NanoChatUiState? _state;

    public event Action<NanoChatRecipient>? OnStartChat;

    public NanoChatLookupView()
    {
        RobustXamlLoader.Load(this);

        SearchInput.OnTextChanged += _ => RebuildContactList();
    }

    public void FocusSearch()
    {
        SearchInput.GrabKeyboardFocus();
    }

    public void UpdateContactList(NanoChatUiState state)
    {
        _state = state;
        RebuildContactList();
    }

    private void RebuildContactList()
    {
        ContactsList.RemoveAllChildren();

        if (_state == null)
            return;

        if (_state.Contacts is not { } contacts)
        {
            ContactsList.AddChild(new Label { Text = Loc.GetString("nano-chat-look-up-no-server") });
            return;
        }

        var search = SearchInput.Text.Trim().TrimStart('#');
        var atLimit = _state.MaxRecipients <= _state.Recipients.Count;
        var idx = 0;

        foreach (var contact in contacts)
        {
            if (!Matches(contact, search))
                continue;

            var hasChat = _state.Recipients.ContainsKey(contact.Number);

            var nameLabel = new Label
            {
                Text = contact.Name,
                ClipText = true,
            };

            var info = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };
            info.AddChild(nameLabel);

            if (!string.IsNullOrEmpty(contact.JobTitle))
            {
                var jobLabel = new Label
                {
                    Text = contact.JobTitle,
                    ClipText = true,
                };
                jobLabel.AddStyleClass("LabelSubText");
                info.AddChild(jobLabel);
            }

            var numberLabel = new Label
            {
                Text = $"#{contact.Number:D4}",
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(8, 0),
            };

            var startChatButton = new Button
            {
                Text = Loc.GetString(hasChat ? "nano-chat-look-up-open" : "nano-chat-look-up-write"),
                VerticalAlignment = VAlignment.Center,
                MinWidth = 90,
                Disabled = contact.Number == _state.OwnNumber || (!hasChat && atLimit),
            };
            startChatButton.AddStyleClass("OpenBoth");
            startChatButton.OnPressed += _ => OnStartChat?.Invoke(contact);

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(6, 2),
            };
            row.AddChild(info);
            row.AddChild(numberLabel);
            row.AddChild(startChatButton);

            var panel = new PanelContainer
            {
                HorizontalExpand = true,
            };
            panel.AddStyleClass(idx % 2 == 0 ? "PanelBackgroundBaseDark" : "PanelBackgroundLight");
            panel.AddChild(row);

            ContactsList.AddChild(panel);
            idx++;
        }

        if (idx == 0)
        {
            ContactsList.AddChild(new Label
            {
                Text = Loc.GetString("nano-chat-look-up-not-found"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 8),
            });
        }
    }

    private static bool Matches(NanoChatRecipient contact, string search)
    {
        if (search.Length == 0)
            return true;

        return contact.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
               || contact.JobTitle?.Contains(search, StringComparison.CurrentCultureIgnoreCase) == true
               || contact.Number.ToString("D4").Contains(search);
    }
}
