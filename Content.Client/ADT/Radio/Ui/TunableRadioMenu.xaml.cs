using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.Radio;
using Content.Shared.ADT.Radio.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Radio.Ui;

[GenerateTypedNameReferences]
public sealed partial class TunableRadioMenu : FancyWindow
{
    private static readonly Color ScreenBackground = Color.FromHex("#08150F");
    private static readonly Color ScreenBorder = Color.FromHex("#1E3B2B");
    private static readonly Color ScreenText = Color.FromHex("#6EF7A5");
    private static readonly Color IndicatorOn = Color.FromHex("#6EF7A5");
    private static readonly Color IndicatorOff = Color.FromHex("#4A6355");

    private const int CoarseStep = 10;
    private const int FineStep = 1;

    public event Action<int>? OnFrequencyChanged;
    public event Action<bool>? OnMicrophonePressed;
    public event Action<bool>? OnSpeakerPressed;

    private int _frequency;
    private int _minFrequency;
    private int _maxFrequency;
    private bool _locked;

    private bool _refreshing;

    public TunableRadioMenu()
    {
        RobustXamlLoader.Load(this);

        ScreenPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = ScreenBackground,
            BorderColor = ScreenBorder,
            BorderThickness = new Thickness(1),
        };

        FrequencyLabel.FontColorOverride = ScreenText;
        UnitLabel.FontColorOverride = ScreenText;

        CoarseDownButton.Text = "<<";
        FineDownButton.Text = "<";
        FineUpButton.Text = ">";
        CoarseUpButton.Text = ">>";

        CoarseDownButton.OnPressed += _ => Nudge(-CoarseStep);
        FineDownButton.OnPressed += _ => Nudge(-FineStep);
        FineUpButton.OnPressed += _ => Nudge(FineStep);
        CoarseUpButton.OnPressed += _ => Nudge(CoarseStep);

        FrequencySlider.Rounded = true;
        FrequencySlider.OnValueChanged += OnSliderMoved;
        FrequencySlider.OnReleased += OnSliderReleased;

        MicButton.OnPressed += args => OnMicrophonePressed?.Invoke(args.Button.Pressed);
        SpeakerButton.OnPressed += args => OnSpeakerPressed?.Invoke(args.Button.Pressed);
    }

    public void Update(Entity<ADTTunableRadioComponent> entity)
    {
        var comp = entity.Comp;

        _refreshing = true;

        _frequency = comp.Frequency;
        _minFrequency = comp.MinFrequency;
        _maxFrequency = comp.MaxFrequency;
        _locked = comp.Locked;

        FrequencySlider.MaxValue = _maxFrequency;
        FrequencySlider.MinValue = _minFrequency;
        FrequencySlider.SetValueWithoutEvent(_frequency);
        FrequencySlider.Disabled = _locked;

        CoarseDownButton.Disabled = _locked;
        FineDownButton.Disabled = _locked;
        FineUpButton.Disabled = _locked;
        CoarseUpButton.Disabled = _locked;

        FrequencyLabel.Text = ADTRadioFrequency.Format(_frequency);

        MicButton.Pressed = comp.MicrophoneEnabled;
        SpeakerButton.Pressed = comp.SpeakerEnabled;

        MicIndicator.Text = Loc.GetString(comp.MicrophoneEnabled
            ? "adt-tunable-radio-indicator-transmit"
            : "adt-tunable-radio-indicator-standby");
        MicIndicator.FontColorOverride = comp.MicrophoneEnabled ? IndicatorOn : IndicatorOff;

        SpeakerIndicator.Text = Loc.GetString(comp.SpeakerEnabled
            ? "adt-tunable-radio-indicator-speaker-on"
            : "adt-tunable-radio-indicator-speaker-off");
        SpeakerIndicator.FontColorOverride = comp.SpeakerEnabled ? IndicatorOn : IndicatorOff;

        Dial.MinFrequency = _minFrequency;
        Dial.MaxFrequency = _maxFrequency;
        Dial.Frequency = _frequency;
        Dial.Transmitting = comp.MicrophoneEnabled;
        Dial.Listening = comp.SpeakerEnabled;

        _refreshing = false;
    }

    private void OnSliderMoved(Robust.Client.UserInterface.Controls.Range slider)
    {
        if (_refreshing || _locked)
            return;

        Preview((int)MathF.Round(slider.Value));
    }

    private void OnSliderReleased(Slider slider)
    {
        if (_locked)
            return;

        Commit((int)MathF.Round(slider.Value));
    }

    private void Nudge(int delta)
    {
        if (_locked)
            return;

        var frequency = Math.Clamp(_frequency + delta, _minFrequency, _maxFrequency);

        Preview(frequency);

        _refreshing = true;
        FrequencySlider.SetValueWithoutEvent(frequency);
        _refreshing = false;

        Commit(frequency);
    }

    private void Preview(int frequency)
    {
        frequency = Math.Clamp(frequency, _minFrequency, _maxFrequency);

        FrequencyLabel.Text = ADTRadioFrequency.Format(frequency);
        Dial.Frequency = frequency;
    }

    private void Commit(int frequency)
    {
        frequency = Math.Clamp(frequency, _minFrequency, _maxFrequency);
        if (frequency == _frequency)
            return;

        _frequency = frequency;
        OnFrequencyChanged?.Invoke(frequency);
    }
}
