using System.Linq;
using Content.Shared.ADT.Surgery.Events;
using Robust.Client.AutoGenerated;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.ADT.Surgery.UI;

[GenerateTypedNameReferences]
public sealed partial class SurgeryWindow : FancyWindow
{
    public event Action<string>? OnGraphSelected;

    public SurgeryWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void Populate(SurgeryChooseGraphState state)
    {
        OptionsContainer.RemoveAllChildren();

        var first = true;
        foreach (var group in state.Options.GroupBy(o => o.Category))
        {
            if (!first)
            {
                OptionsContainer.AddChild(new HighDivider { Margin = new Thickness(0, 6, 0, 6) });
            }
            first = false;

            if (!string.IsNullOrEmpty(group.Key))
            {
                OptionsContainer.AddChild(new Label
                {
                    Text = group.Key,
                    StyleClasses = { "LabelHeadingBigger" },
                    Margin = new Thickness(2, 0, 0, 4),
                });
            }

            foreach (var subGroup in group.GroupBy(o => o.Subcategory))
            {
                if (!string.IsNullOrEmpty(subGroup.Key))
                {
                    OptionsContainer.AddChild(new Label
                    {
                        Text = subGroup.Key,
                        StyleClasses = { "LabelSubText" },
                        Margin = new Thickness(4, 0, 0, 2),
                    });
                }

                foreach (var (graphId, name, _, _) in subGroup)
                {
                    var button = new Button
                    {
                        Text = name,
                        StyleClasses = { "OpenBoth" },
                        HorizontalExpand = true,
                        MinHeight = 32,
                        Margin = new Thickness(0, 0, 0, 2),
                    };
                    button.OnPressed += _ => OnGraphSelected?.Invoke(graphId);
                    OptionsContainer.AddChild(button);
                }
            }
        }
    }
}
