using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.Surgery.Events;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Surgery.UI;

[GenerateTypedNameReferences]
public sealed partial class SurgeryWindow : FancyWindow
{
    public event Action<string>? OnGraphSelected;
    public event Action<string>? OnEdgeSelected;

    private List<(string GraphId, string Name, string Category, string Subcategory)> _graphs = new();
    private List<(string EdgeId, string Label)> _edges = new();
    private string? _category;
    private bool _edgeMode;

    public SurgeryWindow()
    {
        RobustXamlLoader.Load(this);
        SearchBar.OnTextChanged += _ => Rebuild();
    }

    public void Populate(SurgeryChooseEdgeState state)
    {
        _edgeMode = true;
        _edges = state.Options;
        Title = Loc.GetString("surgery-edge-window-title");
        SubtitleLabel.Text = Loc.GetString("surgery-edge-window-subtitle");
        CategoryPanel.Visible = false;
        SearchBar.Visible = false;
        SearchBar.Text = string.Empty;
        Rebuild();
    }

    public void Populate(SurgeryChooseGraphState state)
    {
        _edgeMode = false;
        _graphs = state.Options;
        Title = Loc.GetString("surgery-window-title");
        SubtitleLabel.Text = Loc.GetString("surgery-window-subtitle");
        CategoryPanel.Visible = true;
        SearchBar.Visible = true;

        if (_category != null && _graphs.All(g => g.Category != _category))
            _category = null;

        BuildCategories();
        Rebuild();
    }

    private void BuildCategories()
    {
        CategoryList.RemoveAllChildren();
        var group = new ButtonGroup();

        AddCategoryButton(group, null, Loc.GetString("surgery-window-category-all"), _graphs.Count);

        foreach (var category in _graphs.Select(g => g.Category).Distinct())
        {
            var name = string.IsNullOrEmpty(category) ? Loc.GetString("surgery-window-category-other") : category;
            AddCategoryButton(group, category, name, _graphs.Count(g => g.Category == category));
        }
    }

    private void AddCategoryButton(ButtonGroup group, string? category, string name, int count)
    {
        var button = new Button
        {
            Text = Loc.GetString("surgery-window-category-entry", ("name", name), ("count", count)),
            ToggleMode = true,
            Group = group,
            StyleClasses = { StyleNano.ButtonOpenRight },
            HorizontalExpand = true,
            ClipText = true,
            Pressed = _category == category,
        };

        button.OnPressed += _ =>
        {
            _category = category;
            Rebuild();
        };

        CategoryList.AddChild(button);
    }

    private void Rebuild()
    {
        OptionsContainer.RemoveAllChildren();

        if (_edgeMode)
        {
            foreach (var (edgeId, label) in _edges)
            {
                OptionsContainer.AddChild(OptionButton(label, () => OnEdgeSelected?.Invoke(edgeId)));
            }

            EmptyLabel.Visible = _edges.Count == 0;
            return;
        }

        var search = SearchBar.Text.Trim();
        var filtered = _graphs
            .Where(g => search.Length > 0 || _category == null || g.Category == _category)
            .Where(g => search.Length == 0 || g.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase))
            .ToList();

        EmptyLabel.Visible = filtered.Count == 0;

        var showCategory = search.Length > 0 || _category == null;
        foreach (var group in filtered.GroupBy(g => showCategory ? g.Category + "/" + g.Subcategory : g.Subcategory))
        {
            var first = group.First();
            var header = showCategory
                ? string.Join(" / ", new[] { first.Category, first.Subcategory }.Where(s => !string.IsNullOrEmpty(s)))
                : first.Subcategory;

            if (!string.IsNullOrEmpty(header))
            {
                OptionsContainer.AddChild(new Label
                {
                    Text = header,
                    StyleClasses = { "LabelSubText" },
                    Margin = new Thickness(2, 4, 0, 0),
                });
            }

            foreach (var (graphId, name, _, _) in group)
            {
                OptionsContainer.AddChild(OptionButton(name, () => OnGraphSelected?.Invoke(graphId)));
            }
        }
    }

    private static Button OptionButton(string text, Action onPressed)
    {
        var button = new Button
        {
            Text = text,
            StyleClasses = { StyleNano.ButtonOpenBoth },
            HorizontalExpand = true,
            ClipText = true,
            MinHeight = 30,
            ToolTip = text,
        };
        button.OnPressed += _ => onPressed();
        return button;
    }
}
