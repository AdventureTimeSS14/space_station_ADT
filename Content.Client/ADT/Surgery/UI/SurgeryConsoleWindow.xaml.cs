using System.Linq;
using Content.Shared.ADT.Body.OrganHealth;
using Content.Shared.ADT.Surgery.Events;
using Robust.Client.AutoGenerated;
using Content.Client.UserInterface.Controls;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.ADT.Surgery.UI;

[GenerateTypedNameReferences]
public sealed partial class SurgeryConsoleWindow : FancyWindow
{
    public event Action<bool>? OnAlertsToggled;

    private bool _updating;

    public SurgeryConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        AlertsCheckBox.OnToggled += args =>
        {
            if (!_updating)
                OnAlertsToggled?.Invoke(args.Pressed);
        };
    }

    public void Populate(SurgeryConsoleState state)
    {
        HealthAnalyzer.Populate(state.PatientHealth);
        PopulateOrgans(state);

        _updating = true;
        AlertsCheckBox.Pressed = state.AlertsEnabled;
        _updating = false;

        OperationsBox.Visible = false;

        if (!state.HasTable)
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-table");
            return;
        }

        if (!state.HasPatient)
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-patient");
            return;
        }

        if (string.IsNullOrEmpty(state.GraphName))
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-operation");
            return;
        }

        StatusLabel.Text = string.Empty;
        OperationsBox.Visible = true;
        LocationLabel.Text = string.IsNullOrEmpty(state.Location) ? state.CurrentNode : state.Location;
        NodeLabel.SetMessage(FormattedMessage.FromUnformatted(state.CurrentNode));
        GraphLabel.SetMessage(FormattedMessage.FromUnformatted(state.GraphName));

        StepsLabel.SetMessage(FormattedMessage.FromUnformatted(FormatSteps(state)));
    }

    private void PopulateOrgans(SurgeryConsoleState state)
    {
        OrgansBox.RemoveAllChildren();
        HeartStoppedLabel.Visible = state.HasPatient && state.HeartStopped;
        HeartStoppedLabel.FontColorOverride = StageColor(OrganStage.Failing);

        if (!state.HasPatient || state.Organs.Count == 0)
        {
            OrgansStatusLabel.Text = Loc.GetString(state.HasPatient ? "surgery-console-organs-none" : "surgery-console-no-patient");
            return;
        }

        OrgansStatusLabel.Text = string.Empty;

        foreach (var organ in state.Organs.OrderBy(o => OrganOrder(o.Category)).ThenBy(o => o.Category))
        {
            OrgansBox.AddChild(CreateOrganRow(organ));
        }
    }

    private static int OrganOrder(string category)
    {
        var index = Array.IndexOf(OrganCategories, category);
        return index < 0 ? OrganCategories.Length : index;
    }

    private static readonly string[] OrganCategories = { "Heart", "Lungs", "Liver", "Kidneys", "Stomach", "Eyes", "Ears", "Tongue" };

    private static Control CreateOrganRow(SurgeryConsoleOrgan organ)
    {
        var color = organ.Missing ? Color.FromHex("#6b6b6b") : StageColor(organ.Stage);
        var name = Loc.GetString($"surgery-console-organ-{organ.Category.ToLowerInvariant()}");
        if (organ.Robotic)
            name += " " + Loc.GetString("surgery-console-organ-cyber");

        var health = organ.Missing ? 0f : Math.Clamp(1f - organ.Damage, 0f, 1f);

        string status;
        if (organ.Missing)
            status = Loc.GetString("surgery-console-organ-missing");
        else
            status = Loc.GetString($"surgery-console-organ-condition-{ConditionKey(organ)}")
                     + " " + Loc.GetString("surgery-console-organ-percent", ("value", (int) Math.Round(health * 100f)));

        var bar = new ProgressBar
        {
            MinValue = 0f,
            MaxValue = 1f,
            Value = health,
            HorizontalExpand = true,
            MinHeight = 10,
            BackgroundStyleBoxOverride = new StyleBoxFlat(Color.FromHex("#1b1b21")),
            ForegroundStyleBoxOverride = new StyleBoxFlat(color),
        };

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        header.AddChild(new Label { Text = name, HorizontalExpand = true, StyleClasses = { "LabelHeading" } });
        header.AddChild(new Label { Text = status, FontColorOverride = color, HorizontalAlignment = Control.HAlignment.Right });

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 4,
            Margin = new Thickness(10, 6, 10, 8),
        };
        content.AddChild(header);
        content.AddChild(bar);

        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#25252c"),
                BorderColor = color,
                BorderThickness = new Thickness(3, 0, 0, 0),
            },
            Children = { content },
        };
    }

    private static string ConditionKey(SurgeryConsoleOrgan organ)
    {
        return organ.Stage switch
        {
            OrganStage.Healthy => "excellent",
            OrganStage.Bruised => "good",
            OrganStage.Damaged => organ.Damage >= 0.725f ? "bad" : "poor",
            _ => "terrible",
        };
    }

    private static Color StageColor(OrganStage stage)
    {
        return stage switch
        {
            OrganStage.Healthy => Color.FromHex("#4cb050"),
            OrganStage.Bruised => Color.FromHex("#d9c53a"),
            OrganStage.Damaged => Color.FromHex("#e68a2e"),
            _ => Color.FromHex("#d13b3b"),
        };
    }

    private static string FormatSteps(SurgeryConsoleState state)
    {
        var labels = state.NextSteps
            .Distinct()
            .Select((label, index) => index == 0 || label.Length == 0 ? label : label.Substring(0, 1).ToLowerInvariant() + label.Substring(1))
            .ToList();

        return string.Join(", ", labels);
    }
}
