using System.Linq;
using Content.Shared.ADT.Surgery.Events;
using Robust.Client.AutoGenerated;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.ADT.Surgery.UI;

[GenerateTypedNameReferences]
public sealed partial class SurgeryConsoleWindow : FancyWindow
{
    public event Action<bool>? OnAlertsToggled;

    private bool _updating;

    public SurgeryConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        AlertsCheckBox.OnToggled += args =>
        {
            if (!_updating)
                OnAlertsToggled?.Invoke(args.Pressed);
        };
    }

    public void Populate(SurgeryConsoleState state)
    {
        HealthAnalyzer.Populate(state.PatientHealth);

        _updating = true;
        AlertsCheckBox.Pressed = state.AlertsEnabled;
        _updating = false;

        OperationsBox.Visible = false;

        if (!state.HasTable)
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-table");
            return;
        }

        if (!state.HasPatient)
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-patient");
            return;
        }

        if (string.IsNullOrEmpty(state.GraphName))
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-operation");
            return;
        }

        StatusLabel.Text = string.Empty;
        OperationsBox.Visible = true;
        LocationLabel.Text = string.IsNullOrEmpty(state.Location) ? state.CurrentNode : state.Location;
        NodeLabel.SetMessage(FormattedMessage.FromUnformatted(state.CurrentNode));
        GraphLabel.SetMessage(FormattedMessage.FromUnformatted(state.GraphName));

        StepsLabel.SetMessage(FormattedMessage.FromUnformatted(FormatSteps(state)));
    }

    private static string FormatSteps(SurgeryConsoleState state)
    {
        var labels = state.NextSteps
            .Select(step => step.Label)
            .Distinct()
            .Select((label, index) => index == 0 || label.Length == 0 ? label : label.Substring(0, 1).ToLowerInvariant() + label.Substring(1))
            .ToList();

        return string.Join(", ", labels);
    }
}
