[GenerateTypedNameReferences]
public sealed partial class SurgeryConsoleWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;
    [Dependency] private readonly IResourceCache _cache = default!;

    private static readonly ResPath DamageIconsRsi = new("/Textures/ADT/Objects/Devices/health_analyzer.rsi");
    private static readonly Vector2 DamageIconSize = new(15, 15);

    private static readonly string[] OrganCategories = { "Brain", "Heart", "Lungs", "Liver", "Kidneys", "Stomach", "Eyes", "Ears", "Tongue" };
    private static readonly string[] LimbCategories = { "ArmLeft", "HandLeft", "ArmRight", "HandRight", "LegLeft", "FootLeft", "LegRight", "FootRight" };
    private static readonly string[] DamageGroupOrder = { "Burn", "Brute", "Airloss", "Toxin", "Genetic" };

    private readonly SpriteSystem _sprite;
    private readonly DamageableSystem _damageable;

    private readonly Font _boldFont;

    public event Action<bool>? OnAlertsToggled;

    private bool _updating;

    public SurgeryConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entManager.System<SpriteSystem>();
        _damageable = _entManager.System<DamageableSystem>();
        _boldFont = _cache.NotoStack(variation: "Bold", size: 13);

        var nameFont = _cache.NotoStack(variation: "Bold", size: 15);
        var valueFont = _cache.NotoStack(variation: "Bold", size: 18);

        EmptyTitleLabel.FontOverride = nameFont;
        PatientNameLabel.FontOverride = nameFont;
        MobStatusLabel.FontOverride = _boldFont;
        RhythmLabel.FontOverride = _boldFont;
        BloodValueLabel.FontOverride = valueFont;
        TemperatureValueLabel.FontOverride = valueFont;
        DamageValueLabel.FontOverride = valueFont;

        BloodBar.BackgroundStyleBoxOverride = new StyleBoxFlat(SurgeryConsoleStyle.Track);

        AlertsCheckBox.OnToggled += args =>
        {
            if (!_updating)
                OnAlertsToggled?.Invoke(args.Pressed);
        };
    }

    public void Populate(SurgeryConsoleState state)
    {
        _updating = true;
        AlertsCheckBox.Pressed = state.AlertsEnabled;
        _updating = false;

        EmptyView.Visible = !state.HasPatient;
        PatientView.Visible = state.HasPatient;

        if (!state.HasPatient)
        {
            EmptyTitleLabel.Text = Loc.GetString(state.HasTable ? "surgery-console-no-patient" : "surgery-console-no-table");
            EmptyHintLabel.Text = Loc.GetString(state.HasTable ? "surgery-console-no-patient-hint" : "surgery-console-no-table-hint");
            PatientSprite.SetEntity(null);
            return;
        }

        var target = _entManager.GetEntity(state.PatientHealth.TargetEntity);
        if (target != null && !_entManager.EntityExists(target))
            target = null;

        PopulateIdentity(target);
        PopulateMonitor(state);
        PopulateBanners(state, target);
        PopulateVitals(state.PatientHealth, target);
        PopulateOperation(state);
        PopulateDamage(target);
        PopulateChemicals(state.PatientHealth.MetabolizingReagents);
        PopulateAddictions(state.PatientHealth.Addictions);
        PopulateOrgans(state);
    }

    private void PopulateIdentity(EntityUid? target)
    {
        PatientSprite.SetEntity(target);

        if (target is not { } patient)
        {
            PatientNameLabel.Text = Loc.GetString("health-analyzer-window-entity-unknown-text");
            SpeciesLabel.Text = Loc.GetString("health-analyzer-window-entity-unknown-species-text");
            MobStatusLabel.Text = Loc.GetString("health-analyzer-window-entity-unknown-text");
            MobStatusLabel.FontColorOverride = SurgeryConsoleStyle.TextDim;
            return;
        }

        PatientNameLabel.Text = Identity.Name(patient, _entManager);
        SpeciesLabel.Text = _entManager.TryGetComponent<HumanoidProfileComponent>(patient, out var humanoid)
            ? Loc.GetString(_prototypes.Index(humanoid.Species).Name)
            : Loc.GetString("health-analyzer-window-entity-unknown-species-text");

        if (_entManager.TryGetComponent<MobStateComponent>(patient, out var mobState))
        {
            MobStatusLabel.Text = MobStatusText(mobState.CurrentState);
            MobStatusLabel.FontColorOverride = SurgeryConsoleStyle.ForMobState(mobState.CurrentState);
        }
        else
        {
            MobStatusLabel.Text = Loc.GetString("health-analyzer-window-entity-unknown-text");
            MobStatusLabel.FontColorOverride = SurgeryConsoleStyle.TextDim;
        }
    }

    private static string MobStatusText(MobState state)
    {
        return state switch
        {
            MobState.Alive => Loc.GetString("health-analyzer-window-entity-alive-text"),
            MobState.SoftCritical => Loc.GetString("health-analyzer-window-entity-soft-critical-text"),
            MobState.Critical => Loc.GetString("health-analyzer-window-entity-critical-text"),
            MobState.Dead => Loc.GetString("health-analyzer-window-entity-dead-text"),
            _ => Loc.GetString("health-analyzer-window-entity-unknown-text"),
        };
    }

    private void PopulateMonitor(SurgeryConsoleState state)
    {
        MonitorBox.Visible = state.Pulse != null;
        if (state.Pulse is not { } pulse)
            return;

        HeartMonitor.Pulse = pulse;
        RhythmLabel.Text = pulse.Describe();
        RhythmLabel.FontColorOverride = SurgeryConsoleStyle.ForPulse(pulse);
    }

    private void PopulateBanners(SurgeryConsoleState state, EntityUid? target)
    {
        BannersBox.RemoveAllChildren();

        if (state.HeartStopped)
            BannersBox.AddChild(CreateBanner(Loc.GetString("surgery-console-heart-stopped"), true));

        if (state.PatientHealth.Unrevivable == true)
            BannersBox.AddChild(CreateBanner(Loc.GetString("surgery-console-banner-unrevivable"), true));

        if (state.PatientHealth.Bleeding == true)
            BannersBox.AddChild(CreateBanner(Loc.GetString("surgery-console-banner-bleeding"), true));

        if (_entManager.HasComponent<AllergicComponent>(target))
            BannersBox.AddChild(CreateBanner(Loc.GetString("health-analyzer-window-entity-allergy-text"), false));

        BannersBox.Visible = BannersBox.ChildCount > 0;
    }

    private Control CreateBanner(string text, bool critical)
    {
        var background = critical ? SurgeryConsoleStyle.CriticalBanner : SurgeryConsoleStyle.WarningBanner;
        var foreground = critical ? SurgeryConsoleStyle.CriticalBannerText : SurgeryConsoleStyle.WarningBannerText;

        return new PanelContainer
        {
            PanelOverride = SurgeryConsoleStyle.Padded(background, 5f),
            Children =
            {
                new Label
                {
                    Text = text,
                    FontOverride = _boldFont,
                    FontColorOverride = foreground,
                    HorizontalAlignment = HAlignment.Center,
                },
            },
        };
    }

    private void PopulateVitals(HealthAnalyzerUiState health, EntityUid? target)
    {
        VitalsPanel.Visible = target != null;
        if (target is not { } patient)
            return;

        if (float.IsNaN(health.BloodLevel))
        {
            BloodValueLabel.Text = Loc.GetString("health-analyzer-window-entity-unknown-value-text");
            BloodValueLabel.FontColorOverride = SurgeryConsoleStyle.TextDim;
            BloodBar.Visible = false;
        }
        else
        {
            var color = SurgeryConsoleStyle.ForBlood(health.BloodLevel);
            BloodValueLabel.Text = Loc.GetString("surgery-console-percent", ("value", (int) Math.Round(health.BloodLevel * 100f)));
            BloodValueLabel.FontColorOverride = color;
            BloodBar.Visible = true;
            BloodBar.Value = health.BloodLevel;
            BloodBar.ForegroundStyleBoxOverride = new StyleBoxFlat(color);
        }

        TemperatureValueLabel.Text = float.IsNaN(health.Temperature)
            ? Loc.GetString("health-analyzer-window-entity-unknown-value-text")
            : $"{health.Temperature - Atmospherics.T0C:F1} °C";

        var damage = _damageable.GetTotalDamage(patient);
        DamageValueLabel.Text = damage.ToString();
        DamageValueLabel.FontColorOverride = SurgeryConsoleStyle.ForDamage((float) damage);
    }

    private void PopulateOperation(SurgeryConsoleState state)
    {
        OperationNameBox.RemoveAllChildren();
        OperationStateBox.RemoveAllChildren();
        NextStepsBox.RemoveAllChildren();

        var selected = !string.IsNullOrEmpty(state.GraphName);
        OperationDetails.Visible = selected;
        OperationLocationLabel.Visible = selected && !string.IsNullOrEmpty(state.Location);

        if (!selected)
        {
            OperationNameBox.AddChild(WrappedText(Loc.GetString("surgery-console-no-operation"), SurgeryConsoleStyle.Text));
            OperationNameBox.AddChild(WrappedText(Loc.GetString("surgery-console-no-operation-hint"), SurgeryConsoleStyle.TextDim));
            return;
        }

        OperationLocationLabel.Text = state.Location;
        OperationNameBox.AddChild(WrappedText(state.GraphName, SurgeryConsoleStyle.Text, true));
        OperationStateBox.AddChild(WrappedText(state.CurrentNode, SurgeryConsoleStyle.Text));

        var steps = state.NextSteps.Distinct().ToList();
        if (steps.Count == 0)
            NextStepsBox.AddChild(WrappedText(Loc.GetString("surgery-console-no-steps"), SurgeryConsoleStyle.TextDim));

        foreach (var step in steps)
        {
            NextStepsBox.AddChild(WrappedText(step, SurgeryConsoleStyle.Signal));
        }
    }

    private static RichTextLabel WrappedText(string text, Color color, bool bold = false)
    {
        var message = new FormattedMessage();
        message.PushColor(color);

        if (bold)
            message.PushTag(new MarkupNode("bold", new MarkupParameter(), null));

        message.AddText(text);

        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(message);
        return label;
    }

    private void PopulateDamage(EntityUid? target)
    {
        DamageBox.RemoveAllChildren();
        DamagePanel.Visible = target != null;

        if (target is not { } patient)
            return;

        var groups = _damageable.GetDamagePerGroup(patient)
            .Where(g => g.Value > 0)
            .OrderBy(g => DamageGroupIndex(g.Key))
            .ToList();

        DamageEmptyLabel.Visible = groups.Count == 0;

        var damagePerType = _damageable.GetAllDamage(patient).DamageDict;

        foreach (var (groupId, amount) in groups)
        {
            var group = _prototypes.Index<DamageGroupPrototype>(groupId);
            DamageBox.AddChild(CreateDamageRow(group.LocalizedName,
                groupId.ToString(),
                amount,
                SurgeryConsoleStyle.Text,
                SurgeryConsoleStyle.ForDamage((float) amount),
                new Thickness(0, 4, 0, 0)));

            foreach (var type in group.DamageTypes)
            {
                if (!damagePerType.TryGetValue(type, out var typeAmount) || typeAmount <= 0)
                    continue;

                DamageBox.AddChild(CreateDamageRow(_prototypes.Index<DamageTypePrototype>(type).LocalizedName,
                    type.ToString(),
                    typeAmount,
                    SurgeryConsoleStyle.TextDim,
                    SurgeryConsoleStyle.TextDim,
                    new Thickness(19, 0, 0, 0)));
            }
        }

        var injuries = ADTInjuryReport.GetLines(_entManager, _prototypes, patient);
        if (injuries.Count > 0)
            DamageEmptyLabel.Visible = false;

        foreach (var injury in injuries)
        {
            DamageBox.AddChild(WrappedText(injury, SurgeryConsoleStyle.Bruised));
        }
    }

    private static int DamageGroupIndex(string groupId)
    {
        var index = Array.IndexOf(DamageGroupOrder, groupId);
        return index < 0 ? DamageGroupOrder.Length : index;
    }

    private Control CreateDamageRow(string name, string iconId, FixedPoint2 amount, Color nameColor, Color amountColor, Thickness margin)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 4,
            Margin = margin,
        };

        row.AddChild(new TextureRect
        {
            SetSize = DamageIconSize,
            Texture = GetDamageIcon(iconId.ToLowerInvariant()),
            VerticalAlignment = VAlignment.Center,
        });
        row.AddChild(new Label { Text = name, FontColorOverride = nameColor, HorizontalExpand = true });
        row.AddChild(new Label { Text = amount.ToString(), FontColorOverride = amountColor });

        return row;
    }

    private Texture GetDamageIcon(string state)
    {
        var rsi = _cache.GetResource<RSIResource>(DamageIconsRsi).RSI;
        return _sprite.Frame0(new SpriteSpecifier.Rsi(DamageIconsRsi, rsi.TryGetState(state, out _) ? state : "unknown"));
    }

    private void PopulateChemicals(List<(string ReagentId, FixedPoint2 Quantity)>? reagents)
    {
        ChemicalsBox.RemoveAllChildren();
        ChemicalsPanel.Visible = reagents is { Count: > 0 };

        if (reagents == null)
            return;

        foreach (var (reagentId, quantity) in reagents.OrderByDescending(r => r.Quantity))
        {
            var name = reagentId;
            var color = SurgeryConsoleStyle.TextDim;

            if (_prototypes.TryIndex<ReagentPrototype>(reagentId, out var reagent))
            {
                name = reagent.LocalizedName;
                color = reagent.SubstanceColor;
            }

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
            };
            row.AddChild(new PanelContainer
            {
                MinWidth = 10,
                MinHeight = 10,
                VerticalAlignment = VAlignment.Center,
                PanelOverride = new StyleBoxFlat(color.WithAlpha(1f)),
            });
            row.AddChild(new Label { Text = name, HorizontalExpand = true, ClipText = true });
            row.AddChild(new Label
            {
                Text = Loc.GetString("surgery-console-units", ("value", quantity)),
                FontColorOverride = SurgeryConsoleStyle.TextDim,
            });

            ChemicalsBox.AddChild(row);
        }
    }

    private void PopulateAddictions(List<AddictionInfo>? addictions)
    {
        AddictionsBox.RemoveAllChildren();
        AddictionsPanel.Visible = addictions is { Count: > 0 };

        if (addictions is not { Count: > 0 })
            return;

        var anyTreatable = false;
        foreach (var addiction in addictions)
        {
            if (!_prototypes.TryIndex<AddictionPrototype>(addiction.Kind, out var kind))
                continue;

            var kindName = Loc.GetString(kind.Name);
            var stageName = Loc.GetString($"health-analyzer-addiction-stage-{addiction.Stage}");
            var line = Loc.GetString(addiction.Permanent ? "health-analyzer-window-addiction-permanent" : "health-analyzer-window-addiction-line",
                ("kind", kindName),
                ("stage", addiction.Stage),
                ("stageName", stageName));

            AddictionsBox.AddChild(WrappedText(line, SurgeryConsoleStyle.Text));

            if (!addiction.Permanent)
                anyTreatable = true;
        }

        AddictionsBox.AddChild(WrappedText(
            Loc.GetString(anyTreatable ? "health-analyzer-window-addictions-treatment" : "health-analyzer-window-addictions-untreatable"),
            SurgeryConsoleStyle.TextDim));
    }

    private void PopulateOrgans(SurgeryConsoleState state)
    {
        OrgansBox.RemoveAllChildren();
        ProsthesesBox.RemoveAllChildren();

        var organs = state.Organs
            .Where(o => !LimbCategories.Contains(o.Category))
            .OrderBy(o => OrderIndex(OrganCategories, o.Category))
            .ThenBy(o => o.Category)
            .ToList();

        OrgansEmptyLabel.Visible = organs.Count == 0;

        foreach (var organ in organs)
        {
            OrgansBox.AddChild(CreateOrganRow(organ));
        }

        var prostheses = state.Organs
            .Where(o => LimbCategories.Contains(o.Category))
            .OrderBy(o => OrderIndex(LimbCategories, o.Category))
            .ToList();

        ProsthesesPanel.Visible = prostheses.Count > 0;

        foreach (var prosthesis in prostheses)
        {
            ProsthesesBox.AddChild(new Label { Text = OrganName(prosthesis.Category) });
        }
    }

    private static int OrderIndex(string[] order, string category)
    {
        var index = Array.IndexOf(order, category);
        return index < 0 ? order.Length : index;
    }

    private static string OrganName(string category)
    {
        return Loc.GetString($"surgery-console-organ-{category.ToLowerInvariant()}");
    }

    private Control CreateOrganRow(SurgeryConsoleOrgan organ)
    {
        var failing = organ.Missing || organ.Stage == OrganStage.Failing;
        var color = organ.Missing ? SurgeryConsoleStyle.Failing : SurgeryConsoleStyle.ForStage(organ.Stage);
        var health = organ.Missing ? 0f : Math.Clamp(1f - organ.Damage, 0f, 1f);

        var name = OrganName(organ.Category);
        if (organ.Robotic)
            name += " " + Loc.GetString("surgery-console-organ-cyber");

        var status = organ.Missing
            ? Loc.GetString("surgery-console-organ-missing")
            : Loc.GetString($"surgery-console-organ-condition-{ConditionKey(organ)}")
              + " " + Loc.GetString("surgery-console-organ-percent", ("value", (int) Math.Round(health * 100f)));

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        header.AddChild(new Label { Text = name, HorizontalExpand = true, ClipText = true });
        header.AddChild(new Label { Text = status, FontColorOverride = color });

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 2,
        };
        content.AddChild(header);
        content.AddChild(new ProgressBar
        {
            MinValue = 0f,
            MaxValue = 1f,
            Value = health,
            HorizontalExpand = true,
            MinHeight = 6,
            BackgroundStyleBoxOverride = new StyleBoxFlat(SurgeryConsoleStyle.Track),
            ForegroundStyleBoxOverride = new StyleBoxFlat(color),
        });

        return new PanelContainer
        {
            PanelOverride = SurgeryConsoleStyle.Padded(failing ? SurgeryConsoleStyle.FailingTint : SurgeryConsoleStyle.Panel, 4f),
            Children = { content },
        };
    }

    private static string ConditionKey(SurgeryConsoleOrgan organ)
    {
        return organ.Stage switch
        {
            OrganStage.Healthy => "excellent",
            OrganStage.Bruised => "good",
            OrganStage.Damaged => organ.Damage >= 0.725f ? "bad" : "poor",
            _ => "terrible",
        };
    }
}
