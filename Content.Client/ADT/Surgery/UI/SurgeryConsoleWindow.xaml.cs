using System.Linq;
using Content.Shared.ADT.Surgery.Events;
using Robust.Client.AutoGenerated;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Surgery.UI;

[GenerateTypedNameReferences]
public sealed partial class SurgeryConsoleWindow : FancyWindow
{
    public SurgeryConsoleWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void Populate(SurgeryConsoleState state)
    {
        HealthAnalyzer.Populate(state.PatientHealth);

        StepsContainer.RemoveAllChildren();

        if (!state.HasTable)
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-table");
            GraphLabel.Text = string.Empty;
            NodeLabel.Text = string.Empty;
            return;
        }

        if (!state.HasPatient)
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-patient");
            GraphLabel.Text = string.Empty;
            NodeLabel.Text = string.Empty;
            return;
        }

        if (string.IsNullOrEmpty(state.GraphName))
        {
            StatusLabel.Text = Loc.GetString("surgery-console-no-operation");
            GraphLabel.Text = string.Empty;
            NodeLabel.Text = string.Empty;
            return;
        }

        StatusLabel.Text = Loc.GetString("surgery-console-status-ok");
        GraphLabel.Text = Loc.GetString("surgery-console-graph", ("name", state.GraphName));
        NodeLabel.Text = Loc.GetString("surgery-console-node", ("node", state.CurrentNode));

        foreach (var (label, toolTags) in state.NextSteps)
        {
            var tools = toolTags.Count == 0
                ? Loc.GetString("surgery-console-any-tool")
                : string.Join(", ", toolTags.Select(LocalizeToolTag));

            StepsContainer.AddChild(new Label
            {
                Text = Loc.GetString("surgery-console-step", ("label", label), ("tools", tools)),
            });
        }
    }

    private static string LocalizeToolTag(string tagId)
    {
        var key = $"surgery-tool-{tagId}";
        return Loc.TryGetString(key, out var loc) ? loc : tagId;
    }
}
