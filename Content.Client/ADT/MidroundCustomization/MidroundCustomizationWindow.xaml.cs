using System.Linq;
using System.Numerics;
using Content.Client.ADT.Bark;
using Content.Client.ADT.SpeechBarks;
using Content.Client.ADT.TTS;
using Content.Client.Corvax.Sponsors;
using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.MidroundCustomization;
using Content.Shared.ADT.SpeechBarks;
using Content.Shared.ADT.TTS;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.MidroundCustomization;

[GenerateTypedNameReferences]
public sealed partial class MidroundCustomizationWindow : DefaultWindow
{
    public Action<string>? OnVoiceChanged;
    public Action<(string Proto, float Pitch, float MinVar, float MaxVar)>? OnBarkChanged;
    public Action<bool>? OnPointLightColorToggled;

    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private readonly SponsorsManager _sponsorsManager = IoCManager.Resolve<SponsorsManager>();
    private readonly SpeechBarksSystem _barkSystem;
    private readonly TTSSystem _ttsSystem;

    private List<TTSVoicePrototype> _voiceList = new();

    private FancyWindow? _barkWindow;
    private string _currentVoice = string.Empty;

    private string _currentBarkProto = string.Empty;
    private float _currentBarkPitch = 1f;
    private float _currentBarkMinVar = 0.1f;
    private float _currentBarkMaxVar = 0.5f;

    private string _pendingBarkProto = string.Empty;
    private float _pendingBarkPitch = 1f;
    private float _pendingBarkMinVar = 0.1f;
    private float _pendingBarkMaxVar = 0.5f;

    public MidroundCustomizationWindow()
    {
        IoCManager.InjectDependencies(this);

        _barkSystem = _entityManager.System<SpeechBarksSystem>();
        _ttsSystem = _entityManager.System<TTSSystem>();

        RobustXamlLoader.Load(this);

        VoiceButton.OnItemSelected += args =>
        {
            VoiceButton.SelectId(args.Id);
            _currentVoice = _voiceList[args.Id].ID;
            OnVoiceChanged?.Invoke(_currentVoice);
        };

        VoicePlayButton.OnPressed += _ => _ttsSystem.RequestPreviewTTS(_currentVoice);

        BarkProtoButton.OnPressed += _ => OpenBarkWindow();
        BarkPlayButton.OnPressed += _ => _barkSystem.PlayDataPreview(_pendingBarkProto, _pendingBarkPitch, _pendingBarkMinVar, _pendingBarkMaxVar);

        PointLightColorCheckBox.OnToggled += args => OnPointLightColorToggled?.Invoke(args.Pressed);

        _voiceList = _prototypeManager
            .EnumeratePrototypes<TTSVoicePrototype>()
            .Where(voice => voice.RoundStart)
            .OrderBy(voice => Loc.GetString(voice.Name))
            .ToList();
    }

    public void UpdateState(MidroundCustomizationUiState state)
    {
        PointLightColorCheckBox.Visible = state.PointLightColor;
        if (state.PointLightColor)
            PointLightColorCheckBox.Pressed = state.PointLightColorEnabled;

        if (state.Voice != null)
        {
            _currentVoice = state.Voice;
            UpdateVoice(state.Sex, state.Species, state.Voice);
            VoiceContainer.Visible = true;
        }
        else
        {
            VoiceContainer.Visible = false;
        }

        if (state.BarkProto != null)
        {
            _currentBarkProto = state.BarkProto;
            _currentBarkPitch = state.BarkPitch;
            _currentBarkMinVar = state.BarkMinVar;
            _currentBarkMaxVar = state.BarkMaxVar;

            if (_barkWindow == null)
            {
                _pendingBarkProto = state.BarkProto;
                _pendingBarkPitch = state.BarkPitch;
                _pendingBarkMinVar = state.BarkMinVar;
                _pendingBarkMaxVar = state.BarkMaxVar;
            }

            UpdateBarkButtonText(_pendingBarkProto);
            BarkContainer.Visible = true;
        }
        else
        {
            BarkContainer.Visible = false;
        }
    }

    private void UpdateVoice(Sex sex, ProtoId<SpeciesPrototype> species, string currentVoice)
    {
        VoiceButton.Clear();

        var firstVoiceChoiceId = -1;
        for (var i = 0; i < _voiceList.Count; i++)
        {
            var voice = _voiceList[i];
            if (!HumanoidCharacterProfile.CanHaveVoice(voice, sex, species))
                continue;

            VoiceButton.AddItem(Loc.GetString(voice.Name), i);

            if (!CanUseVoice(voice))
            {
                VoiceButton.SetItemDisabled(VoiceButton.GetIdx(i), true);
                continue;
            }

            if (firstVoiceChoiceId == -1)
                firstVoiceChoiceId = i;
        }

        var voiceChoiceId = _voiceList.FindIndex(voice => voice.ID == currentVoice);
        if (VoiceButton.TrySelectId(voiceChoiceId))
            return;

        if (firstVoiceChoiceId == -1 || !VoiceButton.TrySelectId(firstVoiceChoiceId))
            return;

        _currentVoice = _voiceList[firstVoiceChoiceId].ID;
        OnVoiceChanged?.Invoke(_currentVoice);
    }

    private bool CanUseVoice(TTSVoicePrototype voice)
    {
        if (!voice.SponsorOnly)
            return true;

        if (!_sponsorsManager.TryGetInfo(out var sponsor))
            return false;

        return sponsor.AllowedMarkings.Contains(voice.ID);
    }

    private void UpdateBarkButtonText(string proto)
    {
        if (!_prototypeManager.TryIndex<BarkPrototype>(proto, out var bark))
        {
            BarkProtoButton.Text = Loc.GetString("humanoid-profile-editor-bark-none");
            return;
        }

        BarkProtoButton.Text = Loc.GetString(bark.Name);
    }

    private void OpenBarkWindow()
    {
        if (_barkWindow != null)
        {
            _barkWindow.Close();
            _barkWindow = null;
        }

        var barkTab = new BarkTab();
        barkTab.SetSelectedBark(_pendingBarkProto, _pendingBarkPitch, _pendingBarkMinVar, _pendingBarkMaxVar);

        barkTab.OnBarkSelected += id =>
        {
            _pendingBarkProto = id;
            UpdateBarkButtonText(id);
        };
        barkTab.OnPitchChanged += pitch => _pendingBarkPitch = pitch;
        barkTab.OnMinVarChanged += minVar => _pendingBarkMinVar = minVar;
        barkTab.OnMaxVarChanged += maxVar => _pendingBarkMaxVar = maxVar;

        _barkWindow = new FancyWindow
        {
            Title = Loc.GetString("humanoid-profile-editor-bark-window-title"),
            MinSize = new Vector2(750, 600),
        };
        _barkWindow.ContentsContainer.AddChild(barkTab);
        _barkWindow.OnClose += () =>
        {
            _barkWindow = null;
            SendBarkIfChanged();
        };
        _barkWindow.OpenCentered();
    }

    private void SendBarkIfChanged()
    {
        if (_pendingBarkProto == _currentBarkProto
            && MathHelper.CloseTo(_pendingBarkPitch, _currentBarkPitch)
            && MathHelper.CloseTo(_pendingBarkMinVar, _currentBarkMinVar)
            && MathHelper.CloseTo(_pendingBarkMaxVar, _currentBarkMaxVar))
        {
            return;
        }

        OnBarkChanged?.Invoke((_pendingBarkProto, _pendingBarkPitch, _pendingBarkMinVar, _pendingBarkMaxVar));
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        _barkWindow?.Close();
        _barkWindow = null;
    }
}
