using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.ClockGreeting;

[GenerateTypedNameReferences]
public sealed partial class ClockGreetingUI : UIWidget
{
    [Dependency] private readonly IResourceCache _resCache = default!;

    public ClockGreetingUI()
    {
        RobustXamlLoader.Load(this);
        Label.FontOverride = _resCache.GetFont("/Fonts/ADT/Specialelite.ttf", 18);
        Label.FontColorOverride = Color.White;
    }

    public void SetText(string text)
    {
        Label.Text = text;
    }
}
