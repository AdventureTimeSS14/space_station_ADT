using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.ADT.OfferItem;

[GenerateTypedNameReferences]
public sealed partial class OfferItemWindow : FancyWindow
{
    public event Action? OnAccept;
    public event Action? OnDecline;

    public OfferItemWindow()
    {
        RobustXamlLoader.Load(this);

        AcceptButton.OnPressed += _ => OnAccept?.Invoke();
        DeclineButton.OnPressed += _ => OnDecline?.Invoke();
    }

    public void SetOffer(string userName, string itemName, EntityUid item)
    {
        ItemView.SetEntity(item);
        OfferText.SetMessage(Loc.GetString("offer-item-window-text",
            ("user", FormattedMessage.EscapeText(userName)),
            ("item", FormattedMessage.EscapeText(itemName))));
    }
}
