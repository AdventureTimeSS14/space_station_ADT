using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.AshWalker;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.AshWalker.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTNecropolisCompassWindow : FancyWindow
{
    public event Action<NetEntity>? OnPointSelected;

    public ADTNecropolisCompassWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetPoints(List<ADTPointOfInterestEntry> points)
    {
        PointList.RemoveAllChildren();

        foreach (var point in points)
        {
            PointList.AddChild(BuildRow(point));
        }
    }

    private Control BuildRow(ADTPointOfInterestEntry point)
    {
        var button = new Button
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 4),
            MinHeight = 40,
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            // Let the click through to the button underneath.
            MouseFilter = MouseFilterMode.Ignore,
        };

        if (point.Proto is { } proto)
        {
            var view = new EntityPrototypeView
            {
                SetSize = new Vector2(32, 32),
                Stretch = SpriteView.StretchMode.Fill,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 6, 0),
            };
            view.SetPrototype(proto);
            row.AddChild(view);
        }

        row.AddChild(new Label
        {
            Text = point.Name,
            VerticalAlignment = VAlignment.Center,
        });

        button.AddChild(row);

        var target = point.Entity;
        button.OnPressed += _ => OnPointSelected?.Invoke(target);

        return button;
    }
}
