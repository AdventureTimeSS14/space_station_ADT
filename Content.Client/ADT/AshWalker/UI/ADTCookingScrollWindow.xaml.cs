using System.Linq;
using Content.Client.Guidebook.Controls;
using Content.Client.UserInterface.Controls;
using Content.Shared.Kitchen;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.ADT.AshWalker.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTCookingScrollWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private readonly List<GuideMicrowaveEmbed> _recipes = new();

    public ADTCookingScrollWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Header.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("adt-cooking-scroll-content")));
        SearchBar.OnTextChanged += args => ApplySearch(args.Text);

        var recipes = _prototype.EnumeratePrototypes<FoodRecipePrototype>()
            .Where(r => (r.RecipeType & (int) MicrowaveRecipeType.TribalOven) != 0 && !r.HideInGuidebook)
            .OrderBy(r => r.Name);

        foreach (var recipe in recipes)
        {
            var embed = new GuideMicrowaveEmbed(recipe);
            _recipes.Add(embed);
            RecipeList.AddChild(embed);
        }
    }

    private void ApplySearch(string query)
    {
        query = query.Trim();

        foreach (var recipe in _recipes)
        {
            recipe.Visible = query.Length == 0 || recipe.CheckMatchesSearch(query);
        }
    }
}
