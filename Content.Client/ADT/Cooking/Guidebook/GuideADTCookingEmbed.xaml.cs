using System.Linq;
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using Content.Shared.ADT.Cooking;
using Content.Shared.ADT.Cooking.Prototypes;
using Content.Shared.Chemistry.Reagent;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.ADT.Cooking.Guidebook;

[GenerateTypedNameReferences]
public sealed partial class GuideADTCookingEmbed : PanelContainer, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private IPrototypeManager _prototype = default!;

    private static readonly Dictionary<ADTCookwareType, EntProtoId> CookwareIcons = new()
    {
        { ADTCookwareType.Pan, "ADTCookwarePan" },
        { ADTCookwareType.Pot, "ADTCookwarePot" },
        { ADTCookwareType.Tray, "ADTCookwareTray" },
        { ADTCookwareType.Plate, "FoodPlate" },
    };

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuideADTCookingEmbed(ADTCookingRecipePrototype recipe)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;

        GenerateHeader(recipe);
        GenerateIngredients(recipe);
        GenerateMethod(recipe);
        GenerateToppings(recipe);
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    private void GenerateHeader(ADTCookingRecipePrototype recipe)
    {
        if (recipe.Result == null)
            return;

        var entity = _prototype.Index<EntityPrototype>(recipe.Result.Value);
        RepresentedPrototype = entity;

        IconContainer.AddChild(new GuideEntityEmbed(recipe.Result.Value, false, false));
        ResultName.SetMarkup(entity.Name);
        ResultDescription.SetMarkup(entity.Description);
    }

    private void GenerateIngredients(ADTCookingRecipePrototype recipe)
    {
        foreach (var (reagentId, amount) in recipe.Reagents.OrderByDescending(p => p.Value))
        {
            AddReagent(reagentId, amount);
        }

        foreach (var ingredient in recipe.Ingredients)
        {
            if (ingredient.Id != null && _prototype.TryIndex<EntityPrototype>(ingredient.Id.Value, out var proto))
            {
                IngredientsGrid.AddChild(new GuideEntityEmbed(ingredient.Id.Value, false, false));

                var name = new GuidebookRichPrototypeLink();
                name.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("guidebook-microwave-solid-name-display", ("ingredient", proto.Name))));
                name.LinkedPrototype = proto;
                IngredientsGrid.AddChild(name);
            }
            else if (ingredient.Tag != null)
            {
                IngredientsGrid.AddChild(new Control());

                var name = new RichTextLabel();
                name.SetMarkup(Loc.GetString("adt-guidebook-cooking-tag", ("tag", ingredient.Tag.Value.Id)));
                IngredientsGrid.AddChild(name);
            }
            else
            {
                continue;
            }

            var count = new RichTextLabel();
            count.SetMarkup(Loc.GetString("guidebook-microwave-solid-quantity-display", ("amount", ingredient.Count)));
            IngredientsGrid.AddChild(count);
        }
    }

    private void AddReagent(ProtoId<ReagentPrototype> reagentId, FixedPoint2 amount)
    {
        if (!_prototype.TryIndex(reagentId, out var reagent))
            return;

        var color = new GuidebookRichPrototypeLink();
        color.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("guidebook-microwave-reagent-color-display", ("color", reagent.SubstanceColor))));
        color.HorizontalAlignment = HAlignment.Center;
        color.LinkedPrototype = reagent;
        IngredientsGrid.AddChild(color);

        var name = new RichTextLabel();
        name.SetMarkup(Loc.GetString("guidebook-microwave-reagent-name-display", ("reagent", reagent.LocalizedName)));
        IngredientsGrid.AddChild(name);

        var quantity = new RichTextLabel();
        quantity.SetMarkup(Loc.GetString("guidebook-microwave-reagent-quantity-display", ("amount", amount)));
        IngredientsGrid.AddChild(quantity);
    }

    private void GenerateToppings(ADTCookingRecipePrototype recipe)
    {
        if (recipe.MaxToppings <= 0)
            return;

        var names = new List<string>();
        foreach (var tag in recipe.ToppingTags)
        {
            names.Add(Loc.TryGetString($"adt-cooking-topping-tag-{tag.Id}", out var tagName) ? tagName : tag.Id);
        }

        foreach (var id in recipe.ToppingIds)
        {
            if (_prototype.TryIndex<EntityPrototype>(id, out var proto) && !names.Contains(proto.Name))
                names.Add(proto.Name);
        }

        var lines = new List<string>
        {
            Loc.GetString("adt-guidebook-cooking-toppings", ("toppings", string.Join(", ", names)), ("max", recipe.MaxToppings)),
        };

        foreach (var variant in recipe.ToppingResults)
        {
            if (!_prototype.TryIndex<EntityPrototype>(variant.Result, out var result))
                continue;

            var toppingNames = variant.Toppings
                .Select(t => _prototype.TryIndex<EntityPrototype>(t, out var p) ? p.Name : t.Id)
                .Distinct()
                .ToList();

            lines.Add(Loc.GetString("adt-guidebook-cooking-topping-result",
                ("toppings", string.Join(Loc.GetString("adt-guidebook-cooking-or"), toppingNames)),
                ("result", result.Name)));
        }

        ToppingsLabel.SetMarkup(string.Join("\n", lines));
    }

    private void GenerateMethod(ADTCookingRecipePrototype recipe)
    {
        if (CookwareIcons.TryGetValue(recipe.Cookware, out var icon) && _prototype.HasIndex<EntityPrototype>(icon))
            CookwareContainer.AddChild(new GuideEntityEmbed(icon, false, false));

        MethodLabel.SetMarkup(Loc.GetString("adt-guidebook-cooking-method",
            ("method", Loc.GetString($"adt-cooking-method-{recipe.Method.ToString().ToLowerInvariant()}")),
            ("time", recipe.Time)));

        if (recipe.Method == ADTCookingMethod.Raw)
        {
            MethodLabel.SetMarkup(Loc.GetString("adt-guidebook-cooking-raw"));
            return;
        }

        var media = recipe.PreferredMedia
            .Select(m => _prototype.TryIndex(m, out var medium) && _prototype.TryIndex(medium.Reagent, out var reagent) ? reagent.LocalizedName : null)
            .Where(n => n != null)
            .ToList();

        if (media.Count > 0)
            MediumLabel.SetMarkup(Loc.GetString("adt-guidebook-cooking-media", ("media", string.Join(", ", media))));
        else if (recipe.Method == ADTCookingMethod.Boiled)
            MediumLabel.SetMarkup(Loc.GetString("adt-guidebook-cooking-water"));
    }
}
