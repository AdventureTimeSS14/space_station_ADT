using System.Linq;
using System.Numerics;
using Content.Client.Lobby.UI.ProfileEditorControls;
using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.BodyTypes;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Utility;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class BodyTypeWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototype = default!;

    public event Action<ProtoId<BodyTypePrototype>?>? OnBodyTypeSelected;

    private readonly List<BodyTypeOption> _options = new();
    private ProtoId<SpeciesPrototype>? _species;
    private Direction _direction = Direction.South;
    private JobPrototype? _job;
    private bool _showClothes;

    public BodyTypeWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        RotateLeftButton.OnPressed += _ => SetDirection(_direction.TurnCw());
        RotateRightButton.OnPressed += _ => SetDirection(_direction.TurnCcw());
    }

    public static List<BodyTypePrototype> GetBodyTypes(IPrototypeManager prototype, ProtoId<SpeciesPrototype> species)
    {
        return prototype.EnumeratePrototypes<BodyTypePrototype>()
            .Where(bodyType => bodyType.Species.Contains(species))
            .OrderBy(bodyType => bodyType.Order)
            .ThenBy(bodyType => bodyType.ID)
            .ToList();
    }

    public void LoadPreview(HumanoidCharacterProfile profile, JobPrototype? job, bool showClothes)
    {
        _job = job;
        _showClothes = showClothes;

        if (_species != profile.Species)
            BuildOptions(profile);

        foreach (var option in _options)
        {
            option.View.LoadPreview(WithBodyType(profile, option.BodyType), _job, _showClothes);
            option.Button.Pressed = option.BodyType == profile.Appearance.BodyType;
        }
    }

    public void SetProfile(HumanoidCharacterProfile profile)
    {
        if (_species != profile.Species)
        {
            LoadPreview(profile, _job, _showClothes);
            return;
        }

        foreach (var option in _options)
        {
            option.View.ReloadProfilePreview(WithBodyType(profile, option.BodyType));
            option.Button.Pressed = option.BodyType == profile.Appearance.BodyType;
        }
    }

    private static HumanoidCharacterProfile WithBodyType(HumanoidCharacterProfile profile, ProtoId<BodyTypePrototype>? bodyType)
    {
        return profile.WithCharacterAppearance(profile.Appearance.WithBodyType(bodyType));
    }

    private void BuildOptions(HumanoidCharacterProfile profile)
    {
        ClearOptions();
        _species = profile.Species;

        var group = new ButtonGroup();

        AddOption(null, Loc.GetString("body-type-default"), group);
        foreach (var bodyType in GetBodyTypes(_prototype, profile.Species))
        {
            AddOption(bodyType.ID, Loc.GetString(bodyType.Name), group);
        }
    }

    private void AddOption(ProtoId<BodyTypePrototype>? bodyType, string name, ButtonGroup group)
    {
        var view = new ProfilePreviewSpriteView
        {
            Scale = new Vector2(4, 4),
            OverrideDirection = _direction,
            SetSize = new Vector2(128, 128),
        };

        var preview = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#1B1B1E") },
        };
        preview.AddChild(view);

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(4),
        };
        content.AddChild(preview);
        content.AddChild(new Label
        {
            Text = name,
            HorizontalAlignment = HAlignment.Center,
        });

        var button = new Button
        {
            ToggleMode = true,
            Group = group,
        };
        button.AddChild(content);
        button.OnPressed += _ => OnBodyTypeSelected?.Invoke(bodyType);

        OptionsContainer.AddChild(button);
        _options.Add(new BodyTypeOption(bodyType, view, button));
    }

    private void SetDirection(Direction direction)
    {
        _direction = direction;

        foreach (var option in _options)
        {
            option.View.OverrideDirection = _direction;
        }
    }

    private void ClearOptions()
    {
        foreach (var option in _options)
        {
            option.View.ClearPreview();
        }

        _options.Clear();
        OptionsContainer.RemoveAllChildren();
        _species = null;
    }

    public override void Close()
    {
        base.Close();
        ClearOptions();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            ClearOptions();
    }

    private readonly record struct BodyTypeOption(
        ProtoId<BodyTypePrototype>? BodyType,
        ProfilePreviewSpriteView View,
        Button Button);
}
