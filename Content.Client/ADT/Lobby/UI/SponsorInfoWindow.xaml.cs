[GenerateTypedNameReferences]
[UsedImplicitly]
public sealed partial class SponsorInfoWindow : DefaultWindow
{
    [Dependency] private readonly SponsorsManager _sponsorsManager = default!;
    [Dependency] private readonly IPlayerManager _player = default!;
    [Dependency] private readonly IUriOpener _uriOpener = default!;
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IEntityManager _entMan = default!;

    private readonly Content.Client.ADT.Sponsors.SponsorManager _adtSponsors;

    private static readonly Color ColorActive = Color.FromHex("#66CCFF");
    private static readonly Color ColorInactive = Color.FromHex("#AB3232");
    private static readonly Color ColorYes = Color.FromHex("#7CC576");
    private static readonly Color ColorNo = Color.FromHex("#8A8A8A");
    private static readonly Color RowColor = Color.FromHex("#2F2F3B");
    private static readonly Color RowColorAlt = Color.FromHex("#292B38");

    private const int MaxNames = 3;
    private const float LabelRatio = 3f;
    private const float ValueRatio = 2f;
    private const int DaysInMonth = 30;
    private int _rowIndex;

    public bool HasSponsor { get; private set; }
    public SponsorInfo? SponsorInfo { get; private set; }

    private readonly string _userName;

    public SponsorInfoWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _adtSponsors = IoCManager.Resolve<Content.Client.ADT.Sponsors.SponsorManager>();
        _userName = _player.LocalSession?.Name ?? Loc.GetString("ui-lobby-sponsor-menu-unknown");

        ButtonSiteBoosty.ModulateSelfOverride = Color.FromHex("#a68202");
        ButtonSiteBoosty.OnPressed += _ =>
        {
            var url = _cfg.GetCVar(CCVars.InfoLinksWebsite);
            _uriOpener.OpenUri(url);
        };

        ButtonSponsorColors.OnPressed += _ =>
        {
            new Content.Client.ADT.Sponsors.UI.SponsorColorsWindow(_adtSponsors).OpenCentered();
        };

        _adtSponsors.Updated += UpdateSponsorInfo;

        UpdateSponsorInfo();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _adtSponsors.Updated -= UpdateSponsorInfo;
    }

    private void UpdateSponsorInfo()
    {
        var data = _adtSponsors.Data;
        var hasLegacy = _sponsorsManager.TryGetInfo(out var legacy);

        SponsorInfo = legacy;
        HasSponsor = data.HasAnyBenefit || hasLegacy;

        ButtonSponsorColors.Visible = data.AllowCustomOocColor
                                      || data.AllowCustomGhostColor
                                      || data.GhostColors.Count > 0;

        PlayerNameLabel.Text = _userName;
        TiersContainer.RemoveAllChildren();
        BenefitsContainer.RemoveAllChildren();

        SetBadge(HasSponsor);

        if (data.HasAnyBenefit)
        {
            BuildTiers(data);
            BuildBenefits(data);
            return;
        }

        if (hasLegacy && legacy != null)
        {
            BuildLegacy(legacy);
            return;
        }

        BuildEmpty();
    }

    private void SetBadge(bool active)
    {
        var color = active ? ColorActive : ColorInactive;

        StatusBadgePanel.PanelOverride = new StyleBoxFlat(color.WithAlpha(0.25f));
        StatusBadgeLabel.FontColorOverride = color;
        StatusBadgeLabel.Text = Loc.GetString(active
            ? "adt-sponsor-info-badge-active"
            : "adt-sponsor-info-badge-none");
    }

    private void BuildTiers(SponsorData data)
    {
        if (data.Tiers.Count == 0)
        {
            TiersContainer.AddChild(MakeWeakLabel(Loc.GetString("adt-sponsor-info-custom-grant")));
            return;
        }

        foreach (var tier in data.Tiers)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
            };

            row.AddChild(new Label
            {
                Text = tier.DisplayName,
                FontColorOverride = ColorActive,
            });

            var until = tier.ExpiresAt == null
                ? Loc.GetString("adt-sponsor-info-forever")
                : Loc.GetString("adt-sponsor-info-until",
                    ("date", tier.ExpiresAt.Value.ToLocalTime().ToString("dd.MM.yyyy")));

            row.AddChild(MakeWeakLabel(until));
            TiersContainer.AddChild(row);
        }
    }

    private void BuildBenefits(SponsorData data)
    {
        AddSection(Loc.GetString("adt-sponsor-info-section-roles"));

        var bypassJobs = (data.RoleBypass & SponsorRoleBypass.Jobs) != 0;
        AddFlagRow(Loc.GetString("adt-sponsor-info-row-bypass-jobs"), bypassJobs);
        AddFlagRow(Loc.GetString("adt-sponsor-info-row-bypass-antags"),
            (data.RoleBypass & SponsorRoleBypass.Antags) != 0);

        if (bypassJobs && data.ExcludedDepartments.Count > 0)
        {
            AddRow(Loc.GetString("adt-sponsor-info-row-excluded-departments"),
                DescribeSet(data.ExcludedDepartments, false, ResolveDepartmentName));
        }

        if (bypassJobs && data.ExcludedJobs.Count > 0)
        {
            AddRow(Loc.GetString("adt-sponsor-info-row-excluded-jobs"),
                DescribeSet(data.ExcludedJobs, false, ResolveJobName));
        }

        AddSection(Loc.GetString("adt-sponsor-info-section-customization"));

        AddRow(Loc.GetString("adt-sponsor-info-row-loadouts"),
            DescribeSet(data.Loadouts, data.AllLoadouts, ResolveLoadoutName));
        AddRow(Loc.GetString("adt-sponsor-info-row-markings"),
            DescribeSet(data.Markings, data.AllMarkings, ResolveMarkingName));
        AddRow(Loc.GetString("adt-sponsor-info-row-species"),
            DescribeSet(data.Species, false, ResolveSpeciesName));
        AddRow(Loc.GetString("adt-sponsor-info-row-traits"),
            DescribeSet(data.Traits, false, ResolveTraitName));
        AddRow(Loc.GetString("adt-sponsor-info-row-tts"),
            DescribeSet(data.TtsVoices, data.AllTtsVoices, ResolveVoiceName));

        AddSection(Loc.GetString("adt-sponsor-info-section-chat"));

        if (data.OocColor != null)
        {
            AddColorsRow(Loc.GetString("adt-sponsor-info-row-ooc"), new[] { data.OocColor.Value });
        }
        else
        {
            AddRow(Loc.GetString("adt-sponsor-info-row-ooc"), Loc.GetString("adt-sponsor-info-none"), ColorNo);
        }

        AddFlagRow(Loc.GetString("adt-sponsor-info-row-ooc-custom"), data.AllowCustomOocColor);

        if (data.AllowCustomGhostColor)
        {
            AddRow(Loc.GetString("adt-sponsor-info-row-ghost"), Loc.GetString("adt-sponsor-info-any-color"), ColorYes);
        }
        else
        {
            AddColorsRow(Loc.GetString("adt-sponsor-info-row-ghost"), data.GhostColors);
        }

        AddSection(Loc.GetString("adt-sponsor-info-section-other"));

        AddFlagRow(Loc.GetString("adt-sponsor-info-row-priority"), data.PriorityJoin);
        AddRow(Loc.GetString("adt-sponsor-info-row-slots"),
            data.ExtraCharacterSlots > 0 ? $"+{data.ExtraCharacterSlots}" : Loc.GetString("adt-sponsor-info-none"),
            data.ExtraCharacterSlots > 0 ? ColorYes : ColorNo);

        if (data.NextExpiry != null)
            AddHint(FormatCountdown(data.NextExpiry.Value));
    }

    private static string FormatCountdown(DateTime expiryUtc)
    {
        var left = expiryUtc - DateTime.UtcNow;

        if (left <= TimeSpan.Zero)
            return Loc.GetString("adt-sponsor-info-expiry-passed");

        if (left < TimeSpan.FromMinutes(1))
            return Loc.GetString("adt-sponsor-info-expiry-soon");

        return Loc.GetString("adt-sponsor-info-next-expiry", ("left", DescribeSpan(left)));
    }

    private static string DescribeSpan(TimeSpan left)
    {
        if (left < TimeSpan.FromHours(1))
            return Loc.GetString("adt-sponsor-info-span-minutes", ("count", (int) left.TotalMinutes));

        if (left < TimeSpan.FromDays(1))
            return Loc.GetString("adt-sponsor-info-span-hours", ("count", (int) left.TotalHours));

        if (left < TimeSpan.FromDays(DaysInMonth))
            return Loc.GetString("adt-sponsor-info-span-days", ("count", (int) left.TotalDays));

        return Loc.GetString("adt-sponsor-info-span-months", ("count", (int) (left.TotalDays / DaysInMonth)));
    }

    private void BuildLegacy(SponsorInfo legacy)
    {
        TiersContainer.AddChild(MakeWeakLabel(Loc.GetString("adt-sponsor-info-legacy-hint")));

        AddSection(Loc.GetString("adt-sponsor-info-section-subscription"));

        AddRow(Loc.GetString("adt-sponsor-info-row-legacy-tier"),
            legacy.Tier?.ToString() ?? Loc.GetString("adt-sponsor-info-none"),
            ColorActive);
        AddRow(Loc.GetString("adt-sponsor-info-row-expires"),
            legacy.ExpireDate.ToLocalTime().ToString("dd.MM.yyyy"));

        AddSection(Loc.GetString("adt-sponsor-info-section-chat"));

        var legacyOoc = Color.TryFromHex(legacy.OOCColor ?? string.Empty);

        if (legacyOoc != null)
        {
            AddColorsRow(Loc.GetString("adt-sponsor-info-row-ooc"), new[] { legacyOoc.Value });
        }
        else
        {
            AddRow(Loc.GetString("adt-sponsor-info-row-ooc"), Loc.GetString("adt-sponsor-info-none"), ColorNo);
        }

        AddSection(Loc.GetString("adt-sponsor-info-section-customization"));

        AddRow(Loc.GetString("adt-sponsor-info-row-markings"),
            DescribeSet(legacy.AllowedMarkings, false, ResolveMarkingName));

        AddSection(Loc.GetString("adt-sponsor-info-section-other"));

        AddFlagRow(Loc.GetString("adt-sponsor-info-row-allow-job"), legacy.AllowJob);
        AddFlagRow(Loc.GetString("adt-sponsor-info-row-priority"), legacy.HavePriorityJoin);
        AddRow(Loc.GetString("adt-sponsor-info-row-slots"),
            legacy.ExtraSlots > 0 ? $"+{legacy.ExtraSlots}" : Loc.GetString("adt-sponsor-info-none"),
            legacy.ExtraSlots > 0 ? ColorYes : ColorNo);
    }

    private void BuildEmpty()
    {
        TiersContainer.AddChild(MakeWeakLabel(Loc.GetString("adt-sponsor-info-no-sponsor")));

        BenefitsContainer.AddChild(new Label
        {
            Text = Loc.GetString("adt-sponsor-info-no-sponsor-hint"),
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, 24, 0, 6),
        });
    }

    private void AddSection(string title)
    {
        _rowIndex = 0;

        BenefitsContainer.AddChild(new Label
        {
            Text = title,
            StyleClasses = { StyleClass.LabelHeading },
            Margin = new Thickness(0, 10, 0, 2),
        });

        BenefitsContainer.AddChild(new PanelContainer
        {
            StyleClasses = { StyleClass.LowDivider },
            SetHeight = 2,
            Margin = new Thickness(0, 0, 0, 2),
        });
    }

    private void AddRow(string label, string value, Color? valueColor = null)
    {
        var row = MakeRow(label);

        var valueLabel = new Label
        {
            Text = value,
            SizeFlagsStretchRatio = ValueRatio,
            HorizontalExpand = true,
            ClipText = true,
            Margin = new Thickness(6, 4),
        };

        if (valueColor != null)
            valueLabel.FontColorOverride = valueColor;

        row.AddChild(valueLabel);
    }

    private void AddFlagRow(string label, bool enabled)
    {
        var text = Loc.GetString(enabled ? "adt-sponsor-info-yes" : "adt-sponsor-info-no");
        AddRow(label, text, enabled ? ColorYes : ColorNo);
    }

    private void AddColorsRow(string label, IReadOnlyList<Color> colors)
    {
        if (colors.Count == 0)
        {
            AddRow(label, Loc.GetString("adt-sponsor-info-none"), ColorNo);
            return;
        }

        var row = MakeRow(label);

        var swatches = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 3,
            SizeFlagsStretchRatio = ValueRatio,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(6, 4),
        };

        foreach (var color in colors)
        {
            swatches.AddChild(new PanelContainer
            {
                MinSize = new Vector2(28, 14),
                PanelOverride = new StyleBoxFlat(color),
                ToolTip = color.ToHex(),
            });
        }

        row.AddChild(swatches);
    }

    private void AddHint(string text)
    {
        BenefitsContainer.AddChild(new Label
        {
            Text = text,
            StyleClasses = { StyleClass.LabelSubText },
            Margin = new Thickness(8, 10, 0, 0),
        });
    }

    private BoxContainer MakeRow(string label)
    {
        var background = _rowIndex++ % 2 == 0 ? RowColor : RowColorAlt;

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 0,
        };

        content.AddChild(new Label
        {
            Text = label,
            SizeFlagsStretchRatio = LabelRatio,
            HorizontalExpand = true,
            ClipText = true,
            Margin = new Thickness(6, 4),
            StyleClasses = { StyleClass.LabelSubText },
        });

        content.AddChild(new VSeparator());

        var panel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(background),
        };

        panel.AddChild(content);
        BenefitsContainer.AddChild(panel);

        return content;
    }

    private static Label MakeWeakLabel(string text)
    {
        return new Label
        {
            Text = text,
            StyleClasses = { StyleClass.LabelSubText },
        };
    }

    private string DescribeSet(IReadOnlyCollection<string> ids, bool all, Func<string, string?> resolve)
    {
        if (all)
            return Loc.GetString("adt-sponsor-info-all");

        if (ids.Count == 0)
            return Loc.GetString("adt-sponsor-info-none");

        var names = ids
            .Select(id => resolve(id) ?? id)
            .OrderBy(name => name)
            .ToList();

        if (names.Count <= MaxNames)
            return string.Join(", ", names);

        var shown = string.Join(", ", names.Take(MaxNames));
        return $"{shown}, {Loc.GetString("adt-sponsor-info-more", ("count", names.Count - MaxNames))}";
    }

    private string? ResolveDepartmentName(string id)
    {
        if (!_proto.TryIndex<DepartmentPrototype>(id, out var proto))
            return null;

        return Loc.GetString(proto.Name);
    }

    private string? ResolveJobName(string id)
    {
        if (!_proto.TryIndex<JobPrototype>(id, out var proto))
            return null;

        return proto.LocalizedName;
    }

    private string? ResolveLoadoutName(string id)
    {
        if (!_proto.TryIndex<LoadoutPrototype>(id, out var proto))
            return null;

        if (_entMan.EntitySysManager.TryGetEntitySystem<LoadoutSystem>(out var loadouts))
            return loadouts.GetName(proto);

        return proto.ID;
    }

    private string? ResolveMarkingName(string id)
    {
        if (!_proto.HasIndex<MarkingPrototype>(id))
            return null;

        return Loc.GetString($"marking-{id}");
    }

    private string? ResolveSpeciesName(string id)
    {
        if (!_proto.TryIndex<SpeciesPrototype>(id, out var proto))
            return null;

        return Loc.GetString(proto.Name);
    }

    private string? ResolveTraitName(string id)
    {
        if (!_proto.TryIndex<TraitPrototype>(id, out var proto))
            return null;

        return Loc.GetString(proto.Name);
    }

    private string? ResolveVoiceName(string id)
    {
        if (!_proto.TryIndex<TTSVoicePrototype>(id, out var proto))
            return null;

        return proto.Name;
    }
}
