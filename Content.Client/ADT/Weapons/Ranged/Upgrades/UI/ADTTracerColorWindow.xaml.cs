using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Weapons.Ranged.Upgrades.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTTracerColorWindow : DefaultWindow
{
    public event Action<Color>? OnColorSelected;

    public ADTTracerColorWindow()
    {
        RobustXamlLoader.Load(this);

        ColorSelector.OnColorChanged += color => OnColorSelected?.Invoke(color);
    }

    public void SetColor(Color color)
    {
        ColorSelector.Color = color;
    }
}
