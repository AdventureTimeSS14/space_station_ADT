using Content.Client.UserInterface.Controls;
using Content.Shared.Humanoid;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Dissociative;

[GenerateTypedNameReferences]
public sealed partial class DissociativeAlterSetupWindow : FancyWindow
{
    public event Action<Sex>? OnSexSelected;
    public event Action? OnCustomize;
    public event Action<string>? OnConfirm;

    private static readonly Sex[] Sexes = { Sex.Male, Sex.Female, Sex.Unsexed };

    private bool _nameSet;

    public DissociativeAlterSetupWindow()
    {
        RobustXamlLoader.Load(this);

        for (var i = 0; i < Sexes.Length; i++)
        {
            SexSelector.AddItem(Loc.GetString($"dissociative-setup-sex-{Sexes[i].ToString().ToLowerInvariant()}"), i);
        }

        SexSelector.OnItemSelected += args =>
        {
            SexSelector.SelectId(args.Id);
            OnSexSelected?.Invoke(Sexes[args.Id]);
        };

        CustomizeButton.OnPressed += _ => OnCustomize?.Invoke();
        ConfirmButton.OnPressed += _ => OnConfirm?.Invoke(NameEdit.Text);
    }

    public void UpdateState(string name, Sex sex)
    {
        if (!_nameSet)
        {
            NameEdit.Text = name;
            _nameSet = true;
        }

        SexSelector.SelectId(Array.IndexOf(Sexes, sex));
    }
}
