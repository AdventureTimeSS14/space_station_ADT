using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.Xenobiology.UI;

/// <summary>
/// On-screen counter shown to the pilot of a xenobiology console.
/// Top number is the monkey cube stock, bottom is stored slimes out of capacity.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class XenobiologyConsoleStatusControl : Control
{
    [Dependency] private readonly IResourceCache _resources = default!;

    public XenobiologyConsoleStatusControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        var counterFont = _resources.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 10);
        BiomassLabel.FontOverride = counterFont;
        SlimeLabel.FontOverride = counterFont;
    }

    public void UpdateState(int storedSlimes, int maxStoredSlimes, int monkeyCubes)
    {
        BiomassLabel.Text = monkeyCubes.ToString();
        SlimeLabel.Text = $"{storedSlimes}/{maxStoredSlimes}";
    }
}
