[GenerateTypedNameReferences]
public sealed partial class UITab : Control
{
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IEntitySystemManager _entSysMan = default!;

    public UITab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var themes = _prototypeManager.EnumeratePrototypes<HudThemePrototype>().ToList();
        themes.Sort();
        var themeEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var gear in themes)
        {
            themeEntries.Add(new OptionDropDownCVar<string>.ValueOption(gear.ID, Loc.GetString(gear.Name)));
        }

        var layoutEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var layout in Enum.GetValues(typeof(ScreenType)))
        {
            layoutEntries.Add(new OptionDropDownCVar<string>.ValueOption(layout.ToString()!, Loc.GetString($"ui-options-hud-layout-{layout.ToString()!.ToLower()}")));
        }

        var rangedSights = new List<OptionDropDownCVar<string>.ValueOption>();
        var meleeSights = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var sight in _prototypeManager.EnumeratePrototypes<SightPrototype>())
        {
            var option = new OptionDropDownCVar<string>.ValueOption(sight.ID, Loc.GetString(sight.Name));
            if (sight.Bolt)
                continue;
            switch (sight.SightType)
            {
                case SightType.Ranged:
                    rangedSights.Add(option);
                    break;
                case SightType.Melee:
                    meleeSights.Add(option);
                    break;
                case SightType.Universal:
                    meleeSights.Add(option);
                    rangedSights.Add(option);
                    break;
            }
        }

        SightsOptionsHash.OnTextChanged += OnTextChanged;

        Control.AddOptionDropDown(CVars.InterfaceTheme, DropDownHudTheme, themeEntries);
        Control.AddOptionDropDown(CCVars.UILayout, DropDownHudLayout, layoutEntries);
        Control.AddOptionSlider(ADTCCVars.ChatSeparatedMinWidth, SeparatedChatWidthSlider, 300, 580);
        Control.AddOptionDropDown(ADTCCVars.RangedSight, DropDownRangedSight, rangedSights);
        Control.AddOptionDropDown(ADTCCVars.MeleeSight, DropDownMeleeSight, meleeSights);
        Control.AddOptionSlider(ADTCCVars.RangedSightScale, RangedSightScaleSlider, 10, 100);
        Control.AddOptionSlider(ADTCCVars.RangedSightOffset, RangedSightOffsetSlider, 0, 100);
        Control.AddOptionCheckBox(ADTCCVars.RangedSightRotation, RangedSightRotationCheckBox);
        Control.AddOptionCheckBox(ADTCCVars.MeleeSightRotation, MeleeSightRotationCheckBox);
        Control.AddOptionDropDown(
            ADTCCVars.HeldItemShowMode,
            DropDownHeldItemShowMode,
            [
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.Always, Loc.GetString("ui-options-held-item-show-always")),
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.CombatModeOnly, Loc.GetString("ui-options-held-item-show-combat")),
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.OutsideCombatModeOnly, Loc.GetString("ui-options-held-item-show-outside-combat")),
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.Never, Loc.GetString("ui-options-held-item-show-never")),
            ]);
        Control.AddOptionCheckBox(ADTCCVars.SightShowBoltIndicator, SightBoltIndicatorCheckBox);
        Control.AddOptionCheckBox(ADTCCVars.SightShowJamIndicator, SightJamIndicatorCheckBox);
        Control.AddOptionCheckBox(ADTCCVars.SightShowHeatIndicator, SightHeatIndicatorCheckBox);
        Control.AddOptionColorSlider(ADTCCVars.SightMainColor, SightMainColorSlider);
        Control.AddOptionColorSlider(ADTCCVars.SightSecondColor, SightSecondColorSlider);
        Control.OptionsChanged += UpdateSightsOptionsHash;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _cfg.OnValueChanged(ADTCCVars.RangedSight, OnSightCVarChanged);
        _cfg.OnValueChanged(ADTCCVars.MeleeSight, OnSightCVarChanged);
        _cfg.OnValueChanged(ADTCCVars.RangedSightScale, OnSightCVarChanged);
        _cfg.OnValueChanged(ADTCCVars.RangedSightOffset, OnSightCVarChanged);
        _cfg.OnValueChanged(ADTCCVars.RangedSightRotation, OnSightCVarChanged);
        _cfg.OnValueChanged(ADTCCVars.MeleeSightRotation, OnSightCVarChanged);
        _cfg.OnValueChanged(ADTCCVars.SightMainColor, OnSightCVarChanged);
        _cfg.OnValueChanged(ADTCCVars.SightSecondColor, OnSightCVarChanged);
        UpdateSightsOptionsHash();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _cfg.UnsubValueChanged(ADTCCVars.RangedSight, OnSightCVarChanged);
        _cfg.UnsubValueChanged(ADTCCVars.MeleeSight, OnSightCVarChanged);
        _cfg.UnsubValueChanged(ADTCCVars.RangedSightScale, OnSightCVarChanged);
        _cfg.UnsubValueChanged(ADTCCVars.RangedSightOffset, OnSightCVarChanged);
        _cfg.UnsubValueChanged(ADTCCVars.RangedSightRotation, OnSightCVarChanged);
        _cfg.UnsubValueChanged(ADTCCVars.MeleeSightRotation, OnSightCVarChanged);
        _cfg.UnsubValueChanged(ADTCCVars.SightMainColor, OnSightCVarChanged);
        _cfg.UnsubValueChanged(ADTCCVars.SightSecondColor, OnSightCVarChanged);
    }

    private bool _suppressSightCode;

    private void OnSightCVarChanged<T>(T _)
        => UpdateSightsOptionsHash();

    private void UpdateSightsOptionsHash()
    {
        if (_suppressSightCode)
            return;

        var ranged = SelectedSight(DropDownRangedSight) ?? _cfg.GetCVar(ADTCCVars.RangedSight);
        var melee = SelectedSight(DropDownMeleeSight) ?? _cfg.GetCVar(ADTCCVars.MeleeSight);
        var scale = (int) RangedSightScaleSlider.Slider.Value;
        var offset = (int) RangedSightOffsetSlider.Slider.Value;
        var rotation = RangedSightRotationCheckBox.Pressed;
        var meleeRotation = MeleeSightRotationCheckBox.Pressed;
        var main = SightMainColorSlider.Slider.Color.ToHex();
        var second = SightSecondColorSlider.Slider.Color.ToHex();
        var raw = $"{ranged}\u001F{melee}\u001F{scale}\u001F{offset}\u001F{rotation}\u001F{main}\u001F{second}\u001F{meleeRotation}";
        var bytes = System.Text.Encoding.UTF8.GetBytes(raw);
        var packed = Convert.ToBase64String(bytes);
        if (SightsOptionsHash.Text == packed)
        {
            RefreshSightPreview(ranged, melee, scale, offset, main, second);
            return;
        }

        _suppressSightCode = true;
        SightsOptionsHash.Text = packed;
        _suppressSightCode = false;
        SightsOptionsHash.UpdateDraw();
        RefreshSightPreview(ranged, melee, scale, offset, main, second);
    }

    private void RefreshSightPreview(string ranged, string melee, int scale, int offset, string main, string second)
    {
        if (!_entSysMan.TryGetEntitySystem(out SpriteSystem? _sprite))
            return;
        var mainColor = Color.FromHex(main);
        var secondColor = Color.FromHex(second);

        if (_prototypeManager.TryIndex(ranged, out SightPrototype? rangedProto) && rangedProto.SightType is (SightType.Ranged or SightType.Universal))
            UpdateSightPreview(_sprite, RangedSightPreview, rangedProto, scale, offset, mainColor, secondColor);

        if (_prototypeManager.TryIndex(melee, out SightPrototype? meleeProto) && meleeProto.SightType is (SightType.Melee or SightType.Universal))
            UpdateSightPreview(_sprite, MeleeSightPreview, meleeProto, scale, offset, mainColor, secondColor);
    }

    private static void UpdateSightPreview(SpriteSystem sprite, OptionsSightPreview preview, SightPrototype proto, int scale, int offset, Color main, Color second)
    {
        var rsi = sprite.RsiStateLike(proto.Sprite);
        if (!rsi.IsAnimated || rsi.AnimationFrameCount < 3)
        {
            preview.UpdateTexture(sprite.Frame0(proto.Sprite), scale / 100f, offset / 100f, main, second);
            preview.SetBrackets();
            return;
        }

        var bracket1 = rsi.GetFrame(RsiDirection.South, 0); // Left
        var sight = rsi.GetFrame(RsiDirection.South, 1); // Center
        var bracket2 = rsi.GetFrame(RsiDirection.South, 2); // Right
        var bracket3 = rsi.AnimationFrameCount >= 4 ? rsi.GetFrame(RsiDirection.South, 3) : null; // Down
        var bracket4 = rsi.AnimationFrameCount >= 5 ? rsi.GetFrame(RsiDirection.South, 4) : null; // Up
        preview.UpdateTexture(sight, scale / 100f, offset / 100f, main, second);
        preview.SetBrackets(bracket1, bracket2, bracket3, bracket4);
    }

    private void OnTextChanged(LineEdit.LineEditEventArgs args)
    {
        if (_suppressSightCode || args.Text is not { } packed)
            return;

        byte[] bytes;
        try
        {
            bytes = Convert.FromBase64String(packed);
        }
        catch
        {
            return;
        }

        var raw = System.Text.Encoding.UTF8.GetString(bytes);
        var parts = raw.Split('\u001F');

        // 7 fields: hashes made before melee sight rotation got its own setting.
        if (parts.Length is not (7 or 8))
            return;

        _suppressSightCode = true;

        if (_prototypeManager.TryIndex(parts[0], out SightPrototype? ranged) && ranged.SightType is (SightType.Ranged or SightType.Universal))
            SelectSight(DropDownRangedSight, parts[0]);

        if (_prototypeManager.TryIndex(parts[1], out SightPrototype? melee) && melee.SightType is (SightType.Melee or SightType.Universal))
            SelectSight(DropDownMeleeSight, parts[1]);

        if (int.TryParse(parts[2], out var scale))
            RangedSightScaleSlider.Slider.Value = scale;
        if (int.TryParse(parts[3], out var offset))
            RangedSightOffsetSlider.Slider.Value = offset;

        if (bool.TryParse(parts[4], out var rotation))
            RangedSightRotationCheckBox.Pressed = rotation;

        if (bool.TryParse(parts.Length > 7 ? parts[7] : parts[4], out var meleeRotation))
            MeleeSightRotationCheckBox.Pressed = meleeRotation;

        if (Color.TryFromHex(parts[5], out var main))
            SightMainColorSlider.Slider.Color = main;

        if (Color.TryFromHex(parts[6], out var second))
            SightSecondColorSlider.Slider.Color = second;

        _suppressSightCode = false;
        Control.ValueChanged();
        UpdateSightsOptionsHash();
    }

    private static string? SelectedSight(OptionDropDown dropDown)
        => dropDown.Button.SelectedMetadata as string;

    private static void SelectSight(OptionDropDown dropDown, string sightId)
    {
        var button = dropDown.Button;
        for (var i = 0; i < button.ItemCount; i++)
        {
            if (button.GetItemMetadata(i) is string id && id == sightId)
            {
                button.SelectId(i);
                return;
            }
        }
    }
}
