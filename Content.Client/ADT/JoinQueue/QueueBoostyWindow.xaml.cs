using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client.ADT.JoinQueue;

[GenerateTypedNameReferences]
public sealed partial class QueueBoostyWindow : FancyWindow
{
    public static readonly Color BoostyColor = Color.FromHex("#e0761b");

    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IUriOpener _uri = default!;

    public QueueBoostyWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        MessageLabel.SetMarkup(Loc.GetString("queue-boosty-message"));

        BoostyButton.ModulateSelfOverride = BoostyColor;
        BoostyButton.OnPressed += _ =>
        {
            _uri.OpenUri(_cfg.GetCVar(CCVars.InfoLinksWebsite));
            Close();
        };
        LaterButton.OnPressed += _ => Close();
    }
}
