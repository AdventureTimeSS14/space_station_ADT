using System.Numerics;
using Content.Shared.ADT.JoinQueue;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.ADT.JoinQueue;

[GenerateTypedNameReferences]
public sealed partial class QueueGamesControl : Control
{
    private static readonly ResPath SlotRsi = new("/Textures/ADT/Structures/Machines/slotmachines/slotmachinehighroller.rsi");

    [Dependency] private QueueGamesManager _manager = default!;

    private readonly Button[] _cells = new Button[MsgQueueGameState.BoardSize];
    private bool _spinning;
    private string? _slotResult;

    public QueueGamesControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        for (var i = 0; i < _cells.Length; i++)
        {
            var cell = (byte) i;
            var button = new Button { MinSize = new Vector2(48, 48) };
            button.OnPressed += _ => _manager.SendAction(QueueGameAction.MakeMove, cell);
            Board.AddChild(button);
            _cells[i] = button;
        }

        SlotSprite.DisplayRect.TextureScale = new Vector2(2, 2);
        SetSlotSprite("slotmachine");

        SearchButton.OnPressed += _ => _manager.SendAction(_manager.State?.Searching == true
            ? QueueGameAction.CancelSearch
            : QueueGameAction.FindOpponent);
        SpinButton.OnPressed += _ => _manager.SendAction(QueueGameAction.SpinSlot);

        _manager.StateUpdated += UpdateState;
        _manager.SlotResult += OnSlotResult;
        UpdateState();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        _manager.StateUpdated -= UpdateState;
        _manager.SlotResult -= OnSlotResult;
    }

    private void OnSlotResult(bool won)
    {
        _slotResult = Loc.GetString(won ? "queue-games-slot-win" : "queue-games-slot-lose");
        SetSlotSprite("slotmachine");
        UpdateState();
    }

    private void UpdateState()
    {
        Visible = _manager.State != null;
        if (_manager.State is not { } state)
            return;

        if (state.Spinning != _spinning)
        {
            _spinning = state.Spinning;
            SetSlotSprite(_spinning ? "slotmachine_spin" : "slotmachine");

            if (_spinning)
                _slotResult = null;
        }

        ScoreLabel.Text = Loc.GetString("queue-games-score", ("score", state.Score), ("required", state.ScoreToSpin));
        StatusLabel.Text = GetStatus(state);

        for (var i = 0; i < _cells.Length; i++)
        {
            var mark = state.Board[i];
            _cells[i].Text = mark switch
            {
                QueueGameMark.Cross => "X",
                QueueGameMark.Nought => "O",
                _ => string.Empty,
            };
            _cells[i].Disabled = !state.YourTurn || mark != QueueGameMark.None;
        }

        SearchButton.Text = Loc.GetString(state.Searching ? "queue-games-cancel-search" : "queue-games-find");
        SearchButton.Disabled = state.InMatch || state.Spinning;

        SlotLabel.Text = _slotResult ?? Loc.GetString("queue-games-slot-hint", ("required", state.ScoreToSpin));
        SpinButton.Disabled = state.Spinning || state.Searching || state.InMatch || state.Score < state.ScoreToSpin;
    }

    private static string GetStatus(MsgQueueGameState state)
    {
        if (state.InMatch)
        {
            var mark = state.Mark == QueueGameMark.Cross ? "X" : "O";
            return Loc.GetString(state.YourTurn ? "queue-games-your-turn" : "queue-games-opponent-turn",
                ("mark", mark));
        }

        if (state.Spinning)
            return Loc.GetString("queue-games-spinning");

        if (state.Searching)
            return Loc.GetString("queue-games-searching");

        return state.LastResult switch
        {
            QueueGameResult.Win => Loc.GetString("queue-games-result-win"),
            QueueGameResult.Lose => Loc.GetString("queue-games-result-lose"),
            QueueGameResult.Draw => Loc.GetString("queue-games-result-draw"),
            QueueGameResult.OpponentLeft => Loc.GetString("queue-games-result-opponent-left"),
            _ => Loc.GetString("queue-games-idle"),
        };
    }

    private void SetSlotSprite(string state)
    {
        SlotSprite.SetFromSpriteSpecifier(new SpriteSpecifier.Rsi(SlotRsi, state));
    }
}
