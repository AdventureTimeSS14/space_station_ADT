using System.Numerics;
using System.Threading;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client.ADT.SpawnMenu.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTTileSpawnWindow : DefaultWindow
{
    [Dependency] private IClipboardManager _clipboard = default!;
    [Dependency] private IResourceCache _resources = default!;

    private static readonly Vector2 ListItemSize = new(0, 36);
    private static readonly Vector2 GridItemSize = new(76, 76);
    private static readonly Color CaptionColor = Color.FromHex("#A0A0A0");

    private readonly ADTSpawnCategoryTree _tree;
    private IReadOnlyList<ADTTileSpawnEntry> _items = Array.Empty<ADTTileSpawnEntry>();
    private CancellationTokenSource? _searchCancel;

    public ADTTileSpawnEntry? Selected { get; private set; }
    public Func<string, bool>? IsFavorite;

    public bool IsGrid => ItemsView.Grid;

    public event Action<string>? OnSearchChanged;
    public event Action<ADTSpawnCategoryNode?>? OnCategorySelected;
    public event Action<ADTTileSpawnEntry?>? OnTileSelected;
    public event Action<ADTTileSpawnEntry>? OnFavoriteToggled;

    public ADTTileSpawnWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _tree = new ADTSpawnCategoryTree(CategoryTree);
        _tree.OnSelected += node => OnCategorySelected?.Invoke(node);

        SearchBar.OnTextChanged += args => QueueSearch(args.Text);
        SearchBar.OnTextEntered += _ => SelectFirst();
        ClearButton.OnPressed += _ => ClearSearch();
        ListModeButton.OnPressed += _ => SetGridMode(false);
        GridModeButton.OnPressed += _ => SetGridMode(true);
        CopyIdButton.OnPressed += _ =>
        {
            if (Selected != null)
                _clipboard.SetText(Selected.Definition.ID);
        };
        FavoriteButton.OnPressed += _ =>
        {
            if (Selected != null)
                OnFavoriteToggled?.Invoke(Selected);
        };
        Split.SetSplitFractionOnNextArrange(0.25f);

        ItemsView.Factory = CreateButton;
        ItemsView.SetItemSizes(ListItemSize, GridItemSize);
        SetGridMode(true);
    }

    protected override void Opened()
    {
        base.Opened();

        SearchBar.GrabKeyboardFocus();
    }

    public void SetCategories(IReadOnlyList<ADTSpawnCategoryNode> roots, ADTSpawnCategoryNode? selected)
    {
        _tree.SetCategories(roots, selected);
    }

    public void UpdateCategoryCounts(bool hideEmpty)
    {
        _tree.UpdateCounts(hideEmpty);
    }

    public void SetGridMode(bool grid)
    {
        ListModeButton.Pressed = !grid;
        GridModeButton.Pressed = grid;
        ItemsView.SetGrid(grid);
    }

    public void SetItems(IReadOnlyList<ADTTileSpawnEntry> items)
    {
        _items = items;
        CountLabel.Text = Loc.GetString("adt-spawn-menu-count", ("count", items.Count));
        ItemsView.SetCount(items.Count);
    }

    public void SetSelected(ADTTileSpawnEntry? entry)
    {
        Selected = entry;

        foreach (var control in ItemsView.VisibleControls)
        {
            if (control is ADTSpawnSimpleButton button)
                button.ActualButton.Pressed = _items[button.Index] == entry;
        }

        UpdateDetails();
    }

    public void RefreshDetails()
    {
        UpdateDetails();
    }

    private void UpdateDetails()
    {
        if (Selected == null)
        {
            DetailsContent.Visible = false;
            DetailsEmpty.Visible = true;
            return;
        }

        DetailsContent.Visible = true;
        DetailsEmpty.Visible = false;

        var definition = Selected.Definition;
        DetailsPreview.Texture = Selected.GetVariant(_resources, 0);
        DetailsName.Text = Selected.Name;
        DetailsId.Text = definition.ID;
        DetailsId.ToolTip = definition.ID;

        var favorite = IsFavorite?.Invoke(definition.ID) ?? false;
        FavoriteButton.Pressed = favorite;
        FavoriteButton.Text = Loc.GetString(favorite ? "adt-spawn-menu-favorite-remove" : "adt-spawn-menu-favorite-add");

        VariantsBox.RemoveAllChildren();
        VariantsCaption.Visible = definition.Variants > 1;
        if (definition.Variants > 1)
        {
            for (var i = 0; i < definition.Variants; i++)
            {
                VariantsBox.AddChild(new TextureRect
                {
                    Texture = Selected.GetVariant(_resources, i),
                    SetSize = new Vector2(32, 32),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                });
            }
        }

        var message = new FormattedMessage();
        AddLine(message, "adt-spawn-menu-details-category", Selected.Category.Name);
        AddFlag(message, definition.IsSubFloor, "adt-spawn-menu-tile-flag-subfloor");
        AddFlag(message, definition.Weather, "adt-spawn-menu-tile-flag-weather");
        AddFlag(message, definition.Indestructible, "adt-spawn-menu-tile-flag-indestructible");
        AddFlag(message, definition.AllowRotationMirror, "adt-spawn-menu-tile-flag-rotation");

        if (definition.BaseTurf != null)
            AddLine(message, "adt-spawn-menu-tile-base-turf", definition.BaseTurf.Value.Id);

        if (definition.ItemDropPrototypeName != null)
            AddLine(message, "adt-spawn-menu-tile-item-drop", definition.ItemDropPrototypeName.Value.Id);

        DetailsInfo.SetMessage(message);
    }

    private static void AddFlag(FormattedMessage message, bool value, string caption)
    {
        if (!value)
            return;

        if (!message.IsEmpty)
            message.PushNewline();

        message.AddText(Loc.GetString(caption));
    }

    private static void AddLine(FormattedMessage message, string caption, string value)
    {
        if (!message.IsEmpty)
            message.PushNewline();

        message.PushColor(CaptionColor);
        message.AddText(Loc.GetString(caption));
        message.Pop();
        message.AddText(" ");
        message.AddText(value);
    }

    private void SelectFirst()
    {
        if (_items.Count > 0)
            OnTileSelected?.Invoke(_items[0]);
    }

    private void QueueSearch(string text)
    {
        ClearButton.Disabled = string.IsNullOrEmpty(text);

        _searchCancel?.Cancel();
        _searchCancel = new CancellationTokenSource();

        Timer.Spawn(ADTEntitySpawnWindow.SearchDelay, () =>
        {
            if (Disposed)
                return;

            OnSearchChanged?.Invoke(text);
        }, _searchCancel.Token);
    }

    private void ClearSearch()
    {
        _searchCancel?.Cancel();
        SearchBar.Clear();
        ClearButton.Disabled = true;
        OnSearchChanged?.Invoke(string.Empty);
    }

    private Control CreateButton(int index, bool grid)
    {
        var entry = _items[index];
        var preview = new TextureRect
        {
            Texture = entry.GetVariant(_resources, 0),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
        };

        var button = new ADTSpawnSimpleButton(index, grid, preview, entry.Name, $"{entry.Name}\n{entry.Definition.ID}");
        button.ActualButton.Pressed = entry == Selected;
        button.ActualButton.OnToggled += args => OnTileSelected?.Invoke(args.Pressed ? entry : null);
        return button;
    }
}
