using System.Numerics;
using System.Threading;
using Content.Client.UserInterface.Controls.FancyTree;
using Robust.Client.AutoGenerated;
using Robust.Client.Placement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client.ADT.SpawnMenu.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTEntitySpawnWindow : DefaultWindow
{
    [Dependency] private IPlacementManager _placement = default!;

    public const int SearchDelay = 150;

    private static readonly Vector2 ListItemSize = new(0, 36);
    private static readonly Vector2 GridItemSize = new(76, 76);

    private readonly Dictionary<ADTSpawnCategoryNode, TreeItem> _categoryItems = new();

    private IReadOnlyList<ADTSpawnListItem> _items = Array.Empty<ADTSpawnListItem>();
    private bool _updatingTree;
    private CancellationTokenSource? _searchCancel;

    public EntityPrototype? SelectedPrototype { get; private set; }

    public bool IsGrid => ItemsView.Grid;

    public event Action<EntityPrototype?>? OnPrototypeSelected;
    public event Action<string>? OnSearchChanged;
    public event Action<ADTSpawnCategoryNode?>? OnCategorySelected;
    public event Action<string, string, bool>? OnTagToggled;
    public event Action<EntityPrototype>? OnFavoriteToggled;

    public ADTEntitySpawnWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var modes = _placement.AllModeNames;
        for (var i = 0; i < modes.Length; i++)
        {
            OverrideMenu.AddItem(modes[i], i);
        }

        SearchBar.OnTextChanged += args => QueueSearch(args.Text);
        SearchBar.OnTextEntered += _ => SelectFirst();
        ClearButton.OnPressed += _ => ClearSearch();
        ListModeButton.OnPressed += _ => SetGridMode(false);
        GridModeButton.OnPressed += _ => SetGridMode(true);
        DetailsButton.OnToggled += args => DetailsScroll.Visible = args.Pressed;
        CategoryTree.OnSelectedItemChanged += OnTreeSelectionChanged;
        Details.OnVariantSelected += prototype => OnPrototypeSelected?.Invoke(prototype);
        Details.OnTagPressed += (raw, normalized) => OnTagToggled?.Invoke(raw, normalized, true);
        Details.OnFavoriteToggled += prototype => OnFavoriteToggled?.Invoke(prototype);
        Split.SetSplitFractionOnNextArrange(0.24f);

        ItemsView.Factory = CreateButton;
        ItemsView.SetItemSizes(ListItemSize, GridItemSize);
        SetGridMode(false);
    }

    protected override void Opened()
    {
        base.Opened();

        SearchBar.GrabKeyboardFocus();
    }

    public void SetFavoriteChecker(Func<string, bool> isFavorite)
    {
        Details.IsFavorite = isFavorite;
    }

    public void SetDetailsVisible(bool visible)
    {
        DetailsButton.Pressed = visible;
        DetailsScroll.Visible = visible;
    }

    public void SetItems(IReadOnlyList<ADTSpawnListItem> items, int prototypeCount)
    {
        _items = items;
        CountLabel.Text = Loc.GetString("adt-spawn-menu-count", ("count", prototypeCount));
        ItemsView.SetCount(items.Count);
        UpdateDetails();
    }

    public void SetSelected(EntityPrototype? prototype)
    {
        SelectedPrototype = prototype;

        foreach (var control in ItemsView.VisibleControls)
        {
            if (control is ADTEntitySpawnButton button)
                button.ActualButton.Pressed = button.Item.Contains(prototype);
        }

        UpdateDetails();
    }

    public void RefreshDetails()
    {
        UpdateDetails();
    }

    public void SetTagBar(IReadOnlyList<(string Raw, string Normalized)> active)
    {
        TagBar.RemoveAllChildren();

        foreach (var (raw, normalized) in active)
        {
            var chip = new ADTSpawnTagChip(normalized, Loc.GetString("adt-spawn-menu-tag-active", ("tag", raw)), true)
            {
                ToolTip = Loc.GetString("adt-spawn-menu-tag-remove-tooltip"),
            };
            chip.OnPressed += _ => OnTagToggled?.Invoke(raw, normalized, false);
            TagBar.AddChild(chip);
        }

        TagBar.Visible = TagBar.ChildCount > 0;
    }

    public void SetCategories(IReadOnlyList<ADTSpawnCategoryNode> roots, ADTSpawnCategoryNode? selected)
    {
        _updatingTree = true;

        CategoryTree.Clear();
        _categoryItems.Clear();

        foreach (var root in roots)
        {
            AddCategory(root, null);
        }

        if (selected != null && _categoryItems.TryGetValue(selected, out var item))
        {
            CategoryTree.SetSelectedIndex(item.Index);
            CategoryTree.ExpandParentEntries(item.Index);
        }

        _updatingTree = false;
    }

    public void UpdateCategoryCounts(bool hideEmpty)
    {
        var selected = CategoryTree.SelectedItem;

        foreach (var (node, item) in _categoryItems)
        {
            item.Label.Text = Loc.GetString("adt-spawn-menu-category", ("name", node.Name), ("count", node.Count));
            item.Visible = !hideEmpty || node.Count > 0 || item == selected;
        }
    }

    public void SetGridMode(bool grid)
    {
        ListModeButton.Pressed = !grid;
        GridModeButton.Pressed = grid;
        ItemsView.SetGrid(grid);
    }

    private void AddCategory(ADTSpawnCategoryNode node, TreeItem? parent)
    {
        var item = CategoryTree.AddItem(parent);
        item.Metadata = node;
        item.Label.Text = node.Name;

        if (node.Service)
            item.Label.FontColorOverride = Color.FromHex("#E8B05A");

        _categoryItems[node] = item;

        foreach (var child in node.Children)
        {
            AddCategory(child, item);
        }
    }

    private void OnTreeSelectionChanged(TreeItem? item)
    {
        if (_updatingTree)
            return;

        OnCategorySelected?.Invoke(item?.Metadata as ADTSpawnCategoryNode);
    }

    private void SelectFirst()
    {
        if (_items.Count == 0)
            return;

        OnPrototypeSelected?.Invoke(_items[0].Representative.Prototype);
    }

    private void UpdateDetails()
    {
        ADTSpawnListItem? selectedItem = null;
        foreach (var item in _items)
        {
            if (!item.Contains(SelectedPrototype))
                continue;

            selectedItem = item;
            break;
        }

        Details.SetItem(selectedItem, SelectedPrototype);
    }

    private void QueueSearch(string text)
    {
        ClearButton.Disabled = string.IsNullOrEmpty(text);

        _searchCancel?.Cancel();
        _searchCancel = new CancellationTokenSource();

        Timer.Spawn(SearchDelay, () =>
        {
            if (Disposed)
                return;

            OnSearchChanged?.Invoke(text);
        }, _searchCancel.Token);
    }

    private void ClearSearch()
    {
        _searchCancel?.Cancel();
        SearchBar.Clear();
        ClearButton.Disabled = true;
        OnSearchChanged?.Invoke(string.Empty);
    }

    private Control CreateButton(int index, bool grid)
    {
        var item = _items[index];
        var button = new ADTEntitySpawnButton(item, index, grid, BuildTooltip(item));

        button.ActualButton.Pressed = item.Contains(SelectedPrototype);
        button.ActualButton.OnToggled += args =>
        {
            OnPrototypeSelected?.Invoke(args.Pressed ? button.Item.Representative.Prototype : null);
        };
        button.OnTagPressed += (raw, normalized) => OnTagToggled?.Invoke(raw, normalized, true);

        return button;
    }

    private static string BuildTooltip(ADTSpawnListItem item)
    {
        var prototype = item.Representative.Prototype;
        var name = string.IsNullOrEmpty(prototype.Name) ? prototype.ID : prototype.Name;

        if (item.Variants.Count > 1)
            return Loc.GetString("adt-spawn-menu-variants-tooltip", ("name", name), ("count", item.Variants.Count));

        if (!string.IsNullOrWhiteSpace(prototype.EditorSuffix))
            name = $"{name} [{prototype.EditorSuffix}]";

        var description = string.IsNullOrEmpty(prototype.Description)
            ? Loc.GetString("adt-spawn-menu-no-description")
            : prototype.Description;

        return $"{name}\n{prototype.ID}\n{description}";
    }
}
