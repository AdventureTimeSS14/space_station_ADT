using System.Linq;
using System.Numerics;
using System.Threading;
using Content.Client.Decals;
using Content.Client.Decals.UI;
using Content.Shared.Decals;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client.ADT.SpawnMenu.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTDecalSpawnWindow : DefaultWindow
{
    [Dependency] private IClipboardManager _clipboard = default!;
    [Dependency] private IEntityManager _entities = default!;

    private const int RecentColorLimit = 10;

    private static readonly Vector2 ListItemSize = new(0, 36);
    private static readonly Vector2 GridItemSize = new(64, 72);

    private readonly DecalPlacementSystem _decalPlacement;
    private readonly ADTSpawnCategoryTree _tree;
    private readonly FloatSpinBox _rotationSpinBox;
    private PaletteColorPicker? _picker;
    private CancellationTokenSource? _searchCancel;

    private IReadOnlyList<ADTDecalSpawnItem> _items = Array.Empty<ADTDecalSpawnItem>();
    private ADTDecalSpawnItem? _selectedItem;
    private Color _color = Color.White;
    private bool _useColor;
    private bool _snap;
    private bool _cleanable;
    private bool _auto;
    private bool _singleErase;
    private float _rotation;
    private int _zIndex;

    public readonly List<Color> RecentColorList = new();

    public ADTDecalSpawnEntry? Selected { get; private set; }
    public Func<string, bool>? IsFavorite;

    public bool IsGrid => ItemsView.Grid;

    public event Action<string>? OnSearchChanged;
    public event Action<ADTSpawnCategoryNode?>? OnCategorySelected;
    public event Action<ADTDecalSpawnEntry>? OnDecalSelected;
    public event Action<ADTDecalSpawnEntry>? OnFavoriteToggled;
    public event Action? OnRecentColorsChanged;

    public ADTDecalSpawnWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _decalPlacement = _entities.System<DecalPlacementSystem>();

        _tree = new ADTSpawnCategoryTree(CategoryTree);
        _tree.OnSelected += node => OnCategorySelected?.Invoke(node);

        _rotationSpinBox = new FloatSpinBox(90.0f, 0)
        {
            HorizontalExpand = true,
        };
        RotationBox.AddChild(_rotationSpinBox);

        DetailsPreview.DisplayRect.Stretch = TextureRect.StretchMode.KeepAspectCentered;

        SearchBar.OnTextChanged += args => QueueSearch(args.Text);
        SearchBar.OnTextEntered += _ => SelectFirst();
        ClearButton.OnPressed += _ => ClearSearch();
        ListModeButton.OnPressed += _ => SetGridMode(false);
        GridModeButton.OnPressed += _ => SetGridMode(true);
        OptionsButton.OnToggled += args => OptionsBox.Visible = args.Pressed;
        CopyIdButton.OnPressed += _ =>
        {
            if (Selected != null)
                _clipboard.SetText(Selected.Id);
        };
        FavoriteButton.OnPressed += _ =>
        {
            if (Selected != null)
                OnFavoriteToggled?.Invoke(Selected);
        };
        PaletteButton.OnPressed += _ => TogglePalette();
        ColorPicker.OnColorChanged += OnColorPicked;

        _rotationSpinBox.OnValueChanged += args =>
        {
            _rotation = args.Value;
            UpdatePlacementInfo();
        };
        EnableAuto.OnToggled += args =>
        {
            _auto = args.Pressed;
            if (Selected != null)
                ApplyDefaults(Selected.Prototype);
        };
        EnableColor.OnToggled += args =>
        {
            _useColor = args.Pressed;
            UpdatePlacementInfo();
            UpdateColors();
        };
        EnableSnap.OnToggled += args =>
        {
            _snap = args.Pressed;
            UpdatePlacementInfo();
        };
        EnableCleanable.OnToggled += args =>
        {
            _cleanable = args.Pressed;
            UpdatePlacementInfo();
        };
        EnableSingleErase.OnToggled += args =>
        {
            _singleErase = args.Pressed;
            UpdatePlacementInfo();
        };
        ZIndexSpinBox.ValueChanged += args =>
        {
            _zIndex = args.Value;
            UpdatePlacementInfo();
        };

        Split.SetSplitFractionOnNextArrange(0.24f);

        ItemsView.Factory = CreateButton;
        ItemsView.SetItemSizes(ListItemSize, GridItemSize);
        SetGridMode(true);
    }

    protected override void Opened()
    {
        base.Opened();

        _decalPlacement.SetActive(true);
        SearchBar.GrabKeyboardFocus();
    }

    public override void Close()
    {
        base.Close();

        _decalPlacement.SetActive(false);
        _picker?.Close();
    }

    public void SetCategories(IReadOnlyList<ADTSpawnCategoryNode> roots, ADTSpawnCategoryNode? selected)
    {
        _tree.SetCategories(roots, selected);
    }

    public void UpdateCategoryCounts(bool hideEmpty)
    {
        _tree.UpdateCounts(hideEmpty);
    }

    public void SetGridMode(bool grid)
    {
        ListModeButton.Pressed = !grid;
        GridModeButton.Pressed = grid;
        ItemsView.SetGrid(grid);
    }

    public void SetItems(IReadOnlyList<ADTDecalSpawnItem> items, int decalCount)
    {
        _items = items;
        CountLabel.Text = Loc.GetString("adt-spawn-menu-count", ("count", decalCount));
        ItemsView.SetCount(items.Count);
        UpdateSelectedItem();
        UpdateDetails();
    }

    public void SetRecentColors(IEnumerable<Color> colors)
    {
        RecentColorList.Clear();
        RecentColorList.AddRange(colors);
        UpdateRecentColors();
    }

    public void Select(ADTDecalSpawnEntry entry)
    {
        Selected = entry;

        if (_auto)
            ApplyDefaults(entry.Prototype);

        if (_useColor)
            PushRecentColor(_color);

        UpdateSelectedItem();
        UpdatePlacementInfo();
        UpdatePressed();
        UpdateDetails();
    }

    public void RefreshDetails()
    {
        UpdateDetails();
    }

    private void ApplyDefaults(DecalPrototype decal)
    {
        EnableCleanable.Pressed = decal.DefaultCleanable;
        EnableColor.Pressed = decal.DefaultCustomColor;
        EnableSnap.Pressed = decal.DefaultSnap;
        _cleanable = decal.DefaultCleanable;
        _useColor = decal.DefaultCustomColor;
        _snap = decal.DefaultSnap;
        UpdatePlacementInfo();
        UpdateColors();
    }

    private void UpdateSelectedItem()
    {
        _selectedItem = null;
        foreach (var item in _items)
        {
            if (!item.Contains(Selected))
                continue;

            _selectedItem = item;
            break;
        }
    }

    private void UpdatePlacementInfo()
    {
        if (Selected == null)
            return;

        var color = _useColor ? _color : Color.White;
        _decalPlacement.UpdateDecalInfo(Selected.Id, color, _rotation, _snap, _zIndex, _cleanable, _singleErase);
    }

    private void OnColorPicked(Color color)
    {
        _color = color;
        UpdatePlacementInfo();
        UpdateColors();
    }

    private void TogglePalette()
    {
        if (_picker == null)
        {
            _picker = new PaletteColorPicker();
            _picker.OpenToLeft();
            _picker.PaletteList.OnItemSelected += args =>
            {
                var color = (args.ItemList.GetSelected().First().Metadata as Color?)!.Value;
                ColorPicker.Color = color;
                OnColorPicked(color);
                PushRecentColor(color);
            };
            return;
        }

        if (_picker.IsOpen)
            _picker.Close();
        else
            _picker.Open();
    }

    private void PushRecentColor(Color color)
    {
        RecentColorList.Remove(color);
        RecentColorList.Insert(0, color);

        if (RecentColorList.Count > RecentColorLimit)
            RecentColorList.RemoveRange(RecentColorLimit, RecentColorList.Count - RecentColorLimit);

        UpdateRecentColors();
        OnRecentColorsChanged?.Invoke();
    }

    private void UpdateRecentColors()
    {
        RecentColors.RemoveAllChildren();

        foreach (var color in RecentColorList)
        {
            var target = color;
            var button = new ContainerButton
            {
                ToolTip = color.ToHex(),
                Children =
                {
                    new PanelContainer
                    {
                        SetSize = new Vector2(20, 20),
                        PanelOverride = new StyleBoxFlat
                        {
                            BackgroundColor = color,
                            BorderColor = Color.Black,
                            BorderThickness = new Thickness(1),
                        },
                    },
                },
            };
            button.OnPressed += _ =>
            {
                ColorPicker.Color = target;
                OnColorPicked(target);
                EnableColor.Pressed = true;
                _useColor = true;
                UpdatePlacementInfo();
                UpdateColors();
            };
            RecentColors.AddChild(button);
        }
    }

    private void UpdateColors()
    {
        var modulate = _useColor ? _color : Color.White;
        foreach (var control in ItemsView.VisibleControls)
        {
            if (control is ADTSpawnSimpleButton button)
                button.Preview.Modulate = modulate;
        }

        DetailsPreview.Modulate = modulate;
    }

    private void UpdatePressed()
    {
        foreach (var control in ItemsView.VisibleControls)
        {
            if (control is ADTSpawnSimpleButton button)
                button.ActualButton.Pressed = _items[button.Index].Contains(Selected);
        }
    }

    private void UpdateDetails()
    {
        if (Selected == null)
        {
            DetailsContent.Visible = false;
            DetailsEmpty.Visible = true;
            return;
        }

        DetailsContent.Visible = true;
        DetailsEmpty.Visible = false;

        DetailsPreview.SetFromSpriteSpecifier(Selected.Prototype.Sprite);
        DetailsPreview.Modulate = _useColor ? _color : Color.White;
        DetailsId.Text = Selected.Id;
        DetailsId.ToolTip = Selected.Id;

        var favorite = IsFavorite?.Invoke(Selected.Id) ?? false;
        FavoriteButton.Pressed = favorite;
        FavoriteButton.Text = Loc.GetString(favorite ? "adt-spawn-menu-favorite-remove" : "adt-spawn-menu-favorite-add");

        DetailsInfo.Text = Loc.GetString("adt-spawn-menu-decal-info",
            ("category", Selected.Category.Name),
            ("tags", string.Join(", ", Selected.Prototype.Tags)));

        VariantsBox.RemoveAllChildren();
        var variants = _selectedItem?.Variants;
        VariantsCaption.Visible = variants is { Count: > 1 };
        if (variants is not { Count: > 1 })
            return;

        foreach (var variant in variants)
        {
            var preview = new AnimatedTextureRect
            {
                SetSize = new Vector2(32, 32),
            };
            preview.DisplayRect.Stretch = TextureRect.StretchMode.KeepAspectCentered;
            preview.SetFromSpriteSpecifier(variant.Prototype.Sprite);

            var button = new Button
            {
                ToggleMode = true,
                Pressed = variant == Selected,
                ToolTip = variant.Id,
                Children =
                {
                    preview,
                },
            };
            var target = variant;
            button.OnPressed += _ => OnDecalSelected?.Invoke(target);
            VariantsBox.AddChild(button);
        }
    }

    private void SelectFirst()
    {
        if (_items.Count > 0)
            OnDecalSelected?.Invoke(_items[0].Representative);
    }

    private void QueueSearch(string text)
    {
        ClearButton.Disabled = string.IsNullOrEmpty(text);

        _searchCancel?.Cancel();
        _searchCancel = new CancellationTokenSource();

        Timer.Spawn(ADTEntitySpawnWindow.SearchDelay, () =>
        {
            if (Disposed)
                return;

            OnSearchChanged?.Invoke(text);
        }, _searchCancel.Token);
    }

    private void ClearSearch()
    {
        _searchCancel?.Cancel();
        SearchBar.Clear();
        ClearButton.Disabled = true;
        OnSearchChanged?.Invoke(string.Empty);
    }

    private Control CreateButton(int index, bool grid)
    {
        var item = _items[index];
        var preview = new AnimatedTextureRect();
        preview.DisplayRect.Stretch = TextureRect.StretchMode.KeepAspectCentered;
        preview.SetFromSpriteSpecifier(item.Representative.Prototype.Sprite);
        preview.Modulate = _useColor ? _color : Color.White;

        var text = item.Variants.Count > 1
            ? Loc.GetString("adt-spawn-menu-variants-short", ("name", item.Name), ("count", item.Variants.Count))
            : item.Name;

        var button = new ADTSpawnSimpleButton(index, grid, preview, text, item.Representative.Id);
        button.ActualButton.Pressed = item.Contains(Selected);
        button.ActualButton.OnPressed += _ => OnDecalSelected?.Invoke(item.Representative);
        return button;
    }
}
