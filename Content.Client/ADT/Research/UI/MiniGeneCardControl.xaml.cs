using Content.Shared.ADT.SeedDna.Prototypes;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.ADT.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class MiniGeneCardControl : Control
{
    public MiniGeneCardControl(SeedDnaGenePrototype gene, TechDisciplinePrototype discipline, SpriteSystem sprite)
    {
        RobustXamlLoader.Load(this);

        Background.ModulateSelfOverride = discipline.Color;

        Showcase.Texture = sprite.Frame0(new SpriteSpecifier.Rsi(new ResPath("ADT/Objects/Misc/DNA_disk.rsi"), "icon"));
        NameLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString($"seed-dna-row-{gene.ID}")));

        if (gene.Description is { } description)
        {
            var tooltip = new Tooltip();
            tooltip.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(description)));
            Main.TooltipSupplier = _ => tooltip;
        }
    }
}
