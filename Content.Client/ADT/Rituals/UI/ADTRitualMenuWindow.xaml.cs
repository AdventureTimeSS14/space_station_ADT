using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Client.Stylesheets.Palette;
using Content.Shared.ADT.Rituals;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.ADT.Rituals.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTRitualMenuWindow : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    public event Action<ProtoId<ADTRitualPrototype>>? OnStartPressed;

    private List<ADTRitualEntry> _entries = new();
    private ProtoId<ADTRitualPrototype>? _selected;
    private bool _busy;

    private readonly Dictionary<ProtoId<ADTRitualPrototype>, Button> _cooldownButtons = new();

    private int _lastShownSecond = -1;

    public ADTRitualMenuWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StartButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                OnStartPressed?.Invoke(selected);
        };
    }

    public void SetState(ADTRitualBuiState state)
    {
        _entries = state.Rituals;
        _busy = state.Busy;

        if (_selected != null && _entries.All(e => e.Ritual != _selected))
            _selected = null;

        BuildList();
        BuildDetails();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var second = (int)_timing.CurTime.TotalSeconds;
        if (second == _lastShownSecond)
            return;

        _lastShownSecond = second;
        RefreshCountdowns();
    }

    private void RefreshCountdowns()
    {
        var now = _timing.CurTime;

        foreach (var (ritual, button) in _cooldownButtons)
        {
            var entry = _entries.FirstOrDefault(e => e.Ritual == ritual);
            button.Text = EntryLabel(entry, now);
            button.Modulate = entry.Available(now) ? Color.White : Color.FromHex("#8a8a8a");
        }

        if (_selected is { } selected && _entries.Any(e => e.Ritual == selected))
        {
            var entry = _entries.First(e => e.Ritual == selected);
            StartButton.Disabled = _busy || !entry.Available(now);
            StartButton.Text = StartLabel(entry, now);
        }
    }

    private string EntryLabel(ADTRitualEntry entry, TimeSpan now)
    {
        if (!_proto.TryIndex(entry.Ritual, out var proto))
            return string.Empty;

        var name = Loc.GetString(proto.Name);
        var left = entry.CooldownLeft(now);

        if (left > 0)
            return Loc.GetString("adt-ritual-window-entry-cooldown", ("name", name), ("seconds", left));

        if (entry.Charges == 0)
            return Loc.GetString("adt-ritual-window-entry-spent", ("name", name));

        if (entry.Charges > 0)
            return Loc.GetString("adt-ritual-window-entry-charges", ("name", name), ("charges", entry.Charges));

        return name;
    }

    private string StartLabel(ADTRitualEntry entry, TimeSpan now)
    {
        var left = entry.CooldownLeft(now);

        if (left > 0)
            return Loc.GetString("adt-ritual-window-wait", ("seconds", left));

        if (entry.Charges == 0)
            return Loc.GetString("adt-ritual-window-spent");

        return Loc.GetString("adt-ritual-window-start");
    }

    private void BuildList()
    {
        RitualList.RemoveAllChildren();
        _cooldownButtons.Clear();

        var now = _timing.CurTime;

        foreach (var entry in _entries)
        {
            if (!_proto.TryIndex(entry.Ritual, out _))
                continue;

            var button = new Button
            {
                Text = EntryLabel(entry, now),
                HorizontalExpand = true,
                Margin = new Thickness(0, 0, 0, 2),
                MinHeight = 28,
                ToggleMode = true,
                Pressed = _selected == entry.Ritual,
            };

            button.Modulate = entry.Available(now) ? Color.White : Color.FromHex("#8a8a8a");

            var ritual = entry.Ritual;
            button.OnPressed += _ =>
            {
                _selected = ritual;
                BuildList();
                BuildDetails();
            };

            RitualList.AddChild(button);
            _cooldownButtons[ritual] = button;
        }
    }

    private void BuildDetails()
    {
        RequirementList.RemoveAllChildren();
        PriceList.RemoveAllChildren();
        RiskList.RemoveAllChildren();

        if (_selected is not { } selected || !_proto.TryIndex(selected, out var proto))
        {
            RitualName.Text = Loc.GetString("adt-ritual-window-none");
            RitualDescription.SetMessage(string.Empty);
            SetDetailsVisible(false);
            StartButton.Disabled = true;
            StartButton.Text = Loc.GetString("adt-ritual-window-start");
            return;
        }

        SetDetailsVisible(true);

        var now = _timing.CurTime;
        var entry = _entries.FirstOrDefault(e => e.Ritual == selected, new ADTRitualEntry(selected, proto.Charges, TimeSpan.Zero));

        RitualName.Text = Loc.GetString(proto.Name);
        RitualDescription.SetMessage(proto.Description == null ? string.Empty : Loc.GetString(proto.Description));

        BuildRequirements(proto);
        BuildPrice(proto, entry);
        BuildRisk(proto);

        StartButton.Disabled = _busy || !entry.Available(now);
        StartButton.Text = StartLabel(entry, now);
    }

    private void SetDetailsVisible(bool visible)
    {
        DescriptionPanel.Visible = visible;
        RequirementsBlock.Visible = visible;
        PriceBlock.Visible = visible;
        RiskBlock.Visible = visible;
    }

    private void BuildRequirements(ADTRitualPrototype proto)
    {
        AddLine(RequirementList, Loc.GetString("adt-ritual-req-invokers", ("total", proto.ExtraInvokers + 1)));

        if (proto.ShamanOnly)
            AddLine(RequirementList, Loc.GetString("adt-ritual-req-shaman"));

        if (proto.NeededDye != null && proto.DyeFluff != null)
            AddLine(RequirementList, Loc.GetString("adt-ritual-req-dye", ("dye", Loc.GetString(proto.DyeFluff))));

        if (proto.RequiredThings.Count > 0)
            AddLine(RequirementList, Loc.GetString("adt-ritual-req-things", ("things", ThingList(proto))));

        if (proto.RequiredThings.Count == 0 && proto.NeededDye == null)
            AddLine(RequirementList, Loc.GetString("adt-ritual-req-nothing"));
    }

    private static string ThingList(ADTRitualPrototype proto)
    {
        var names = proto.RequiredThings.Select(thing => thing.Amount > 1
            ? Loc.GetString("adt-ritual-req-thing-amount", ("name", Loc.GetString(thing.Name)), ("amount", thing.Amount))
            : Loc.GetString(thing.Name));

        return string.Join(", ", names);
    }

    private void BuildPrice(ADTRitualPrototype proto, ADTRitualEntry entry)
    {
        if (proto.CastTime > TimeSpan.Zero)
        {
            var total = (int)proto.CastTime.TotalSeconds * (proto.ExtraInvokers + 1);

            AddLine(PriceList, Loc.GetString("adt-ritual-price-cast", ("seconds", total)));
        }

        AddLine(PriceList, Loc.GetString("adt-ritual-price-cooldown", ("seconds", (int)proto.Cooldown.TotalSeconds)));

        if (proto.Charges != -1)
            AddLine(PriceList, Loc.GetString("adt-ritual-price-charges", ("left", entry.Charges)));

        var eaten = proto.RequiredThings.Where(t => t.Consume).ToList();

        if (eaten.Count > 0 && proto.DeleteThingsOnSuccess)
        {
            AddLine(PriceList, Loc.GetString("adt-ritual-price-consumes",
                ("things", string.Join(", ", eaten.Select(t => Loc.GetString(t.Name))))));
        }
        else if (proto.RequiredThings.Count > 0)
        {
            AddLine(PriceList, Loc.GetString("adt-ritual-price-consumes-nothing"));
        }
    }

    private void BuildRisk(ADTRitualPrototype proto)
    {
        var fail = (int)MathF.Round(proto.FailChance * 100);
        var disaster = (int)MathF.Round(proto.DisasterChance * 100);

        AddLine(
            RiskList,
            Loc.GetString("adt-ritual-risk", ("fail", fail), ("disaster", disaster)),
            RiskColor(fail));

        if (proto.DeleteThingsOnFail)
            AddLine(RiskList, Loc.GetString("adt-ritual-risk-loses-things"), Palettes.Status.Bad);

        if (proto.Modifiers.Count > 0)
            AddLine(RiskList, Loc.GetString("adt-ritual-risk-conditional"), Palettes.Status.Okay);
    }

    private static Color RiskColor(int percent)
    {
        return percent switch
        {
            <= 15 => Palettes.Status.Good,
            <= 40 => Palettes.Status.Warning,
            _ => Palettes.Status.Bad,
        };
    }

    private static void AddLine(BoxContainer container, string text, Color? color = null)
    {
        var label = new RichTextLabel
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 2),
        };

        label.SetMessage(text, defaultColor: color);
        container.AddChild(label);
    }
}
