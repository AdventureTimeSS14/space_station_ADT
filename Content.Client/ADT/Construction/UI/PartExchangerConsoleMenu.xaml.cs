using System.Numerics;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client.ADT.Construction.UI;

[GenerateTypedNameReferences]
public sealed partial class PartExchangerConsoleMenu : FancyWindow
{
    [Dependency] private IPrototypeManager _prototype = default!;
    
    public event Action<NetEntity>? OnBoardSelected;

    public PartExchangerConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Populate(IEnumerable<(NetEntity Board, EntProtoId Console)> boards)
    {
        BoardsList.RemoveAllChildren();

        foreach (var (board, consoleProto) in boards)
        {
            if (!_prototype.TryIndex(consoleProto, out var consoleProtoData))
                continue;

            var button = new Button
            {
                HorizontalExpand = true,
                ToggleMode = false,
            };

            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            var view = new EntityPrototypeView
            {
                SetSize = new Vector2(32, 32),
                VerticalAlignment = VAlignment.Center,
                Stretch = SpriteView.StretchMode.Fill,
            };
            view.SetPrototype(consoleProto);
            box.AddChild(view);

            box.AddChild(new Label
            {
                Text = consoleProtoData.Name,
                VerticalAlignment = VAlignment.Center,
                HorizontalExpand = true,
            });

            button.AddChild(box);
            button.OnPressed += _ => OnBoardSelected?.Invoke(board);

            BoardsList.AddChild(button);
        }
    }
}
