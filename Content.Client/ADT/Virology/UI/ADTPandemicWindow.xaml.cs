using Content.Shared.ADT.Virology.Pandemic;
using Content.Shared.ADT.Virology.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using static Robust.Client.UserInterface.Controls.BoxContainer;

namespace Content.Client.ADT.Virology.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTPandemicWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    public event Action<int>? OnCreateCulture;
    public event Action<int>? OnCreateVaccine;
    public event Action<int>? OnPrintForm;
    public event Action<int>? OnRequestSymptoms;
    public event Action<int, string>? OnAddSymptom;
    public event Action<int, string>? OnRemoveSymptom;
    public event Action<int>? OnRenameDisease;

    public ADTPandemicWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    private string? GetSymptomTooltip(string id)
    {
        if (!_proto.TryIndex<ADTSymptomPrototype>(id, out var proto))
            return null;

        var parts = new List<string>();
        if (proto.Description is { } desc)
            parts.Add(Loc.GetString(desc));

        parts.Add(Loc.GetString("adt-pandemic-symptom-stats",
            ("level", proto.Level),
            ("stealth", proto.Stealth),
            ("resistance", proto.Resistance),
            ("stageSpeed", proto.StageSpeed),
            ("transmittable", proto.Transmittable),
            ("severity", proto.Severity)));

        return string.Join("\n", parts);
    }

    public void UpdateState(ADTPandemicBoundUserInterfaceState state)
    {
        EjectButton.Disabled = !state.HasBeaker;
        ClearButton.Disabled = !state.HasBeaker;
        EjectButton.Visible = !state.ReadOnly;
        ClearButton.Visible = !state.ReadOnly;

        DnaLabel.Text = state.HasBeaker && state.BloodDna.Length > 0
            ? Loc.GetString("adt-pandemic-dna", ("dna", state.BloodDna))
            : Loc.GetString("adt-pandemic-no-sample");

        StatusLabel.Text = state.ErrorMessage != null
            ? Loc.GetString(state.ErrorMessage)
            : state.Busy
                ? Loc.GetString("adt-pandemic-busy")
                : string.Empty;

        DiseasesContainer.RemoveAllChildren();
        AntibodiesContainer.RemoveAllChildren();

        if (state.Diseases.Count == 0)
        {
            DiseasesContainer.AddChild(new Label
            {
                Text = Loc.GetString("adt-pandemic-no-diseases"),
                StyleClasses = { "LabelSubText" },
            });
        }

        foreach (var disease in state.Diseases)
        {
            DiseasesContainer.AddChild(BuildDiseaseEntry(disease, state));
        }

        if (state.Antibodies.Count == 0)
        {
            AntibodiesContainer.AddChild(new Label
            {
                Text = Loc.GetString("adt-pandemic-no-antibodies"),
                StyleClasses = { "LabelSubText" },
            });
        }

        foreach (var antibody in state.Antibodies)
        {
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 4,
            };

            row.AddChild(new Label
            {
                Text = antibody.Name,
                HorizontalExpand = true,
            });

            AntibodiesContainer.AddChild(row);

            if (state.ReadOnly)
                continue;

            var vaccineButton = new Button
            {
                Text = Loc.GetString("adt-pandemic-create-vaccine"),
                Disabled = state.Busy || !antibody.CanVaccine,
            };

            var index = antibody.Index;
            vaccineButton.OnPressed += _ => OnCreateVaccine?.Invoke(index);
            row.AddChild(vaccineButton);
        }
    }

    private BoxContainer BuildDiseaseEntry(ADTPandemicDiseaseInfo disease, ADTPandemicBoundUserInterfaceState state)
    {
        var box = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        var header = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        header.AddChild(new Label
        {
            Text = disease.Name,
            StyleClasses = { "LabelKeyText" },
            HorizontalExpand = true,
        });

        var index = disease.Index;

        if (disease.IsAdvance && !state.ReadOnly)
        {
            var renameButton = new Button { Text = Loc.GetString("adt-pandemic-rename") };
            renameButton.OnPressed += _ => OnRenameDisease?.Invoke(index);
            header.AddChild(renameButton);
        }

        if (!state.ReadOnly)
        {
            var cultureButton = new Button
            {
                Text = Loc.GetString("adt-pandemic-create-culture"),
                Disabled = state.Busy,
            };
            cultureButton.OnPressed += _ => OnCreateCulture?.Invoke(index);
            header.AddChild(cultureButton);

            var formButton = new Button { Text = Loc.GetString("adt-pandemic-print-form") };
            formButton.OnPressed += _ => OnPrintForm?.Invoke(index);
            header.AddChild(formButton);
        }

        box.AddChild(header);

        box.AddChild(new Label
        {
            Text = Loc.GetString("adt-pandemic-agent", ("agent", disease.Agent)),
            StyleClasses = { "LabelSubText" },
        });

        if (disease.Description.Length > 0)
        {
            box.AddChild(new Label
            {
                Text = disease.Description,
                StyleClasses = { "LabelSubText" },
            });
        }

        box.AddChild(new Label
        {
            Text = Loc.GetString("adt-pandemic-route", ("route", disease.Route)),
            StyleClasses = { "LabelSubText" },
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("adt-pandemic-cure", ("cure", disease.Cure)),
            StyleClasses = { "LabelSubText" },
        });

        box.AddChild(new Label
        {
            Text = Loc.GetString("adt-pandemic-antibodies",
                ("value", Loc.GetString(disease.CanImmunity ? "adt-pandemic-present" : "adt-pandemic-absent"))),
            StyleClasses = { "LabelSubText" },
        });

        if (!disease.IsAdvance)
            return box;

        var symptomsRow = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        symptomsRow.AddChild(new Label
        {
            Text = Loc.GetString("adt-pandemic-symptoms"),
            StyleClasses = { "LabelSubText" },
        });

        if (!state.ReadOnly)
        {
            var addButton = new Button { Text = Loc.GetString("adt-pandemic-add-symptom") };
            addButton.OnPressed += _ => OnRequestSymptoms?.Invoke(index);
            symptomsRow.AddChild(addButton);
        }
        box.AddChild(symptomsRow);

        foreach (var (id, name) in disease.Symptoms)
        {
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 4,
            };

            row.AddChild(new Label
            {
                Text = name,
                HorizontalExpand = true,
                ToolTip = GetSymptomTooltip(id),
            });
            box.AddChild(row);

            if (state.ReadOnly)
                continue;

            var removeButton = new Button
            {
                Text = Loc.GetString("adt-pandemic-remove-symptom"),
                Disabled = disease.Symptoms.Count <= 1,
            };

            var symptomId = id;
            removeButton.OnPressed += _ => OnRemoveSymptom?.Invoke(index, symptomId);
            row.AddChild(removeButton);
        }

        if (state.ReadOnly || state.CandidatesForDisease != index || state.SymptomCandidates.Count == 0)
            return box;

        box.AddChild(new Label
        {
            Text = Loc.GetString("adt-pandemic-choose-symptom"),
            StyleClasses = { "LabelSubText" },
        });

        foreach (var (id, name) in state.SymptomCandidates)
        {
            var candidateButton = new Button { Text = name, ToolTip = GetSymptomTooltip(id) };
            var symptomId = id;
            candidateButton.OnPressed += _ => OnAddSymptom?.Invoke(index, symptomId);
            box.AddChild(candidateButton);
        }

        return box;
    }
}
