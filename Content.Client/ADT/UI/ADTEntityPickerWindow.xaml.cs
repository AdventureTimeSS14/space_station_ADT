using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.ADT.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.ADT.UI;

[GenerateTypedNameReferences]
public sealed partial class ADTEntityPickerWindow : FancyWindow
{
    public event Action<NetEntity>? OnEntrySelected;

    public ADTEntityPickerWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetText(string title, string hint)
    {
        Title = title;
        Hint.Text = hint;
    }

    public void SetEntries(List<ADTEntityPickerEntry> entries)
    {
        EntryList.RemoveAllChildren();

        foreach (var entry in entries)
        {
            EntryList.AddChild(BuildRow(entry));
        }
    }

    private Control BuildRow(ADTEntityPickerEntry entry)
    {
        var button = new Button
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 4),
            MinHeight = 40,
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            // Let the click through to the button underneath.
            MouseFilter = MouseFilterMode.Ignore,
        };

        if (entry.Proto is { } proto)
        {
            var view = new EntityPrototypeView
            {
                SetSize = new Vector2(32, 32),
                Stretch = SpriteView.StretchMode.Fill,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 6, 0),
            };
            view.SetPrototype(proto);
            row.AddChild(view);
        }

        row.AddChild(new Label
        {
            Text = entry.Name,
            VerticalAlignment = VAlignment.Center,
        });

        button.AddChild(row);

        var target = entry.Entity;
        button.OnPressed += _ => OnEntrySelected?.Invoke(target);

        return button;
    }
}
