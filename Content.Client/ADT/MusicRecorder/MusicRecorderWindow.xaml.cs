using Content.Shared.ADT.MusicRecorder;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client.ADT.MusicRecorder;

[GenerateTypedNameReferences]
public sealed partial class MusicRecorderWindow : FancyWindow
{
    public event Action? OnSlotPressed;
    public event Action<string>? OnRename;
    public event Action? OnUpload;
    public event Action<string>? OnRemoveTrack;

    private bool _editing;
    private bool _uploading;
    private MusicRecorderBoundUserInterfaceState? _state;

    public MusicRecorderWindow()
    {
        RobustXamlLoader.Load(this);

        SlotButton.OnPressed += _ => OnSlotPressed?.Invoke();
        RenameButton.OnPressed += _ => SubmitName();
        UploadButton.OnPressed += _ => OnUpload?.Invoke();
        NameEdit.OnTextEntered += _ => SubmitName();
        NameEdit.OnFocusEnter += _ => _editing = true;
        NameEdit.OnFocusExit += _ =>
        {
            _editing = false;
            ApplyState(_state);
        };
    }

    public void UpdateState(MusicRecorderBoundUserInterfaceState state)
    {
        _state = state;
        ApplyState(state);
    }

    public void SetUploading(bool uploading)
    {
        _uploading = uploading;
        ApplyState(_state);
    }

    public void SetStatus(string text, bool error = false)
    {
        StatusLabel.Text = text;
        StatusLabel.FontColorOverride = error ? Color.OrangeRed : Color.FromHex("#d5dde8");
    }

    private void ApplyState(MusicRecorderBoundUserInterfaceState? state)
    {
        var hasCassette = state?.HasCassette ?? false;
        var tracks = state?.Tracks ?? Array.Empty<MusicCassetteTrack>();

        CassetteNameLabel.Text = hasCassette
            ? state?.CassetteName ?? string.Empty
            : Loc.GetString("music-recorder-no-cassette");

        CassetteMetaLabel.Text = hasCassette
            ? Loc.GetString("music-recorder-track-count", ("count", tracks.Length), ("max", MusicCassetteComponent.MaxTracks))
            : Loc.GetString("music-recorder-insert-hint");

        SlotButton.Text = hasCassette
            ? Loc.GetString("music-recorder-eject")
            : Loc.GetString("music-recorder-insert");

        NameEdit.Editable = hasCassette && !_uploading;
        RenameButton.Disabled = !hasCassette || _uploading;
        UploadButton.Disabled = !hasCassette || _uploading || tracks.Length >= MusicCassetteComponent.MaxTracks;

        if (!_editing || !hasCassette)
            NameEdit.Text = hasCassette ? state?.CassetteName ?? string.Empty : string.Empty;

        RebuildTracks(hasCassette, tracks);
    }

    private void RebuildTracks(bool hasCassette, MusicCassetteTrack[] tracks)
    {
        TrackList.RemoveAllChildren();

        if (!hasCassette)
        {
            TrackList.AddChild(new Label
            {
                Text = Loc.GetString("music-recorder-no-cassette"),
                FontColorOverride = Color.FromHex("#9aa4b2"),
            });
            return;
        }

        if (tracks.Length == 0)
        {
            TrackList.AddChild(new Label
            {
                Text = Loc.GetString("music-recorder-no-tracks"),
                FontColorOverride = Color.FromHex("#9aa4b2"),
            });
            return;
        }

        foreach (var track in tracks)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
            };

            row.AddChild(new Label
            {
                Text = Loc.GetString("music-recorder-track-entry",
                    ("name", track.Name),
                    ("time", TimeSpan.FromSeconds(track.Duration).ToString(@"m\:ss"))),
                HorizontalExpand = true,
                ClipText = true,
            });

            var remove = new Button
            {
                Text = Loc.GetString("music-recorder-remove"),
                Disabled = _uploading,
                MinWidth = 36,
            };
            var trackId = track.Id;
            remove.OnPressed += _ => OnRemoveTrack?.Invoke(trackId);
            row.AddChild(remove);
            TrackList.AddChild(row);
        }
    }

    private void SubmitName()
    {
        if (_state is not { HasCassette: true } || _uploading)
            return;

        OnRename?.Invoke(NameEdit.Text);
    }
}
