namespace Content.Client.ADT.TTS.UI;

[GenerateTypedNameReferences]
public sealed partial class TTSOptionsTab : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private static readonly ResPath KeysRsi = new("Objects/Devices/encryption_keys.rsi");
    private static readonly SpriteSpecifier CardBackground = new SpriteSpecifier.Rsi(KeysRsi, "crypt_gray");

    private const int IconSize = 32;

    private readonly Dictionary<string, Slider> _channelSliders = new();

    public TTSOptionsTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Control.AddOptionPercentSlider(
            ADTTTSCVars.TTSVolume,
            SliderVolumeTts,
            scale: ContentAudioSystem.TtsMultiplier);

        Control.AddOptionDropDown<bool>(
            ADTCCVars.ReplaceTTSWithBarks,
            DropDownBarksOrTTS,
            [
                new OptionDropDownCVar<bool>.ValueOption(true, Loc.GetString("ui-options-barks-speech")),
                new OptionDropDownCVar<bool>.ValueOption(false, Loc.GetString("ui-options-tts-speech")),
            ]);

        Control.AddOptionCheckBox(ADTTTSCVars.TTSRadioClientEnabled, RadioEnabledCheckBox);

        Control.AddOptionPercentSlider(
            ADTTTSCVars.TTSRadioVolume,
            SliderRadioVolume,
            scale: ContentAudioSystem.TtsMultiplier);

        BuildChannelList();

        Control.AddOption(new OptionRadioChannelVolumes(Control, _cfg, _channelSliders));
        Control.Initialize();
    }

    private void BuildChannelList()
    {
        var channels = _prototype.EnumeratePrototypes<RadioChannelPrototype>()
            .OrderBy(o => o.LocalizedName, StringComparer.CurrentCulture)
            .ThenBy(o => o.ID, StringComparer.Ordinal)
            .ToList();

        foreach (var channel in channels)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 1),
            };

            row.AddChild(BuildChannelIcon(channel));

            row.AddChild(new Label
            {
                Text = channel.LocalizedName,
                MinWidth = 200,
                VerticalAlignment = VAlignment.Center,
                FontColorOverride = channel.Color,
            });

            var slider = new Slider
            {
                MinValue = 0f,
                MaxValue = 1f,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };

            var valueLabel = new Label
            {
                MinWidth = 48,
                Align = Label.AlignMode.Right,
                Margin = new Thickness(8, 0, 4, 0),
                VerticalAlignment = VAlignment.Center,
            };

            slider.OnValueChanged += _ => valueLabel.Text = FormatPercent(slider.Value);
            valueLabel.Text = FormatPercent(slider.Value);

            row.AddChild(slider);
            row.AddChild(valueLabel);

            ChannelsContainer.AddChild(row);
            _channelSliders[channel.ID] = slider;
        }
    }

    private Control BuildChannelIcon(RadioChannelPrototype channel)
    {
        var stack = new Control
        {
            MinSize = new Vector2(IconSize, IconSize),
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(0, 0, 6, 0),
        };

        stack.AddChild(CreateIcon(CardBackground, null));

        var label = _prototype.TryIndex<TTSRadioChannelPrototype>(channel.ID, out var settings)
            ? settings.Icon
            : null;

        stack.AddChild(CreateIcon(label ?? CardBackground, label == null ? channel.Color : null));

        return stack;
    }

    private static AnimatedTextureRect CreateIcon(SpriteSpecifier specifier, Color? modulate)
    {
        var icon = new AnimatedTextureRect();
        icon.SetFromSpriteSpecifier(specifier);
        icon.DisplayRect.Stretch = TextureRect.StretchMode.KeepAspectCentered;
        icon.DisplayRect.ModulateSelfOverride = modulate;
        return icon;
    }

    private static string FormatPercent(float value)
    {
        return Loc.GetString("ui-options-value-percent", ("value", value));
    }
}

public sealed class OptionRadioChannelVolumes : BaseOptionCVar<string>
{
    private readonly Dictionary<string, Slider> _sliders;

    protected override string Value
    {
        get => TTSRadioVolumes.Serialize(
            _sliders.Select(pair => new KeyValuePair<string, float>(pair.Key, pair.Value.Value)));
        set
        {
            var volumes = TTSRadioVolumes.Parse(value);

            foreach (var (channel, slider) in _sliders)
            {
                slider.Value = volumes.GetValueOrDefault(channel, TTSRadioVolumes.FullVolume);
            }
        }
    }

    public OptionRadioChannelVolumes(
        OptionsTabControlRow controller,
        IConfigurationManager cfg,
        Dictionary<string, Slider> sliders)
        : base(controller, cfg, ADTTTSCVars.TTSRadioChannelVolumes)
    {
        _sliders = sliders;

        foreach (var slider in _sliders.Values)
        {
            slider.OnValueChanged += _ => ValueChanged();
        }
    }
}
